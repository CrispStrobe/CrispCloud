String archiveBatchIntegrityText(
  BuildContext context,
  String key, [
  List<Object> values = const [],
]) {
  final language = Localizations.maybeLocaleOf(context)?.languageCode ?? 'en';
  final index = const [
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ].indexOf(language);
  var value = index < 0
      ? key
      : _messages[key]?[index] ?? archiveIntegrityText(context, key);
  for (var i = 0; i < values.length; i++) {
    value = value.replaceAll('{$i}', '${values[i]}');
  }
  return value;
}

