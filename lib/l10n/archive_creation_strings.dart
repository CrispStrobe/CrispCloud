/// Small, independently maintained catalog for the archive creation workflow.
String archiveCreationText(
  BuildContext context,
  String key, [
  List<Object?> values = const [],
]) {
  final language = Localizations.maybeLocaleOf(context)?.languageCode ?? 'en';
  final index = const [
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ].indexOf(language);
  var value = index < 0 ? key : (_messages[key]?[index] ?? key);
  for (var i = 0; i < values.length; i++) {
    value = value.replaceAll('{$i}', '${values[i]}');
  }
  return value;
}

String archiveCreationError(BuildContext context, Object error) {
  if (error is! ArchiveCreationException) return error.toString();
  final key = switch (error.code) {
    ArchiveCreationError.invalidName => 'Enter a filename with the selected archive extension and no path separators.',
    ArchiveCreationError.unsupportedOptions =>
      'These options are not supported by the selected archive format.',
    ArchiveCreationError.sourceChanged => 'A selected file or folder changed. Close this dialog, refresh, and select it again.',
    ArchiveCreationError.sourceUnavailable =>
      'The original storage is no longer available.',
    ArchiveCreationError.emptySelection =>
      'Select at least one file or folder.',
    ArchiveCreationError.unsupportedEntry => 'This selection contains an unavailable file, symbolic link, or unsupported entry.',
    ArchiveCreationError.duplicateName =>
      'Two selected items would have the same name in the archive.',
    ArchiveCreationError.tooLarge =>
      'Archive creation exceeds its size or entry limit.',
    ArchiveCreationError.destinationExists =>
      'The output already exists. Choose another archive name.',
    ArchiveCreationError.invalidDestination =>
      'Choose an existing destination outside the selected folders.',
    ArchiveCreationError.verificationFailed =>
      'Archive verification failed. No archive was published.',
    ArchiveCreationError.cancelled =>
      'Archive creation cancelled. No archive was published.',
  };
  final message = archiveCreationText(context, key);
  return error.path == null ? message : '$message\n${error.path}';
}

