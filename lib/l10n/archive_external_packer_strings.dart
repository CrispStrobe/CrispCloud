String archiveExternalPackerText(
  BuildContext context,
  String key, [
  List<Object?> values = const [],
]) {
  final language = Localizations.maybeLocaleOf(context)?.languageCode ?? 'en';
  final index = const [
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ].indexOf(language);
  var value = index < 0
      ? key
      : (_messages[key]?[index] ?? archiveCreationText(context, key));
  for (var i = 0; i < values.length; i++) {
    value = value.replaceAll('{$i}', '${values[i]}');
  }
  return value;
}

String archiveExternalPackerError(BuildContext context, Object error) {
  if (error is ArchiveCreationException) {
    return archiveCreationError(context, error);
  }
  final key = error is ArchiveExternalPackerException
      ? switch (error.failure) {
          ArchiveExternalPackerFailure.unsupportedPlatform => 'External tools are available in desktop builds that permit local processes.',
          ArchiveExternalPackerFailure.invalidConfiguration =>
            'Enter the full path to a supported command-line executable.',
          ArchiveExternalPackerFailure.unavailable => 'The selected executable is unavailable or is not a supported tool version.',
          ArchiveExternalPackerFailure.changed => 'The tool or its private input changed. Check the tool and try again.',
          ArchiveExternalPackerFailure.unsupportedFormat =>
            'This tool cannot create the selected archive format.',
          ArchiveExternalPackerFailure.unsupportedOptions =>
            'These options are not supported by the selected archive format.',
          ArchiveExternalPackerFailure.unsupportedEntry => 'This selection contains names, sizes or metadata the tool cannot preserve.',
          ArchiveExternalPackerFailure.capabilityCheckFailed => 'The tool did not pass content and metadata verification. Choose another executable.',
          ArchiveExternalPackerFailure.timeout =>
            'The external tool timed out. No archive was published.',
          ArchiveExternalPackerFailure.cancelled =>
            'Archive creation cancelled. No archive was published.',
          ArchiveExternalPackerFailure.outputTooLarge =>
            'Archive creation exceeds its size or entry limit.',
          ArchiveExternalPackerFailure.invalidOutput => 'The tool output did not match the selection. No archive was published.',
          ArchiveExternalPackerFailure.cleanupFailed => 'Private temporary files were retained because cleanup could not be confirmed. No archive was published.',
          ArchiveExternalPackerFailure.saveFailed =>
            'Tool settings could not be saved on this device.',
          ArchiveExternalPackerFailure.processFailed =>
            'The external tool failed. No archive was published.',
        }
      : 'The external tool failed. No archive was published.';
  return archiveExternalPackerText(context, key);
}

