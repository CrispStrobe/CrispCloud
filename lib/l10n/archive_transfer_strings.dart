String archiveTransferText(
  BuildContext context,
  String key, [
  List<Object?> values = const [],
]) {
  final language = Localizations.maybeLocaleOf(context)?.languageCode ?? 'en';
  final index = const [
    'en',
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ].indexOf(language);
  final messages = archiveTransferMessages[key];
  var text = messages == null ? key : messages[index < 0 ? 0 : index];
  for (var i = 0; i < values.length; i++) {
    text = text.replaceAll('{$i}', '${values[i]}');
  }
  return text;
}

