import 'package:flutter/widgets.dart';

import '../models/command_entry.dart';

class CommandEntryStrings {
  CommandEntryStrings(BuildContext context)
    : language = Localizations.maybeLocaleOf(context)?.languageCode ?? 'en';
  @visibleForTesting
  const CommandEntryStrings.forLanguage(this.language);
  final String language;
  static const languages = [
    'en',
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ];

  String text(String key, [Map<String, Object> values = const {}]) {
    final index = languages.indexOf(language);
    var value = _values[key]![index < 0 ? 0 : index];
    for (final entry in values.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

  String failure(Object error) => text(
    error is CommandEntryException ? error.failure.name : 'launchFailed',
  );

  @visibleForTesting
  static Iterable<String> get keys => _values.keys;
}

