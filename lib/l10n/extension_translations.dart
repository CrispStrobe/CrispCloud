String extensionText(
  String language,
  String english, [
  List<Object?> arguments = const [],
]) {
  final index = CommanderStrings.supportedLanguageCodes.indexOf(language) - 1;
  final translations = extensionTranslations[english];
  if (index < 0 || translations == null) {
    return CommanderStrings.forLanguage(language, english, arguments);
  }
  return translations[index].replaceAllMapped(RegExp(r'\{(\d+)\}'), (match) {
    final argument = int.parse(match[1]!);
    return argument < arguments.length
        ? '${arguments[argument] ?? ''}'
        : match[0]!;
  });
}

extension ExtensionTranslations on BuildContext {
  String extensionTr(String english, [List<Object?> arguments = const []]) =>
      extensionText(
        Localizations.maybeLocaleOf(this)?.languageCode ?? 'en',
        english,
        arguments,
      );
}
