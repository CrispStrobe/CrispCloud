  const ExternalEditingStrings(this.context);
  final BuildContext context;
  static const languages = [
    'en',
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ];
  String text(String key, [List<Object?> values = const []]) {
    final index = languages.indexOf(
      Localizations.maybeLocaleOf(context)?.languageCode ?? 'en',
    );
    var result = messages[key]![index < 0 ? 0 : index];
    for (var i = 0; i < values.length; i++) {
      result = result.replaceAll('{$i}', '${values[i]}');
    }
    return result;
  }

  String failure(Object error) {
    final failure = switch (error) {
      ExternalEditException() => error.failure,
      FilePublicationException() => switch (error.failure) {
        FilePublicationFailure.conflict => ExternalEditFailure.conflict,
        FilePublicationFailure.uncertain => ExternalEditFailure.uncertain,
        FilePublicationFailure.changed => ExternalEditFailure.sourceChanged,
        FilePublicationFailure.unsupported => ExternalEditFailure.unsupported,
        FilePublicationFailure.invalid => ExternalEditFailure.invalid,
        FilePublicationFailure.unavailable => ExternalEditFailure.uploadFailed,
      },
      PrivateStageException() => switch (error.failure) {
        PrivateStageFailure.tooLarge => ExternalEditFailure.tooLarge,
        PrivateStageFailure.changed => ExternalEditFailure.localChanged,
        PrivateStageFailure.busy => ExternalEditFailure.busy,
        PrivateStageFailure.unsupported => ExternalEditFailure.unsupported,
        PrivateStageFailure.invalid || PrivateStageFailure.unavailable =>
          ExternalEditFailure.retainedUnavailable,
      },
      _ => ExternalEditFailure.saveFailed,
    };
    return text('failure_${failure.name}');
  }

  String phase(ExternalEditPhase value) => text('phase_${value.name}');

