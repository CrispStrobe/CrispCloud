  static final catalog = <String, Map<String, String>>{
    for (var i = 0; i < languages.length; i++)
      languages[i]: {for (final row in rows) row.first: row[i]},
  };

  static String forLanguage(String code, String english) =>
      catalog[code]?[english] ??
      ImageEditorStrings.catalog[code]?[english] ??
      catalog['en']?[english] ??
      ImageEditorStrings.catalog['en']?[english] ??
      english;
}

extension HexEditorTranslation on BuildContext {
  String hexTr(String english) => HexEditorStrings.forLanguage(
    Localizations.localeOf(this).languageCode,
    english,
  );
}
