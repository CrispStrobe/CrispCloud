  static String translate(BuildContext context, String english) {
    final String code = Localizations.localeOf(context).languageCode;
    final String? recovery = OfficeRecoveryStrings.lookup(code, english);
    if (recovery != null) return recovery;
    final Map<String, String>? map = _translations[code];
    if (map == null) return english;
    final String normalized = english.replaceAll('…', '...');
    final String? exact = map[english] ?? map[normalized];
    if (exact != null) return exact;
    // Ribbon labels use sentence case while menu labels use title case.
    final String lower = normalized.toLowerCase();
    for (final MapEntry<String, String> entry in map.entries) {
      if (entry.key.toLowerCase() == lower) return entry.value;
    }
    return OfficeRibbonCommonStrings.lookup(code, english) ??
        OfficeFallbackStrings.lookup(code, english) ?? english;
  }

