    final map = translations[language];
    if (map == null) return null;
    final normalized = english.replaceAll('…', '...');
    for (final entry in map.entries) {
      if (entry.key.replaceAll('…', '...').toLowerCase() ==
          normalized.toLowerCase()) {
        return entry.value;
      }
    }
    return null;
  }

