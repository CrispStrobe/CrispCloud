String veraCryptText(
  BuildContext context,
  String english, [
  List<Object> values = const [],
]) {
  final language = Localizations.maybeLocaleOf(context)?.languageCode ?? 'en';
  final index = const [
    'de',
    'fr',
    'es',
    'pt',
    'zh',
    'ja',
    'ko',
    'ar',
  ].indexOf(language);
  var text = index < 0
      ? english
      : veraCryptTranslations[english]?[index] ?? context.commanderTr(english);
  for (var i = 0; i < values.length; i++) {
    text = text.replaceAll('{$i}', '${values[i]}');
  }
  return text;
}

