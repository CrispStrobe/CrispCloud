import 'package:flutter/services.dart';
import 'package:xterm2/xterm.dart';

import '../services/terminal_user_input.dart';

/// An exact logical key and modifier combination, independent of key labels.
class TerminalKeyChord {
  TerminalKeyChord({
    required this.keyId,
    this.ctrl = false,
    this.alt = false,
    this.shift = false,
    this.meta = false,
  }) {
    if (!isBindableKey(LogicalKeyboardKey(keyId)) ||
        (keyId <= 0x10ffff && !ctrl && !alt && !meta)) {
      throw const FormatException('Invalid terminal shortcut');
    }
  }

  final int keyId;
  final bool ctrl;
  final bool alt;
  final bool shift;
  final bool meta;

  static bool isBindableKey(LogicalKeyboardKey key) {
    final id = key.keyId;
    if (id <= 0 ||
        id > 0xffffffffff ||
        (id > 0x10ffff && id < 0x100000000) ||
        (id >= 0xd800 && id <= 0xdfff) ||
        key.isAutogenerated ||
        _modifiers.contains(key)) {
      return false;
    }
    final label = key.keyLabel;
    return label.isNotEmpty && !LogicalKeyboardKey.isControlCharacter(label);
  }

  static const _modifiers = [
    LogicalKeyboardKey.control,
    LogicalKeyboardKey.controlLeft,
    LogicalKeyboardKey.controlRight,
    LogicalKeyboardKey.shift,
    LogicalKeyboardKey.shiftLeft,
    LogicalKeyboardKey.shiftRight,
    LogicalKeyboardKey.alt,
    LogicalKeyboardKey.altLeft,
    LogicalKeyboardKey.altRight,
    LogicalKeyboardKey.meta,
    LogicalKeyboardKey.metaLeft,
    LogicalKeyboardKey.metaRight,
    LogicalKeyboardKey.capsLock,
    LogicalKeyboardKey.numLock,
    LogicalKeyboardKey.fn,
  ];

  bool matches(
    KeyEvent event, {
    required bool ctrl,
    required bool alt,
    required bool shift,
    required bool meta,
  }) =>
      event.logicalKey.keyId == keyId &&
      this.ctrl == ctrl &&
      this.alt == alt &&
      this.shift == shift &&
      this.meta == meta;

  /// Workspace navigation, clipboard, search, zoom and interrupt keep priority.
  /// The user's separately configurable terminal-toggle shortcut is checked by
  /// the editor and panel against the live app shortcut service.
  bool isReserved({required bool apple}) {
    final key = LogicalKeyboardKey(keyId);
    final arrow = const [
      LogicalKeyboardKey.arrowLeft,
      LogicalKeyboardKey.arrowRight,
      LogicalKeyboardKey.arrowUp,
      LogicalKeyboardKey.arrowDown,
    ].contains(key);
    if (ctrl && !alt && !meta && key == LogicalKeyboardKey.tab) return true;
    if (ctrl && !alt && !shift && !meta && key == LogicalKeyboardKey.keyC) {
      return true;
    }
    if (arrow &&
        alt &&
        !shift &&
        ((ctrl && !meta) || (apple && meta && !ctrl))) {
      return true;
    }
    if (!alt && (apple ? meta && !ctrl : ctrl && shift && !meta)) {
      if (const [
        LogicalKeyboardKey.keyT,
        LogicalKeyboardKey.keyW,
        LogicalKeyboardKey.keyD,
        LogicalKeyboardKey.keyC,
        LogicalKeyboardKey.keyV,
        LogicalKeyboardKey.keyF,
        LogicalKeyboardKey.equal,
        LogicalKeyboardKey.add,
        LogicalKeyboardKey.numpadAdd,
        LogicalKeyboardKey.minus,
        LogicalKeyboardKey.numpadSubtract,
        LogicalKeyboardKey.digit0,
        LogicalKeyboardKey.numpad0,
        LogicalKeyboardKey.bracketLeft,
        LogicalKeyboardKey.bracketRight,
      ].contains(key)) {
        return true;
      }
      if (!apple && key == LogicalKeyboardKey.keyE) return true;
      if (shift &&
          (key == LogicalKeyboardKey.enter ||
              key == LogicalKeyboardKey.arrowUp ||
              key == LogicalKeyboardKey.arrowDown)) {
        return true;
      }
    }
    // Xterm's standard alternative clipboard chords remain available.
    if (key == LogicalKeyboardKey.insert &&
        !alt &&
        !meta &&
        ((shift && !ctrl) || (ctrl && !shift))) {
      return true;
    }
    return false;
  }

  String get storageId =>
      '$keyId:${ctrl ? 1 : 0}${alt ? 1 : 0}'
      '${shift ? 1 : 0}${meta ? 1 : 0}';

  String get label {
    final key = LogicalKeyboardKey(keyId);
    return [
      if (ctrl) 'Ctrl',
      if (alt) 'Alt',
      if (shift) 'Shift',
      if (meta) 'Meta',
      key.keyLabel == ' ' ? 'Space' : key.keyLabel,
    ].join('+');
  }

  Map<String, Object?> toJson() => {
    'keyId': keyId,
    'ctrl': ctrl,
    'alt': alt,
    'shift': shift,
    'meta': meta,
  };

  factory TerminalKeyChord.fromJson(Map<String, dynamic> value) {
    if (value['keyId'] is! int ||
        ['ctrl', 'alt', 'shift', 'meta'].any((key) => value[key] is! bool)) {
      throw const FormatException('Invalid terminal shortcut');
    }
    return TerminalKeyChord(
      keyId: value['keyId'] as int,
      ctrl: value['ctrl'] as bool,
      alt: value['alt'] as bool,
      shift: value['shift'] as bool,
      meta: value['meta'] as bool,
    );
  }

  @override
  bool operator ==(Object other) =>
      other is TerminalKeyChord &&
      other.keyId == keyId &&
      other.ctrl == ctrl &&
      other.alt == alt &&
      other.shift == shift &&
      other.meta == meta;

  @override
  int get hashCode => Object.hash(keyId, ctrl, alt, shift, meta);
}

enum TerminalKeyBindingAction { text, key }

/// Explicit local keyboard mappings. Nothing can be triggered by shell output.
class TerminalKeyBinding {
  TerminalKeyBinding({
    required this.chord,
    required this.action,
    this.enabled = true,
    this.text,
    this.key,
    this.ctrl = false,
    this.alt = false,
    this.shift = false,
    this.meta = false,
  }) {
    if (action == TerminalKeyBindingAction.text) {
      if (!isValidText(text ?? '') ||
          key != null ||
          ctrl ||
          alt ||
          shift ||
          meta) {
        throw const FormatException('Invalid terminal text mapping');
      }
    } else if (text != null || key == null || !supportedKeys.contains(key)) {
      throw const FormatException('Invalid terminal key mapping');
    }
  }

  static const maximumTextLength = 4096;
  static final _unsafeText = RegExp(r'[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f]');
  static bool isValidText(String value) =>
      value.isNotEmpty &&
      value.length <= maximumTextLength &&
      !_unsafeText.hasMatch(value);

  static final List<TerminalKey> supportedKeys = List.unmodifiable(
    TerminalKey.values.where(
      (key) =>
          RegExp(r'^(key[A-Z]|digit[0-9]|f([1-9]|1[0-9]|2[0-4]))$')
              .hasMatch(key.name) ||
          const {
            TerminalKey.enter,
            TerminalKey.escape,
            TerminalKey.backspace,
            TerminalKey.tab,
            TerminalKey.space,
            TerminalKey.insert,
            TerminalKey.delete,
            TerminalKey.home,
            TerminalKey.end,
            TerminalKey.pageUp,
            TerminalKey.pageDown,
            TerminalKey.arrowUp,
            TerminalKey.arrowDown,
            TerminalKey.arrowLeft,
            TerminalKey.arrowRight,
            TerminalKey.minus,
            TerminalKey.equal,
            TerminalKey.bracketLeft,
            TerminalKey.bracketRight,
            TerminalKey.backslash,
            TerminalKey.semicolon,
            TerminalKey.quote,
            TerminalKey.backquote,
            TerminalKey.comma,
            TerminalKey.period,
            TerminalKey.slash,
          }.contains(key),
    ),
  );

  final TerminalKeyChord chord;
  final TerminalKeyBindingAction action;
  final bool enabled;
  final String? text;
  final TerminalKey? key;
  final bool ctrl;
  final bool alt;
  final bool shift;
  final bool meta;

  TerminalKeyBinding copyWith({TerminalKeyChord? chord, bool? enabled}) =>
      TerminalKeyBinding(
        chord: chord ?? this.chord,
        action: action,
        enabled: enabled ?? this.enabled,
        text: text,
        key: key,
        ctrl: ctrl,
        alt: alt,
        shift: shift,
        meta: meta,
      );

  TerminalUserInput get input => action == TerminalKeyBindingAction.text
      ? TerminalUserInput.text(text!)
      : TerminalUserInput.keyTap(
          key!,
          ctrl: ctrl,
          alt: alt,
          shift: shift,
          superKey: meta,
          text: _keyText(key!, shift),
        );

  static String keyLabel(TerminalKey key) {
    if (key.name.startsWith('key')) return key.name.substring(3);
    if (key.name.startsWith('digit')) return key.name.substring(5);
    if (key.name.startsWith('f') &&
        int.tryParse(key.name.substring(1)) != null) {
      return key.name.toUpperCase();
    }
    return key.name
        .replaceAllMapped(RegExp(r'[A-Z]'), (m) => ' ${m[0]}')
        .replaceFirstMapped(RegExp(r'^.'), (m) => m[0]!.toUpperCase());
  }

  String get keyDescription => [
    if (ctrl) 'Ctrl',
    if (alt) 'Alt',
    if (shift) 'Shift',
    if (meta) 'Meta',
    if (key != null) keyLabel(key!),
  ].join('+');

  static String? _keyText(TerminalKey key, bool shift) {
    final name = key.name;
    if (RegExp(r'^key[A-Z]$').hasMatch(name)) {
      return shift ? name.substring(3) : name.substring(3).toLowerCase();
    }
    if (name.startsWith('digit')) {
      final digit = int.parse(name.substring(5));
      return shift ? ')!@#\$%^&*('[digit] : '$digit';
    }
    const punctuation = {
      TerminalKey.space: (' ', ' '),
      TerminalKey.minus: ('-', '_'),
      TerminalKey.equal: ('=', '+'),
      TerminalKey.bracketLeft: ('[', '{'),
      TerminalKey.bracketRight: (']', '}'),
      TerminalKey.backslash: ('\\', '|'),
      TerminalKey.semicolon: (';', ':'),
      TerminalKey.quote: ("'", '"'),
      TerminalKey.backquote: ('`', '~'),
      TerminalKey.comma: (',', '<'),
      TerminalKey.period: ('.', '>'),
      TerminalKey.slash: ('/', '?'),
    };
    final pair = punctuation[key];
    return pair == null
        ? null
        : shift
        ? pair.$2
        : pair.$1;
  }

  Map<String, Object?> toJson() => {
    'chord': chord.toJson(),
    'enabled': enabled,
    'action': {
      'kind': action.name,
      if (action == TerminalKeyBindingAction.text) 'text': text,
      if (action == TerminalKeyBindingAction.key) ...{
        'key': key!.name,
        'ctrl': ctrl,
        'alt': alt,
        'shift': shift,
        'meta': meta,
      },
    },
  };

  factory TerminalKeyBinding.fromJson(Map<String, dynamic> value) {
    final chord = value['chord'];
    final enabled = value['enabled'];
    final action = value['action'];
    if (chord is! Map<String, dynamic> ||
        enabled is! bool ||
        action is! Map<String, dynamic>) {
      throw const FormatException('Invalid terminal key binding');
    }
    final parsedChord = TerminalKeyChord.fromJson(chord);
    if (action['kind'] == 'text' && action['text'] is String) {
      return TerminalKeyBinding(
        chord: parsedChord,
        enabled: enabled,
        action: TerminalKeyBindingAction.text,
        text: action['text'] as String,
      );
    }
    if (action['kind'] != 'key' ||
        action['key'] is! String ||
        ['ctrl', 'alt', 'shift', 'meta'].any((key) => action[key] is! bool)) {
      throw const FormatException('Invalid terminal key binding action');
    }
    final keys = supportedKeys.where((key) => key.name == action['key']);
    if (keys.isEmpty) throw const FormatException('Unsupported terminal key');
    return TerminalKeyBinding(
      chord: parsedChord,
      enabled: enabled,
      action: TerminalKeyBindingAction.key,
      key: keys.single,
      ctrl: action['ctrl'] as bool,
      alt: action['alt'] as bool,
      shift: action['shift'] as bool,
      meta: action['meta'] as bool,
    );
  }
}
