import 'dart:convert';
import 'dart:typed_data';

import 'archive_types.dart';
import 'archive_write_model.dart';

/// Finishes our own freshly generated, bounded ZIP, whose encoder writes Unix
/// permissions but labels regular entries as originating on MS-DOS. This is
/// not an existing-archive rewrite operation. The exact captured namespace,
/// permissions, local records and central bounds must agree before any change.
///
/// Only central-directory origin and file-type bits change. Compressed or AES
/// encrypted contents, authentication tags, timestamps and sizes stay intact.
/// The creator must still perform its complete independent readback afterward.
void finalizeCreatedZipMetadata(
  Uint8List bytes,
  List<ArchiveWriteEntry> entries,
) {
  const maximumBytes = 256 * 1024 * 1024;
  const maximumDirectoryBytes = 32 * 1024 * 1024;
  Never invalid() => throw const ArchiveViewException(
    'The generated ZIP metadata does not match its captured entries.',
  );
  if (bytes.length < 22 || bytes.length > maximumBytes) invalid();
  validateArchiveWriteEntries(entries);
  final data = ByteData.sublistView(bytes);
  int u16(int at) => data.getUint16(at, Endian.little);
  int u32(int at) => data.getUint32(at, Endian.little);
  int bounded64(int at) {
    // This output is below 256 MiB and has at most 200,000 entries. Reject a
    // nonzero high word without depending on 64-bit precision in JavaScript.
    if (u32(at + 4) != 0) invalid();
    return u32(at);
  }

  bool matches(int at, List<int> value) {
    if (at < 0 || at > bytes.length - value.length) return false;
    for (var index = 0; index < value.length; index++) {
      if (bytes[at + index] != value[index]) return false;
    }
    return true;
  }

  // This fresh creator never writes an archive comment or a prefixed stub.
  final eocd = bytes.length - 22;
  if (u32(eocd) != 0x06054b50 || u16(eocd + 20) != 0 || u16(eocd + 4) != 0) {
    invalid();
  }
  var count = u16(eocd + 10);
  var directoryBytes = u32(eocd + 12);
  var directoryStart = u32(eocd + 16);
  var directoryEnd = eocd;
  if (directoryBytes == 0xffffffff ||
      directoryStart == 0xffffffff ||
      u16(eocd + 6) == 0xffff) {
    // A large entry count uses ZIP64 even though every offset remains small.
    if (eocd < 76 ||
        u16(eocd + 6) != 0xffff ||
        u16(eocd + 8) != 0xffff ||
        count != 0xffff ||
        directoryBytes != 0xffffffff ||
        directoryStart != 0xffffffff) {
      invalid();
    }
    final locator = eocd - 20;
    if (u32(locator) != 0x07064b50 ||
        u32(locator + 4) != 0 ||
        u32(locator + 16) != 1) {
      invalid();
    }
    final end64 = bounded64(locator + 8);
    if (end64 < 0 ||
        end64 + 56 != locator ||
        u32(end64) != 0x06064b50 ||
        bounded64(end64 + 4) != 44 ||
        u32(end64 + 16) != 0 ||
        u32(end64 + 20) != 0) {
      invalid();
    }
    count = bounded64(end64 + 32);
    if (bounded64(end64 + 24) != count) invalid();
    directoryBytes = bounded64(end64 + 40);
    directoryStart = bounded64(end64 + 48);
    directoryEnd = end64;
  } else if (u16(eocd + 6) != 0 || u16(eocd + 8) != count) {
    invalid();
  }
  if (count != entries.length ||
      directoryBytes > maximumDirectoryBytes ||
      directoryStart > directoryEnd ||
      directoryBytes != directoryEnd - directoryStart) {
    invalid();
  }

  // Collect the exact two fields to update only after all entries validate.
  // Failure therefore leaves the generated bytes unchanged as well.
  final updates = Uint32List(count * 2);
  var central = directoryStart;
  var nextLocal = 0;
  for (var index = 0; index < count; index++) {
    if (central > directoryEnd - 46 || u32(central) != 0x02014b50) invalid();
    final entry = entries[index];
    final encoded = utf8.encode('${entry.path}${entry.isDirectory ? '/' : ''}');
    final flags = u16(central + 8);
    final method = u16(central + 10);
    final crc = u32(central + 16);
    final compressed = u32(central + 20);
    final size = u32(central + 24);
    final nameBytes = u16(central + 28);
    final extraBytes = u16(central + 30);
    final commentBytes = u16(central + 32);
    final attributes = u32(central + 38);
    final local = u32(central + 42);
    final nextCentral = central + 46 + nameBytes + extraBytes + commentBytes;
    final host = bytes[central + 5];
    final type = entry.isDirectory ? 0x4000 : 0x8000;
    final encodedMode = attributes >> 16;
    final mode = entry.mode;
    if (nextCentral > directoryEnd ||
        nameBytes != encoded.length ||
        !matches(central + 46, encoded) ||
        commentBytes != 0 ||
        u16(central + 34) != 0 ||
        flags & 0x800 == 0 ||
        host != 0 && host != 3 ||
        size != entry.size ||
        compressed == 0xffffffff ||
        size == 0xffffffff ||
        local != nextLocal ||
        local > directoryStart - 30 ||
        (attributes & 0xffff) != (entry.isDirectory ? 0x10 : 0) ||
        encodedMode & 0xf000 != 0 && encodedMode & 0xf000 != type ||
        mode != null &&
            (mode < 0 ||
                mode > 0xffff ||
                mode & 0xc00 != 0 ||
                mode & 0xf000 != 0 && mode & 0xf000 != type ||
                encodedMode & 0xfff != mode & 0xfff)) {
      invalid();
    }

    if (u32(local) != 0x04034b50 ||
        u16(local + 6) != flags ||
        u16(local + 8) != method ||
        u16(local + 26) != nameBytes ||
        !matches(local + 30, encoded)) {
      invalid();
    }
    final payload = local + 30 + nameBytes + u16(local + 28);
    if (payload > directoryStart || compressed > directoryStart - payload) {
      invalid();
    }
    nextLocal = payload + compressed;
    if (flags & 8 != 0) {
      if (nextLocal > directoryStart - 16 ||
          u32(nextLocal) != 0x08074b50 ||
          u32(nextLocal + 4) != crc ||
          u32(nextLocal + 8) != compressed ||
          u32(nextLocal + 12) != size) {
        invalid();
      }
      nextLocal += 16;
    } else if (u32(local + 14) != crc ||
        u32(local + 18) != compressed ||
        u32(local + 22) != size) {
      invalid();
    }
    updates[index * 2] = central;
    updates[index * 2 + 1] = (encodedMode & 0xfff) | type;
    central = nextCentral;
  }
  if (central != directoryEnd || nextLocal != directoryStart) invalid();
  for (var index = 0; index < count; index++) {
    final at = updates[index * 2];
    bytes[at + 5] =
        3; // UNIX origin, matching the already captured permissions.
    data.setUint32(
      at + 38,
      (updates[index * 2 + 1] << 16) | (u32(at + 38) & 0xffff),
      Endian.little,
    );
  }
}
