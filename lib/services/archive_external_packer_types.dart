import 'package:path/path.dart' as p;

import 'archive_write_model.dart';

enum ArchiveExternalPackerKind { sevenZip, rar }

enum ArchiveExternalPackerFormat { zip, sevenZip, rar }

enum ArchiveExternalPackerCompression { store, normal, maximum }

extension ArchiveExternalPackerFormatDetails on ArchiveExternalPackerFormat {
  String get extension => switch (this) {
    ArchiveExternalPackerFormat.sevenZip => '.7z',
    _ => '.$name',
  };
  String get label => switch (this) {
    ArchiveExternalPackerFormat.sevenZip => '7z',
    ArchiveExternalPackerFormat.rar => 'RAR5',
    _ => 'ZIP',
  };
}

enum ArchiveExternalPackerFailure {
  unsupportedPlatform,
  invalidConfiguration,
  unavailable,
  changed,
  unsupportedFormat,
  unsupportedOptions,
  unsupportedEntry,
  capabilityCheckFailed,
  processFailed,
  timeout,
  cancelled,
  outputTooLarge,
  invalidOutput,
  cleanupFailed,
  saveFailed,
}

/// Errors deliberately exclude process logs, arguments and temporary paths.
class ArchiveExternalPackerException implements Exception {
  const ArchiveExternalPackerException(this.failure);
  final ArchiveExternalPackerFailure failure;
  @override
  String toString() => 'ArchiveExternalPackerException(${failure.name})';
}

/// A machine-local choice. Arguments are generated by a fixed adapter; users
/// cannot configure shell templates or inject extra packer switches.
class ArchiveExternalPackerConfiguration {
  ArchiveExternalPackerConfiguration({
    required this.platform,
    required this.kind,
    required this.executable,
  }) {
    validate();
  }
  final String platform;
  final ArchiveExternalPackerKind kind;
  final String executable;

  void validate() {
    final paths = platform == 'windows' ? p.windows : p.posix;
    final lower = executable.toLowerCase();
    if (!const {'linux', 'macos', 'windows'}.contains(platform) ||
        !paths.isAbsolute(executable) ||
        executable.length > 4096 ||
        RegExp(r'[\x00-\x1f\x7f]').hasMatch(executable) ||
        platform == 'windows' && !lower.endsWith('.exe') ||
        const ['.bat', '.cmd', '.ps1'].any(lower.endsWith)) {
      throw const ArchiveExternalPackerException(
        ArchiveExternalPackerFailure.invalidConfiguration,
      );
    }
  }

  Map<String, Object> toJson() => {
    'version': 1,
    'platform': platform,
    'kind': kind.name,
    'executable': executable,
  };

  factory ArchiveExternalPackerConfiguration.fromJson(Object? value) {
    if (value is! Map ||
        value.length != 4 ||
        value['version'] != 1 ||
        value['platform'] is! String ||
        value['kind'] is! String ||
        value['executable'] is! String) {
      throw const ArchiveExternalPackerException(
        ArchiveExternalPackerFailure.invalidConfiguration,
      );
    }
    final kind = ArchiveExternalPackerKind.values.where(
      (kind) => kind.name == value['kind'],
    );
    if (kind.length != 1) {
      throw const ArchiveExternalPackerException(
        ArchiveExternalPackerFailure.invalidConfiguration,
      );
    }
    return ArchiveExternalPackerConfiguration(
      platform: value['platform'] as String,
      kind: kind.single,
      executable: value['executable'] as String,
    );
  }
}

/// Captured executable evidence, rechecked immediately before each invocation.
/// This is not an atomic open-and-execute guarantee supplied by the OS.
class ArchiveExternalPackerIdentity {
  const ArchiveExternalPackerIdentity({
    required this.path,
    required this.length,
    required this.modified,
    required this.changed,
    required this.mode,
    required this.sha256,
  });
  final String path, sha256;
  final int length, mode;
  final DateTime modified, changed;

  @override
  bool operator ==(Object other) =>
      other is ArchiveExternalPackerIdentity &&
      path == other.path &&
      length == other.length &&
      modified == other.modified &&
      changed == other.changed &&
      mode == other.mode &&
      sha256 == other.sha256;
  @override
  int get hashCode =>
      Object.hash(path, length, modified, changed, mode, sha256);
}

/// A bounded 7z profile. A solid block can exceed its requested size only when
/// one member is larger; the independent reader still enforces its 64 MiB
/// decoded-folder limit before a candidate can be published.
class ArchiveExternalSevenZipProfile {
  const ArchiveExternalSevenZipProfile({
    this.dictionaryMiB = 16,
    this.threads = 2,
    this.solidBlockMiB = 0,
  });
  static const dictionarySizesMiB = [1, 4, 16];
  static const threadCounts = [1, 2, 4];
  static const solidBlockSizesMiB = [0, 16, 32];
  final int dictionaryMiB, threads, solidBlockMiB;

  void validate() {
    if (!dictionarySizesMiB.contains(dictionaryMiB) ||
        !threadCounts.contains(threads) ||
        !solidBlockSizesMiB.contains(solidBlockMiB)) {
      throw const ArchiveExternalPackerException(
        ArchiveExternalPackerFailure.unsupportedOptions,
      );
    }
  }

  @override
  bool operator ==(Object other) =>
      other is ArchiveExternalSevenZipProfile &&
      dictionaryMiB == other.dictionaryMiB &&
      threads == other.threads &&
      solidBlockMiB == other.solidBlockMiB;
  @override
  int get hashCode => Object.hash(dictionaryMiB, threads, solidBlockMiB);
}

/// Only formats whose executable round-trip probe succeeded are selectable.
/// The installation is transient: capabilities and identities are never saved.
class ArchiveExternalPackerInstallation {
  ArchiveExternalPackerInstallation({
    required this.configuration,
    required this.identity,
    required this.version,
    required Set<ArchiveExternalPackerFormat> formats,
    this.sevenZipProfile = const ArchiveExternalSevenZipProfile(),
  }) : formats = Set.unmodifiable(formats);
  final ArchiveExternalPackerConfiguration configuration;
  final ArchiveExternalPackerIdentity identity;
  final String version;
  final Set<ArchiveExternalPackerFormat> formats;

  /// All three compression levels were checked with this exact 7z profile.
  /// ZIP and RAR use their fixed profiles and do not inherit these options.
  final ArchiveExternalSevenZipProfile sevenZipProfile;

  void validateOptions(ArchiveExternalPackerOptions options) {
    if (!formats.contains(options.format) ||
        configuration.kind == ArchiveExternalPackerKind.rar &&
            options.format != ArchiveExternalPackerFormat.rar ||
        configuration.kind == ArchiveExternalPackerKind.sevenZip &&
            options.format == ArchiveExternalPackerFormat.rar) {
      throw const ArchiveExternalPackerException(
        ArchiveExternalPackerFailure.unsupportedFormat,
      );
    }
    options.sevenZipProfile.validate();
    if (options.sevenZipProfile !=
        (options.format == ArchiveExternalPackerFormat.sevenZip
            ? sevenZipProfile
            : const ArchiveExternalSevenZipProfile())) {
      throw const ArchiveExternalPackerException(
        ArchiveExternalPackerFailure.unsupportedOptions,
      );
    }
  }
}

class ArchiveExternalPackerOptions {
  const ArchiveExternalPackerOptions({
    required this.name,
    required this.format,
    this.compression = ArchiveExternalPackerCompression.normal,
    this.sevenZipProfile = const ArchiveExternalSevenZipProfile(),
  });
  final String name;
  final ArchiveExternalPackerFormat format;
  final ArchiveExternalPackerCompression compression;
  final ArchiveExternalSevenZipProfile sevenZipProfile;
}

abstract interface class ArchiveExternalPackerEngine {
  String? get platform;
  Future<List<ArchiveExternalPackerConfiguration>> discover();
  Future<ArchiveExternalPackerInstallation> probe(
    ArchiveExternalPackerConfiguration configuration, {
    ArchiveExternalSevenZipProfile sevenZipProfile =
        const ArchiveExternalSevenZipProfile(),
    bool Function()? isCancelled,
  });
  Future<void> write({
    required ArchiveExternalPackerInstallation installation,
    required ArchiveExternalPackerOptions options,
    required List<ArchiveWriteEntry> entries,
    required Future<void> Function(List<int>) sink,
    required int maxOutputBytes,
    bool Function()? isCancelled,
  });
}

