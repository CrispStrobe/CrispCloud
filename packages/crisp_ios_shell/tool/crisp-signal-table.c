#include <ctype.h>
#include <signal.h>
#include <stdio.h>
#include <string.h>

#ifndef __APPLE__
#error This generator targets Darwin signal numbering, including the iOS SDK.
#endif

int main(int argc, char **argv) {
    if (argc > 2) { fputs("usage: crisp-signal-table [output.c]\n", stderr); return 2; }
    FILE *out = fopen(argc == 2 ? argv[1] : "signames.c", "w");
    if (!out) { perror("signal table output"); return 1; }
    fputs("/* Darwin signal metadata generated by CrispCloud (MIT). */\n"
          "#include <signal.h>\nconst char *const signal_names[NSIG + 1] = {\n", out);
    for (int number = 0; number < NSIG; ++number) {
        const char *name = number == 0 ? "EXIT" : sys_signame[number];
        fputs("  \"", out);
        if (!name || !*name) {
            fprintf(out, "%d", number);
        } else {
            for (const unsigned char *p = (const unsigned char *)name; *p; ++p) {
                if (!isalnum(*p) && *p != '_') { fclose(out); return 1; }
                fputc(toupper(*p), out);
            }
        }
        fputs("\",\n", out);
    }
    fputs("  0\n};\n", out);
    return fclose(out) == 0 ? 0 : 1;
}
