Uint8List _paddedPng(int extraBytes) {
  final original = mediaFixturePng();
  final typeAndData = Uint8List(extraBytes + 4)
    ..setRange(0, 4, ascii.encode('tEXt'));
  final chunk = ByteData(4)..setUint32(0, extraBytes);
  final crc = ByteData(4)..setUint32(0, getCrc32(typeAndData));
  return Uint8List.fromList([
    ...original.sublist(0, original.length - 12),
    ...chunk.buffer.asUint8List(),
    ...typeAndData,
    ...crc.buffer.asUint8List(),
    ...original.sublist(original.length - 12),
  ]);
}

Uint8List _largeGrayPng() {
  // A valid, very small compressed PNG that expands to 16 Mi pixels. One-bit
  // grayscale keeps fixture creation cheap; host decoders may still use RGBA.
  Uint8List chunk(String type, Uint8List bytes) {
    final payload = Uint8List.fromList([...ascii.encode(type), ...bytes]);
    final size = ByteData(4)..setUint32(0, bytes.length);
    final crc = ByteData(4)..setUint32(0, getCrc32(payload));
    return Uint8List.fromList([
      ...size.buffer.asUint8List(),
      ...payload,
      ...crc.buffer.asUint8List(),
    ]);
  }

  final header = ByteData(13)
    ..setUint32(0, 4096)
    ..setUint32(4, 4096)
    ..setUint8(8, 1);
  return Uint8List.fromList([
    137,
    80,
    78,
    71,
    13,
    10,
    26,
    10,
    ...chunk('IHDR', header.buffer.asUint8List()),
    ...chunk('IDAT', ZLibEncoder().encodeBytes(Uint8List(4096 * 513))),
    ...chunk('IEND', Uint8List(0)),
  ]);
}

