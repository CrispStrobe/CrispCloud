  /// Embedded image keys, sorted case-insensitively.
  List<String> get imageNames => images.keys.toList()
    ..sort((String a, String b) => a.toLowerCase().compareTo(b.toLowerCase()));

  /// Embeds PNG / JPEG [bytes] under a key derived from [fileName]
  /// ([ReportPackage.keyFor]) and returns the key; null when [bytes] are
  /// neither PNG nor JPEG. With [assignToSelection] the selected image
  /// elements switch to the new key in the same undo step.
  String? addImage(
    String fileName,
    Uint8List bytes, {
    bool assignToSelection = false,
  }) {
    if (ReportImageFormat.sniff(bytes) == null) {
      return null;
    }
    final String key = ReportPackage.keyFor(fileName, taken: images.keys);
    _mutate(() {
      images[key] = bytes;
      if (assignToSelection) {
        for (final ReportElement e in selectedElements) {
          if (e is ReportImageElement) {
            e.source = key;
          }
        }
      }
      return true;
    });
    return key;
  }

  /// Renames embedded image [from] to [to] and repoints `<Image>` elements
  /// whose source is exactly [from]. Returns whether it renamed. Undoable.
  bool renameImage(String from, String to) {
    final String name = to.trim();
    if (!images.containsKey(from) ||
        name == from ||
        !ReportPackage.isValidKey(name) ||
        images.keys.any(
          (String k) => k != from && k.toLowerCase() == name.toLowerCase(),
        )) {
      return false;
    }
    _mutate(() {
      images[name] = images.remove(from)!;
      for (final ReportBand band in _template.bands) {
        for (final ReportElement e in band.elements) {
          if (e is ReportImageElement && e.source.trim() == from) {
            e.source = name;
          }
        }
      }
      return true;
    });
    return true;
  }

  /// Swaps the pixels of embedded image [name] for PNG / JPEG [bytes] and
  /// keeps its key, so every element showing it updates at once. Returns
  /// whether it replaced. Undoable.
  bool replaceImage(String name, Uint8List bytes) {
    if (!images.containsKey(name) || ReportImageFormat.sniff(bytes) == null) {
      return false;
    }
    _mutate(() {
      images[name] = bytes;
      return true;
    });
    return true;
  }

  /// Asks [imagePicker] for a file and puts it in place of embedded image
  /// [name] ([replaceImage]). Returns whether it replaced; a file that is
  /// neither PNG nor JPEG leaves a [notice].
  Future<bool> importReplacement(String name) async {
    final ReportImagePicker? picker = imagePicker;
    if (picker == null || !images.containsKey(name)) {
      return false;
    }
    final ({String name, Uint8List bytes})? file = await picker();
    if (file == null || _disposed) {
      return false;
    }
    if (replaceImage(name, file.bytes)) {
      return true;
    }
    _notice = 'The chosen file is not a PNG or JPEG image';
    notifyListeners();
    return false;
  }

  /// Removes embedded image [name]; elements that use it draw nothing until
  /// it is re-added. Returns whether it existed. Undoable.
  bool removeImage(String name) {
    if (!images.containsKey(name)) {
      return false;
    }
    _mutate(() => images.remove(name) != null);
    return true;
  }

  /// Adds an `<Image>` showing embedded image [name] to the insertion band
  /// (at most 40 mm on its long side, keeping the aspect ratio) and selects
  /// it. Returns the element, or null when [name] is not embedded.
  /// Reads a shapefile, GeoJSON, or `.qmap` from [shapePicker], embeds it,
  /// and points the selected shape map at it. Returns the layer name.
  Future<String?> importShape() async {
    final ReportShapePicker? picker = shapePicker;
    if (picker == null) {
      return null;
    }
    final ({String name, Uint8List bytes, Uint8List? attributes})? picked =
        await picker();
    if (picked == null) {
      return null;
    }
    final ReportShapeFile file;
    try {
      final ReportElement? selected = primary;
      final String? keyField = selected is ReportChartElement
          ? selected.shapeKey
          : null;
      file = ReportShapeLayer.read(
        picked.bytes,
        attributes: picked.attributes,
        keyField: keyField,
      );
    } on ReportShapeException catch (e) {
      _notice = e.message;
      notifyListeners();
      return null;
    }
    final String key = ReportPackage.keyFor(picked.name, taken: shapes.keys);
    final Uint8List encoded = file.layer.encode();
    _mutate(() {
      shapes[key] = encoded;
      final ReportElement? selected = primary;
      if (selected is ReportChartElement && selected.chartType.isShapeMap) {
        selected.shape = key;
        final String? field = file.keyField;
        if (field != null && field.isNotEmpty) {
          selected.shapeKey = field;
        }
        final String? label = file.nameField;
        final String current = (selected.labelField ?? '').trim();
        final bool known = file.layer.fields.any(
          (String name) => name.toLowerCase() == current.toLowerCase(),
        );
        if (label != null && label.isNotEmpty && (current.isEmpty || !known)) {
          selected.labelField = label;
        }
        final String table = shapeTableName(key);
        final String set = (selected.dataSet ?? '').trim().toLowerCase();
        if (set.isEmpty || set == 'data.items') {
          selected.dataSet = 'Data.$table';
        }
        _wireShapeMap(selected, forceKey: true);
        _dataTable = table;
      }
      return true;
    });
    return key;
  }

  /// Drops an embedded shape file and points every map that used it back
  /// at the world atlas. The atlas itself is not a file in the report.
  bool removeShape([String? name]) {
    final ReportElement? current = primary;
    final String key =
        (name ?? (current is ReportChartElement ? current.shape : '')).trim();
    if (key.isEmpty || key == 'world' || !shapes.containsKey(key)) {
      return false;
    }
    _mutate(() {
      shapes.remove(key);
      for (final ReportBand band in _template.bands) {
        for (final ReportElement element in band.elements) {
          if (element is ReportChartElement && element.shape == key) {
            element.shape = 'world';
          }
        }
      }
      return true;
    });
    return true;
  }

  /// Points a shape map at the table column that matches its region key and
  /// the numeric column drawn on each region. A custom expression that
  /// already names a column of the table is left as the user wrote it.
  void _wireShapeMap(ReportChartElement e, {bool forceKey = false}) {
    final ReportDataTableView? table = _chartTable(e);
    final String row = _rowToken(e);
    final String? keyCol = _shapeKeyColumn(table, e.shapeKey);
    final String category = (e.category ?? '').trim();
    final String typedKey = (e.shapeKey ?? '').trim();
    if (forceKey && (keyCol != null || typedKey.isNotEmpty)) {
      e.category = '$row.${keyCol ?? typedKey}';
    } else if (_isPlaceholderCategory(category) ||
        _missingColumn(category, table)) {
      if (keyCol != null) {
        e.category = '$row.$keyCol';
      } else if (typedKey.isNotEmpty) {
        e.category = '$row.$typedKey';
      }
    }
    _wireRegionColor(e, table, row, keyCol ?? typedKey);
    final String? measure = _measureColumn(table, keyCol ?? typedKey);
    if (measure == null) {
      return;
    }
    if (e.series.isEmpty) {
      e.series.add(ReportChartSeries(name: measure, value: '$row.$measure'));
      return;
    }
    if (_isPlaceholderValue(e.series.first.value)) {
      e.series.first.value = '$row.$measure';
    }
  }

  ReportDataTableView? _chartTable(ReportChartElement e) {
    final String? set = e.dataSet;
    if (set == null || set.trim().isEmpty) {
      return null;
    }
    final String path = ReportData.normalizePath(
      set.trim().replaceFirst(RegExp(r'^Data\.', caseSensitive: false), ''),
    );
    for (final ReportDataTableView t in dataTables) {
      if (!t.isFields && t.name.toLowerCase() == path.toLowerCase()) {
        return t;
      }
    }
    return null;
  }

  String _rowToken(ReportChartElement e) {
    final String category = (e.category ?? '').trim();
    final int dot = category.indexOf('.');
    if (dot > 0) {
      final String head = category.substring(0, dot);
      if (head == 'item' || head == 'Row' || head == 'row') {
        return head;
      }
    }
    return e.dataSet == null ? 'item' : 'Row';
  }

  String? _shapeKeyColumn(ReportDataTableView? table, String? shapeKey) {
    if (table == null) {
      return null;
    }
    final String requested = (shapeKey ?? '').trim();
    if (requested.isNotEmpty) {
      for (final ReportDataColumnView c in table.columns) {
        if (c.name.toLowerCase() == requested.toLowerCase()) {
          return c.name;
        }
      }
    }
    for (final String name in const <String>[
      'iso_a2',
      'iso_a3',
      'adm0_a3',
      'code',
      'country',
      'region',
    ]) {
      for (final ReportDataColumnView c in table.columns) {
        if (c.name.toLowerCase() == name) {
          return c.name;
        }
      }
    }
    for (final ReportDataColumnView c in table.columns) {
      if (c.type == ReportDataType.text) {
        return c.name;
      }
    }
    return null;
  }

  void _wireRegionColor(
    ReportChartElement e,
    ReportDataTableView? table,
    String row,
    String keyColumn,
  ) {
    if ((e.regionColor ?? '').trim().isNotEmpty || table == null) {
      return;
    }
    for (final String name in const <String>[
      'color',
      'colour',
      'fill',
      'regioncolor',
    ]) {
      for (final ReportDataColumnView column in table.columns) {
        final String lower = column.name.toLowerCase();
        if (lower == name && lower != keyColumn.toLowerCase()) {
          e.regionColor = '$row.${column.name}';
          return;
        }
      }
    }
  }

  String? _measureColumn(ReportDataTableView? table, String? keyColumn) {
    if (table == null) {
      return null;
    }
    for (final ReportDataColumnView c in table.columns) {
      if (c.type == ReportDataType.number &&
          c.name.toLowerCase() != keyColumn?.toLowerCase()) {
        return c.name;
      }
    }
    return null;
  }

  bool _isPlaceholderCategory(String category) {
    return category.isEmpty ||
        RegExp(
          r'^(Row|item|row)\.category$',
          caseSensitive: false,
        ).hasMatch(category);
  }

  bool _isPlaceholderValue(String value) {
    return value.trim().isEmpty ||
        RegExp(
          r'^(Row|item|row)\.(total|value\d*)$',
          caseSensitive: false,
        ).hasMatch(value.trim());
  }

  bool _missingColumn(String expression, ReportDataTableView? table) {
    final String text = expression.trim();
    final int dot = text.lastIndexOf('.');
    if (dot <= 0 || dot == text.length - 1 || text.contains('(')) {
      return false;
    }
    final String head = text.substring(0, dot);
    if (head != 'item' && head != 'Row' && head != 'row') {
      return false;
    }
    return !_namesTableColumn(text, table);
  }

  bool _namesTableColumn(String expression, ReportDataTableView? table) {
    if (table == null) {
      return false;
    }
    final int dot = expression.trim().lastIndexOf('.');
    if (dot < 0 || dot == expression.trim().length - 1) {
      return false;
    }
    final String name = expression.trim().substring(dot + 1);
    for (final ReportDataColumnView c in table.columns) {
      if (c.name.toLowerCase() == name.toLowerCase()) {
        return true;
      }
    }
    return false;
  }

  ReportImageElement? insertImage(String name) {
    final Uint8List? bytes = images[name];
    if (bytes == null) {
      return null;
    }
    const double side = 40 * 72 / 25.4;
    final ImageSize? size = ImageFit.readSize(bytes);
    final double aspect = size == null ? 1 : size.widthPx / size.heightPx;
    final double w = aspect >= 1 ? side : side * aspect;
    final double h = aspect >= 1 ? side / aspect : side;
    final ReportBandKind kind = _insertionBand();
    final ReportTemplate t = _template;
    final double left = t.mirrored
        ? t.pageWidth - t.margins.right - w
        : t.margins.left;
    final ReportElement? e = addElement(
      ReportDesignTool.image,
      kind,
      ReportRect(left, _bandBottom(kind), w, h),
    );
    if (e is! ReportImageElement) {
      return null;
    }
    e.source = name;
    _changed();
    return e;
  }

  /// Asks [imagePicker] for a file and embeds it ([addImage]); returns the
  /// new key, or null when cancelled, unsupported, or there is no picker.
  Future<String?> importImage({bool assignToSelection = false}) async {
    final ReportImagePicker? picker = imagePicker;
    if (picker == null) {
      return null;
    }
    final ({String name, Uint8List bytes})? file = await picker();
    if (file == null || _disposed) {
      return null;
    }
    return addImage(
      file.name,
      file.bytes,
      assignToSelection: assignToSelection,
    );
  }

  static String _imageInfo(Uint8List bytes) {
    final ImageSize? size = ImageFit.readSize(bytes);
    final String type = ReportImageFormat.sniff(bytes) == ReportImageFormat.jpeg
        ? 'JPEG'
        : 'PNG';
    final String kb = _byteSize(bytes.length);
    return size == null
        ? '$type, $kb'
        : '$type ${size.widthPx}×${size.heightPx}, $kb';
  }

