  bool _rejectPath(String path, String what) {
    if (!ReportData.isValidPath(path)) {
      _notice =
          '"$path" is not a valid $what name: use letters, digits or _, '
          'with dots between levels (customer.name)';
      notifyListeners();
      return true;
    }
    final List<String> segs = path.split('.');
    for (int i = 1; i <= segs.length; i++) {
      final String prefix = segs.take(i).join('.');
      final Object? v = ReportData.valueAt(mockData, prefix);
      final bool last = i == segs.length;
      final bool declared = _template.dataSchema.fields.any(
        (ReportDataField f) =>
            ReportData.normalizePath(f.name).toLowerCase() ==
            prefix.toLowerCase(),
      );
      if ((last && (v != null || declared || _view(prefix) != null)) ||
          (!last && v != null && v is! Map<String, Object?>)) {
        _notice = '"$prefix" already exists';
        notifyListeners();
        return true;
      }
    }
    return false;
  }

