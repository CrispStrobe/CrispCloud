  /// Zoom factor (1 = one logical pixel per point).
  double get zoom => _zoom;

  set zoom(double value) {
    final double z = value.clamp(0.25, 4).toDouble();
    if ((z - _zoom).abs() < 1e-6) {
      return;
    }
    _zoom = z;
    notifyListeners();
  }

  /// Width of the canvas viewport in logical pixels (set by the canvas).
  var viewportWidth = 0.0;

  /// Zooms so the page width fills the canvas viewport.
  void fitWidth() {
    if (viewportWidth <= 0) {
      return;
    }
    zoom = (viewportWidth - 48) / _template.pageWidth;
  }

