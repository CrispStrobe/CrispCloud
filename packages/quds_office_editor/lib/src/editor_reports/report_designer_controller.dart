  /// Applies the folder keys of the Variables page; returns whether the
  /// template changed.
  bool _applyVariableFolder(ReportTemplate t, String key, String v) {
    switch (key) {
      case 'var+' || 'vfolder.add':
        final String folder = key == 'vfolder.add'
            ? (selectedVariablePath ?? '')
            : currentVariableFolder;
        final String name = _uniqueVariableName(
          t,
          folder.isEmpty ? 'variable' : '$folder.variable',
        );
        _newVariable(t, name: name);
        _variablePath = name;
        return true;
      case 'vfolder+':
        final String parent = currentVariableFolder;
        var n = 1;
        String folder() => parent.isEmpty ? 'folder$n' : '$parent.folder$n';
        while (_variablePathExists(folder()) ||
            variableNameProblem(t, '${folder()}.variable1') != null) {
          n++;
        }
        final String name = '${folder()}.variable1';
        _newVariable(t, name: name);
        _variablePath = name;
        return true;
      case 'vfolder.name':
        final String? old = selectedVariablePath;
        final String now = v.trim();
        if (old == null || selectedVariable != null || now == old) {
          return false;
        }
        return renameVariableFolder(old, now, mutate: false);
      case 'vfolder.remove':
        final String? folder = selectedVariablePath;
        if (folder == null || selectedVariable != null) {
          return false;
        }
        final String prefix = '${folder.toLowerCase()}.';
        t.variables.removeWhere(
          (ReportVariable x) => x.name.toLowerCase().startsWith(prefix),
        );
        _variablePath = null;
        return true;
    }
    return false;
  }

  /// Renames variable folder [from] to [to] (`stats` → `totals.stats`):
  /// every variable under it moves and `{{Variables.…}}` references follow.
  /// Returns whether it renamed; the reason for a refusal is in [notice].
  /// Undoable.
  bool renameVariableFolder(String from, String to, {bool mutate = true}) {
    bool apply() {
      final ReportTemplate t = _template;
      final String prefix = '${from.toLowerCase()}.';
      final List<ReportVariable> moving = <ReportVariable>[
        for (final ReportVariable x in t.variables)
          if (x.name.toLowerCase().startsWith(prefix)) x,
      ];
      if (moving.isEmpty || to.trim().isEmpty) {
        return false;
      }
      final ReportTemplate probe = ReportTemplate()
        ..variables.addAll(<ReportVariable>[
          for (final ReportVariable x in t.variables)
            if (!moving.contains(x)) x,
        ]);
      final Map<String, String> renames = <String, String>{};
      for (final ReportVariable x in moving) {
        final String next = '$to${x.name.substring(from.length)}';
        final String? problem = variableNameProblem(probe, next);
        if (problem != null) {
          _notice = problem;
          return false;
        }
        probe.variables.add(ReportVariable(name: next));
        renames[x.name] = next;
      }
      for (final ReportVariable x in moving) {
        x.name = renames[x.name]!;
      }
      _variablePath = to;
      _renameVariableRefsMany(renames);
      return true;
    }

    if (!mutate) {
      return apply();
    }
    var done = false;
    _mutate(() => done = apply());
    notifyListeners();
    return done;
  }

  /// Why [name] cannot name a variable other than [self] of [t], or null.
  static String? variableNameProblem(
    ReportTemplate t,
    String name, {
    ReportVariable? self,
  }) {
    if (!ReportVariable.isValidName(name)) {
      return '"$name" is not a valid name: use letters, digits and _, and '
          'dots for folders (stats.sum)';
    }
    final String lower = name.toLowerCase();
    for (final ReportVariable o in t.variables) {
      if (identical(o, self)) {
        continue;
      }
      final String other = o.name.toLowerCase();
      if (other == lower) {
        return 'Another variable is already named "${o.name}"';
      }
      if (other.startsWith('$lower.') || lower.startsWith('$other.')) {
        return '"$name" clashes with "${o.name}": a name cannot be both a '
            'variable and a folder';
      }
    }
    return null;
  }

  ReportVariable _newVariable(
    ReportTemplate t, {
    String? name,
    ReportVariableType type = ReportVariableType.text,
    String? value,
  }) {
    bool taken(String n) => t.variables.any(
      (ReportVariable o) => o.name.toLowerCase() == n.toLowerCase(),
    );
    var candidate = name ?? 'variable1';
    var n = 1;
    while (taken(candidate)) {
      n++;
      candidate = '${name ?? 'variable'}$n';
    }
    final ReportVariable v = ReportVariable(
      name: candidate,
      type: type,
      value: value ?? _variableDefault(type),
    );
    t.variables.add(v);
    return v;
  }

  bool _applyVariable(ReportTemplate t, String key, String v) {
    final List<String> parts = key.split('.');
    final int? i = parts.length == 3 ? int.tryParse(parts[1]) : null;
    if (i == null || i < 0 || i >= t.variables.length) {
      return false;
    }
    final ReportVariable x = t.variables[i];
    switch (parts[2]) {
      case 'name':
        final String n = v.trim();
        if (n == x.name) {
          return false;
        }
        final String? problem = variableNameProblem(t, n, self: x);
        if (problem != null) {
          _notice = problem;
          return false;
        }
        final String old = x.name;
        x.name = n;
        if (_variablePath == old) {
          _variablePath = n;
        }
        _renameVariableRefs(old, n);
      case 'type':
        final ReportVariableType? type = reportEnumByName(
          ReportVariableType.values,
          v,
        );
        if (type == null || type == x.type) {
          return false;
        }
        x.type = type;
        if (x.error != null) {
          x.value = _variableDefault(type);
        }
      case 'value':
        final String old = x.value;
        x.value = x.type == ReportVariableType.text ? v : v.trim();
        if (x.error != null) {
          x.value = old;
          return false;
        }
      case 'format':
        x.format = _opt(v);
      case 'description':
        x.description = v.trim();
      case 'prompt':
        x.prompt = v == 'true';
        if (!x.prompt) {
          x.required = false;
        }
      case 'required':
        x.required = v == 'true';
        if (x.required) {
          x.prompt = true;
        }
      case 'remove':
        t.variables.removeAt(i);
      default:
        return false;
    }
    return true;
  }

  /// Rewrites `Variables.old` references after a rename.
  void _renameVariableRefs(String old, String now) =>
      _renameVariableRefsMany(<String, String>{old: now});

  /// Rewrites `Variables.old` references for every old → new pair.
  void _renameVariableRefsMany(Map<String, String> renames) {
    final String xml = toXml();
    var renamed = xml;
    for (final MapEntry<String, String> r in renames.entries) {
      final RegExp ref = RegExp(
        '(?<![A-Za-z0-9_.\u0600-\u06FF])((?:Variables|Vars|Var)\\.)'
        '${RegExp.escape(r.key)}(?![A-Za-z0-9_.\u0600-\u06FF])',
        caseSensitive: false,
        unicode: true,
      );
      renamed = renamed.replaceAllMapped(
        ref,
        (Match m) => '${m.group(1)}${r.value}',
      );
    }
    if (renamed == xml) {
      return;
    }
    final ReportParseResult parsed = QudsReportXmlParser().parse(renamed);
    if (parsed.hasErrors) {
      return;
    }
    _template = parsed.templateOrThrow;
    _selection.clear();
  }

  /// Adds a template variable and returns it (unique [name], default value
  /// for [type]). Undoable.
  ReportVariable addVariable({
    String? name,
    ReportVariableType type = ReportVariableType.text,
    String? value,
  }) {
    late ReportVariable added;
    _mutate(() {
      added = _newVariable(_template, name: name, type: type, value: value);
      return true;
    });
    return added;
  }

  /// Inserts `{{Variables.name}}` (with its format): at the caret while
  /// editing text or an inspector value (bare `Variables.name` in
  /// expressions), else as a new text box in the selected band. Returns the
  /// created element, if any.
  ReportElement? insertVariable(String name) {
    ReportVariable? v;
    for (final ReportVariable x in _template.variables) {
      if (x.name.toLowerCase() == name.toLowerCase()) {
        v = x;
      }
    }
    if (v == null) {
      return null;
    }
    if (editingId != null && textEditor.editing) {
      textEditor.replaceRange(
        textEditor.selectionStart,
        textEditor.selectionEnd,
        v.placeholder,
      );
      return null;
    }
    if (editingProperty != null && propertyEditor.editing) {
      ReportPropertyKind? kind;
      for (final ReportProperty p in properties) {
        if (p.key == editingProperty) {
          kind = p.kind;
        }
      }
      propertyEditor.replaceRange(
        propertyEditor.selectionStart,
        propertyEditor.selectionEnd,
        kind == ReportPropertyKind.expression
            ? 'Variables.${v.name}'
            : v.placeholder,
      );
      return null;
    }
    final ReportBandKind kind = _insertionBand();
    final ReportTemplate t = _template;
    final double left = t.mirrored
        ? t.pageWidth - t.margins.right
        : t.margins.left;
    final ReportElement? e = addElement(
      ReportDesignTool.text,
      kind,
      ReportRect(left, _bandBottom(kind), 0, 0),
    );
    if (e is ReportTextElement) {
      e.text = v.placeholder;
      _changed();
    }
    return e;
  }

  /// Band that receives inserted elements: the selection's band, else the
  /// first of report header / page header / detail (a report header is
  /// added to an empty template).
  ReportBandKind _insertionBand() {
    ReportBandKind? kind = _selectedBand;
    final ReportElement? p = primary;
    if (p != null) {
      kind = _template.findElement(p.id)?.$1.kind;
    }
    if (kind == null || _template.band(kind) == null) {
      kind = null;
      for (final ReportBandKind k in const <ReportBandKind>[
        ReportBandKind.reportHeader,
        ReportBandKind.pageHeader,
        ReportBandKind.detail,
      ]) {
        if (kind == null && _template.band(k) != null) {
          kind = k;
        }
      }
      kind ??= _template.bands.isEmpty ? null : _template.bands.first.kind;
    }
    if (kind == null) {
      addBand(ReportBandKind.reportHeader);
      kind = ReportBandKind.reportHeader;
    }
    return kind;
  }

  double _bandBottom(ReportBandKind kind) {
    var top = 0.0;
    for (final ReportElement e in _template.band(kind)!.elements) {
      top = _max(top, e.y + e.height);
    }
    return top;
  }

