  ReportCompletionResult _fontCompletion(
    String text, {
    required String query,
    required bool installedOnly,
  }) {
    _loadDeviceFamilies();
    final String q = query.trim().toLowerCase();
    final Set<String> seen = <String>{};
    final List<ReportCompletionItem> first = <ReportCompletionItem>[];
    final List<ReportCompletionItem> rest = <ReportCompletionItem>[];
    void offer(String family, String detail) {
      if (!seen.add(family.toLowerCase())) {
        return;
      }
      final String lower = family.toLowerCase();
      if (q.isNotEmpty && !lower.contains(q)) {
        return;
      }
      final ReportCompletionItem item = ReportCompletionItem(
        label: family,
        insert: family,
        kind: ReportCompletionKind.field,
        detail: detail,
      );
      (q.isNotEmpty && lower.startsWith(q) ? first : rest).add(item);
    }

    if (!installedOnly) {
      for (final String f in embeddedFamilies) {
        offer(f, 'In this report');
      }
      for (final String f in fontFamilies) {
        offer(f, 'Built in');
      }
    } else {
      seen.addAll(embeddedFonts.keys.map((String f) => f.toLowerCase()));
    }
    for (final String f in _deviceFamilies ?? const <String>[]) {
      offer(f, 'Installed on this device');
    }
    return ReportCompletionResult(
      start: 0,
      end: text.length,
      items: <ReportCompletionItem>[...first, ...rest],
    );
  }

  /// Handles the font keys of [setProperty]; returns whether [key] was one.
  bool _setFontProperty(String key, String value) {
    if (key == 'font+') {
      unawaited(importFonts());
      return true;
    }
    if (key == 'font.search') {
      fontSearch = value.trim();
      return true;
    }
    if (key == 'font.add') {
      final String family = value.trim();
      if (family.isNotEmpty) {
        unawaited(embedDeviceFont(family));
      }
      return true;
    }
    if (RegExp(r'^font\.\d+\.(card|uses)$').hasMatch(key)) {
      return true;
    }
    if (key.startsWith('dev.')) {
      final int? i = int.tryParse(key.substring(4));
      final List<String> matches = _deviceMatches();
      if (i != null && i < matches.length) {
        unawaited(embedDeviceFont(matches[i]));
      }
      return true;
    }
    final RegExpMatch? m = RegExp(
      r'^font\.(\d+)\.(default|remove)$',
    ).firstMatch(key);
    if (m == null) {
      return key.startsWith('font.');
    }
    final List<String> names = embeddedFamilies;
    final int i = int.parse(m.group(1)!);
    if (i >= names.length) {
      return true;
    }
    final String family = names[i];
    if (m.group(2) == 'remove') {
      removeFont(family);
      return true;
    }
    final String next = _parseBool(value) ? family : '';
    _mutate(() {
      if (_template.defaultFont == next) {
        return false;
      }
      _template.defaultFont = next;
      return true;
    });
    return true;
  }

  bool _applyElement(ReportElement e, String key, String v) {
    switch (key) {
      case 'name':
        return _rename(e, v.trim());
      case 'visibleWhen':
        e.visibleWhen = _opt(v);
        return true;
      case 'x' || 'y' || 'width' || 'height':
        final double? n = _parseLen(v);
        if (n == null || (n < 0 && key != 'x')) {
          return false;
        }
        switch (key) {
          case 'x':
            e.x = _round(n);
          case 'y':
            e.y = _round(n);
          case 'width':
            e.width = _round(n);
          default:
            e.height = _round(n);
        }
        return true;
    }
    return switch (e) {
      ReportTextElement() => _applyText(e, key, v),
      ReportImageElement() => _applyImage(e, key, v),
      ReportBarcodeElement() => _applyBarcode(e, key, v),
      ReportShapeElement() => _applyShape(e, key, v),
      ReportTableElement() => _applyTable(e, key, v),
      ReportChartElement() => _applyChart(e, key, v),
      ReportCrosstabElement() => _applyCrosstab(e, key, v),
      ReportSubreportElement() => _applySubreport(e, key, v),
    };
  }

