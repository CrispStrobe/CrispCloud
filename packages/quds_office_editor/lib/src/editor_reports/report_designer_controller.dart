  /// Handles the image keys of [setProperty]; returns whether [key] was one.
  bool _setImageProperty(String key, String value) {
    if (key == 'image+' || key == 'source.import') {
      unawaited(importImage(assignToSelection: key == 'source.import'));
      return true;
    }
    if (key == 'source.replace') {
      final ReportElement? e = primary;
      if (e is ReportImageElement) {
        unawaited(importReplacement(e.source.trim()));
      }
      return true;
    }
    final RegExpMatch? m = RegExp(
      r'^img\.(\d+)\.(name|replace|insert|remove)$',
    ).firstMatch(key);
    if (m == null) {
      return false;
    }
    final List<String> names = imageNames;
    final int i = int.parse(m.group(1)!);
    if (i >= names.length) {
      return true;
    }
    switch (m.group(2)) {
      case 'name':
        renameImage(names[i], value);
      case 'replace':
        unawaited(importReplacement(names[i]));
      case 'insert':
        insertImage(names[i]);
      case 'remove':
        removeImage(names[i]);
    }
    return true;
  }

