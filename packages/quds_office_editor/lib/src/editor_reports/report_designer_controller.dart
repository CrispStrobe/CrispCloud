/// A column of the data explorer: declared in the template's
/// [ReportDataSchema] ([inSchema]) or found in the data.
class ReportDataColumnView {
  /// ReportDataColumnView API.
  const ReportDataColumnView({
    required this.name,
    required this.type,
    this.expression,
    this.format,
    this.description = '',
    this.inSchema = false,
    this.error,
  });

  /// Field name in each row.
  final String name;

  /// Declared type, else the type inferred from the values.
  final ReportDataType type;

  /// Row expression of a calculated column.
  final String? expression;

  /// Display format (`n2`).
  final String? format;

  /// description API.
  final String description;

  /// Whether the template's data schema declares the column.
  final bool inSchema;

  /// Why [expression] does not parse, if it does not.
  final String? error;

  /// Whether the values come from [expression].
  bool get isCalculated {
    final String? e = expression;
    return e != null && e.trim().isNotEmpty;
  }
}

/// A table of the data explorer: a data set (`items`), or with an empty
/// [name] the report's single-value fields (one row per field).
class ReportDataTableView {
  /// ReportDataTableView API.
  const ReportDataTableView({
    required this.name,
    required this.columns,
    required this.rows,
    this.description = '',
    this.inSchema = false,
  });

  /// Data path; empty for the fields table.
  final String name;

  /// columns API.
  final List<ReportDataColumnView> columns;

  /// Cell values, row-major (types applied, calculated columns evaluated).
  final List<List<ReportValue>> rows;

  /// description API.
  final String description;

  /// Whether the template's data schema declares the table.
  final bool inSchema;

  /// Whether this lists the single-value fields.
  bool get isFields => name.isEmpty;

  /// Name shown in the explorer.
  String get title => isFields ? 'Fields' : name;
}

