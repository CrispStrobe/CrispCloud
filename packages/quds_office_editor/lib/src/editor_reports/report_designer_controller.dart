    }
    if (!key.startsWith('data.')) {
      return false;
    }
    final ReportDataTableView t = dataTable;
    final ReportDataColumnView? col =
        !t.isFields && _dataColumn >= 0 && _dataColumn < t.columns.length
        ? t.columns[_dataColumn]
        : null;
    final String? field =
        t.isFields && _dataRow >= 0 && _dataRow < _fieldPaths.length
        ? _fieldPaths[_dataRow]
        : null;
    final ReportDataType? type = ReportDataType.fromName(value);
    switch (key) {
      case 'data.row+':
        addDataRow();
      case 'data.col+':
        addDataColumn();
        beginPropertyEdit('data.col.name');
      case 'data.calc+' || 'data.formula+':
        _addFormulaField();
      case 'data.const+':
        addConstantColumn();
      case 'data.col.fill' when col != null:
        fillDataColumn(col.name, value);
      case 'data.row.remove':
        if (_dataRow >= 0) {
          removeDataRows(<int>[_dataRow]);
        }
      case 'data.table.remove':
        removeDataTable(t.name);
      case 'data.description':
        setDataTableDescription(value);
      case 'data.table+':
        if (value.trim().isNotEmpty) {
          addDataTable(value.trim());
        }
      case 'data.import':
        unawaited(importDataFile());
      case 'data.reset':
        setSampleData(null);
      case 'data.col.name' when col != null:
        renameDataColumn(col.name, value);
      case 'data.col.type' when col != null && type != null:
        setDataColumnType(col.name, type);
      case 'data.col.expression' when col != null:
        setDataColumnExpression(col.name, value);
      case 'data.col.format' when col != null:
        setDataColumnFormat(col.name, value);
      case 'data.col.description' when col != null:
        setDataColumnDescription(col.name, value);
      case 'data.col.remove' when col != null:
        removeDataColumn(col.name);
      case 'data.field+':
        if (value.trim().isNotEmpty) {
          addDataField(value.trim());
        }
      case 'data.field.name' when field != null:
        renameDataField(field, value);
      case 'data.field.type' when field != null && type != null:
        setDataFieldType(field, type);
      case 'data.field.description' when field != null:
        setDataFieldDescription(field, value);
      case 'data.field.remove' when field != null:
        removeDataField(field);
    }
    notifyListeners();
    return true;
  }

