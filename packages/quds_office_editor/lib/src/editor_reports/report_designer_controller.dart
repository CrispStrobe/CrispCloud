  /// Whether the explorer can edit data (false while [hasHostData]).
  bool get dataEditable => !hasHostData;

  /// Text of [value] for editing (no display format).
  String _sharedCell(ReportDataTableView t, int column) {
    if (t.rows.isEmpty || column < 0 || column >= t.columns.length) {
      return '';
    }
    final String first = dataCellText(t.rows.first[column]);
    for (final List<ReportValue> row in t.rows.skip(1)) {
      if (dataCellText(row[column]) != first) {
        return '';
      }
    }
    return first;
  }

  static String dataCellText(ReportValue value) => switch (value) {
    ReportNull() => '',
    ReportList(:final List<ReportValue> items) => '[${items.length} items]',
    ReportRecord(:final Map<String, ReportValue> fields) =>
      '{${fields.length} fields}',
    ReportBinary(:final Uint8List bytes) => '${_byteSize(bytes.length)} data',
    _ => value.displayText,
  };

  ReportFormatter? _formatter;
  ReportFormatDefaults? _formatterDefaults;

  /// Text of [value] in [column] as the grid shows it (column format
  /// applied).
  String dataCellDisplay(ReportDataColumnView column, ReportValue value) {
    final String? format = column.format?.trim();
    if (format == null || format.isEmpty || value is ReportNull) {
      return dataCellText(value);
    }
    if (_formatter == null ||
        !identical(_formatterDefaults, _template.formats)) {
      _formatterDefaults = _template.formats;
      _formatter = ReportFormatter(defaults: _template.formats);
    }
    try {
      return _formatter!.format(value, format);
    } on Object {
      return dataCellText(value);
    }
  }

  /// Whether cell ([row], [column]) of [dataTable] can be typed into:
  /// stored columns of editable data, and the Value column of the fields.
  bool canEditDataCell(int row, int column) {
    final ReportDataTableView t = dataTable;
    if (hasHostData ||
        row < 0 ||
        row >= t.rows.length ||
        column < 0 ||
        column >= t.columns.length) {
      return false;
    }
    final ReportValue v = t.rows[row][column];
    if (v is ReportList || v is ReportRecord || v is ReportBinary) {
      return false;
    }
    return t.isFields ? column == 1 : !t.columns[column].isCalculated;
  }

  /// Cell of [dataTable] being edited, if any.
  ({int row, int column})? get editingDataCell {
    final RegExpMatch? m = _cellKey.firstMatch(editingProperty ?? '');
    return m == null
        ? null
        : (row: int.parse(m.group(1)!), column: int.parse(m.group(2)!));
  }

  /// Starts editing a cell of [dataTable] with its current text, or with
  /// [initial] (the first typed character). Returns whether it started.
  bool beginCellEdit(int row, int column, {String? initial}) {
    _endEdits();
    if (!canEditDataCell(row, column)) {
      return false;
    }
    final ReportDataTableView t = dataTable;
    _dataTable = t.name;
    _dataRow = row;
    _dataColumn = column;
    editingProperty = 'cell.$row.$column';
    propertyEditor.begin(initial ?? dataCellText(t.rows[row][column]));
    if (initial == null) {
      propertyEditor.selectAll();
    }
    notifyListeners();
    return true;
  }

  bool _blockedByHost() {
    if (!hasHostData) {
      return false;
    }
    _notice = 'The preview data comes from the host app and is read-only';
    notifyListeners();
    return true;
  }

  /// Runs [edit] on a copy of [mockData] and keeps the result as
  /// [sampleData], as one undo step. The old map is never mutated, so undo
  /// restores the same object.
  bool _editSample(bool Function(ReportData data) edit) {
    if (_blockedByHost()) {
      return false;
    }
    final _Snapshot before = _snapshot();
    final ReportData next = ReportData(ReportData.copyMap(mockData));
    if (!edit(next)) {
      notifyListeners();
      return false;
    }
    _sample = next.values;
    _push(before);
    _changed();
    return true;
  }

  static (bool, Object?) _parseValue(String text, ReportDataType type) {
    final String s = text.trim();
    if (s.isEmpty) {
      return (true, null);
    }
    switch (type) {
      case ReportDataType.text:
        return (true, text);
      case ReportDataType.number:
        final num? n = ReportDataType.parseNumber(s);
        return (n != null, n);
      case ReportDataType.boolean:
        final bool? b = ReportDataType.parseBool(s);
        return (b != null, b);
      case ReportDataType.date:
        final DateTime? d = DateTime.tryParse(s);
        return (d != null, d);
    }
  }

  static String? _rawKey(Map<String, Object?> row, String name) {
    if (row.containsKey(name)) {
      return name;
    }
    final String lower = name.toLowerCase();
    for (final String k in row.keys) {
      if (k.toLowerCase() == lower) {
        return k;
      }
    }
    return null;
  }

  /// The list at [path] in [data], created when missing.
  static List<Object?> _rawList(ReportData data, String path) {
    final Object? at = data.get(path);
    if (at is List<Object?>) {
      return at;
    }
    final List<Object?> created = <Object?>[];
    data.set(path, created);
    return created;
  }

  /// Positions of the records in [list] (explorer rows skip other items).
  static List<int> _recordPositions(List<Object?> list) => <int>[
    for (int i = 0; i < list.length; i++)
      if (list[i] is Map<String, Object?>) i,
  ];

  ReportDataTableView? _tableFor(String? table) {
    final ReportDataTableView t = table == null
        ? dataTable
        : (_view(table) ??
              ReportDataTableView(
                name: ReportData.normalizePath(table),
                columns: const <ReportDataColumnView>[],
                rows: const <List<ReportValue>>[],
              ));
    return t.isFields ? null : t;
  }

  /// Sets cell ([row], [column]) of [table] (default: [dataTable]) from
  /// [text], parsed by the column type; empty text clears it. Returns
  /// whether it changed. Undoable.
  bool setDataCell(int row, int column, String text, {String? table}) {
    final ReportDataTableView t = table == null
        ? dataTable
        : (_view(table) ?? dataTable);
    if (row < 0 ||
        row >= t.rows.length ||
        column < 0 ||
        column >= t.columns.length) {
      return false;
    }
    if (t.isFields) {
      return column == 1 && row < _fieldPaths.length
          ? setDataField(_fieldPaths[row], text)
          : false;
    }
    final ReportDataColumnView col = t.columns[column];
    if (col.isCalculated) {
      _notice = '"${col.name}" is calculated: edit its formula instead';
      notifyListeners();
      return false;
    }
    final (bool ok, Object? value) = _parseValue(text, col.type);
    if (!ok) {
      _notice = '"${text.trim()}" is not a valid ${col.type.name}';
      notifyListeners();
      return false;
    }
    return _editSample((ReportData d) {
      final List<Map<String, Object?>> rows = d.rows(t.name);
      if (row >= rows.length) {
        return false;
      }
      final Map<String, Object?> r = rows[row];
      final String key = _rawKey(r, col.name) ?? col.name;
      if (r.containsKey(key) && r[key] == value) {
        return false;
      }
      r[key] = value;
      _writeShapeCell(t.name, row, col.name, value);
      return true;
    });
  }

  /// Inserts an empty row into [table] (default: [dataTable]) at [at]
  /// (default: after the selected row, else at the end) and selects it.
  /// Undoable.
  bool addDataRow({int? at, String? table}) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null) {
      return false;
    }
    if (shapeKeyForTable(t.name) != null) {
      _notice = 'Rows come from the map file';
      notifyListeners();
      return false;
    }
    return _editSample((ReportData d) {
      final List<Object?> list = _rawList(d, t.name);
      final List<int> positions = _recordPositions(list);
      final int want = at ?? (_dataRow >= 0 ? _dataRow + 1 : positions.length);
      final int index = want.clamp(0, positions.length);
      final int insertAt = index < positions.length
          ? positions[index]
          : list.length;
      list.insert(insertAt, <String, Object?>{
        for (final ReportDataColumnView c in t.columns)
          if (!c.isCalculated) c.name: null,
      });
      _dataTable = t.name;
      _dataRow = index;
      return true;
    });
  }

  /// Deletes [rows] (explorer indices) from [table] (default: [dataTable]).
  /// Undoable.
  bool removeDataRows(Iterable<int> rows, {String? table}) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null) {
      return false;
    }
    if (shapeKeyForTable(t.name) != null) {
      _notice = 'Rows come from the map file';
      notifyListeners();
      return false;
    }
    final List<int> order = rows.toSet().toList()..sort();
    return _editSample((ReportData d) {
      final Object? at = d.get(t.name);
      if (at is! List<Object?>) {
        return false;
      }
      final List<int> positions = _recordPositions(at);
      var any = false;
      for (final int k in order.reversed) {
        if (k >= 0 && k < positions.length) {
          at.removeAt(positions[k]);
          any = true;
        }
      }
      return any;
    });
  }

  /// The schema table of [view], created when missing and completed with
  /// the columns found only in the data (with their inferred types), so the
  /// explorer keeps its column order once the structure is edited.
  ReportDataTable _schemaTable(ReportDataTableView view) {
    final ReportDataSchema schema = _template.dataSchema;
    ReportDataTable? t = schema.table(view.name);
    if (t == null) {
      t = ReportDataTable(name: view.name);
      schema.tables.add(t);
    }
    for (final ReportDataColumnView c in view.columns) {
      if (t.column(c.name) == null) {
        t.columns.add(
          ReportDataColumn(
            name: c.name,
            type: c.type,
            expression: c.expression,
            format: c.format,
            description: c.description,
          ),
        );
      }
    }
    return t;
  }

  /// Runs [edit] as one undo step: on the sample data when it is editable
  /// (also materializing inferred data), else on the template only.
  bool _editStructure(bool Function(ReportData? data) edit) {
    if (hasHostData) {
      var changed = false;
      _mutate(() => changed = edit(null));
      return changed;
    }
    return _editSample(edit);
  }

  String _freeName(Iterable<String> taken, String base) {
    final Set<String> used = <String>{
      for (final String t in taken) t.toLowerCase(),
    };
    for (int i = 1; ; i++) {
      final String candidate = '$base$i';
      if (!used.contains(candidate.toLowerCase())) {
        return candidate;
      }
    }
  }

  bool _rejectName(String name, Iterable<String> taken, String what) {
    if (!ReportData.isValidName(name)) {
      _notice =
          '"$name" is not a valid $what name: start with a letter or _, '
          'then use letters, digits or _';
      notifyListeners();
      return true;
    }
    if (taken.any((String t) => t.toLowerCase() == name.toLowerCase())) {
      _notice = 'A $what named "$name" already exists';
      notifyListeners();
      return true;
    }
    return false;
  }

  /// Adds a column to [table] (default: [dataTable]): stored (empty in
  /// every row) or, with an [expression], calculated per row. Selects it
  /// and returns its name; null when [name] is invalid or taken. Undoable.
  String? addDataColumn({
    String? name,
    ReportDataType type = ReportDataType.text,
    String? expression,
    String? table,
  }) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null) {
      return null;
    }
    final bool calculated = expression != null && expression.trim().isNotEmpty;
    final Iterable<String> taken = t.columns.map(
      (ReportDataColumnView c) => c.name,
    );
    final String n =
        name?.trim() ?? _freeName(taken, calculated ? 'calc' : 'column');
    if (_rejectName(n, taken, 'column')) {
      return null;
    }
    final bool done = _editStructure((ReportData? d) {
      _schemaTable(t).columns.add(
        ReportDataColumn(
          name: n,
          type: type,
          expression: calculated ? expression.trim() : null,
        ),
      );
      if (d != null && !calculated) {
        _rawList(d, t.name);
        for (final Map<String, Object?> r in d.rows(t.name)) {
          r[n] = null;
        }
      }
      return true;
    });
    if (!done) {
      return null;
    }
    _dataTable = t.name;
    _dataRow = -1;
    _dataColumn = t.columns.length;
    notifyListeners();
    return n;
  }

  /// Adds a stored column and writes [value] into every row. Selects it
  /// and returns its name; null when [name] is invalid or taken. Undoable.
  String? addConstantColumn({
    String? name,
    String value = '',
    ReportDataType type = ReportDataType.text,
    String? table,
  }) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null) {
      return null;
    }
    final Iterable<String> taken = t.columns.map(
      (ReportDataColumnView c) => c.name,
    );
    final String n = name?.trim() ?? _freeName(taken, 'constant');
    if (_rejectName(n, taken, 'column')) {
      return null;
    }
    final (bool ok, Object? parsed) = _parseValue(value, type);
    if (!ok) {
      _notice = '"${value.trim()}" is not a valid ${type.name}';
      notifyListeners();
      return null;
    }
    final bool done = _editStructure((ReportData? d) {
      _schemaTable(t).columns.add(ReportDataColumn(name: n, type: type));
      if (d != null) {
        _rawList(d, t.name);
        for (final Map<String, Object?> r in d.rows(t.name)) {
          r[n] = parsed;
        }
      }
      _writeShapeColumn(t.name, n, parsed);
      return true;
    });
    if (!done) {
      return null;
    }
    _dataTable = t.name;
    _dataRow = -1;
    _dataColumn = t.columns.length;
    beginPropertyEdit('data.col.fill');
    return n;
  }

  /// Writes [text] into every row of column [name]. A shape attribute is
  /// written back into the map file as well. Undoable.
  bool fillDataColumn(String name, String text, {String? table}) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null) {
      return false;
    }
    final ReportDataColumnView? col = _columnView(t, name);
    if (col == null || col.isCalculated) {
      return false;
    }
    final (bool ok, Object? value) = _parseValue(text, col.type);
    if (!ok) {
      _notice = '"${text.trim()}" is not a valid ${col.type.name}';
      notifyListeners();
      return false;
    }
    return _editSample((ReportData d) {
      final List<Map<String, Object?>> rows = d.rows(t.name);
      var changed = false;
      for (final Map<String, Object?> r in rows) {
        final String key = _rawKey(r, col.name) ?? col.name;
        if (r[key] != value) {
          r[key] = value;
          changed = true;
        }
      }
      if (!changed && rows.isNotEmpty) {
        return false;
      }
      _writeShapeColumn(t.name, col.name, value);
      return true;
    });
  }

  ReportDataColumnView? _columnView(ReportDataTableView t, String name) {
    final String want = name.trim().toLowerCase();
    for (final ReportDataColumnView c in t.columns) {
      if (c.name.toLowerCase() == want) {
        return c;
      }
    }
    return null;
  }

  /// Removes column [name] from [table] (default: [dataTable]): from the
  /// schema and from every row. Undoable.
  bool removeDataColumn(String name, {String? table}) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null ||
        !t.columns.any(
          (ReportDataColumnView c) =>
              c.name.toLowerCase() == name.toLowerCase(),
        )) {
      return false;
    }
    final bool done = _editStructure((ReportData? d) {
      final ReportDataTable? st = _template.dataSchema.table(t.name);
      st?.columns.removeWhere(
        (ReportDataColumn c) => c.name.toLowerCase() == name.toLowerCase(),
      );
      if (d != null) {
        for (final Map<String, Object?> r in d.rows(t.name)) {
          final String? key = _rawKey(r, name);
          if (key != null) {
            r.remove(key);
          }
        }
      }
      return true;
    });
    if (done) {
      _dataColumn = -1;
      notifyListeners();
    }
    return done;
  }

  /// Renames column [from] of [table] (default: [dataTable]) to [to] in the
  /// schema and every row, and rewrites the layout's bindings
  /// (`item.from`, `items.from`). Undoable.
  bool renameDataColumn(String from, String to, {String? table}) {
    final ReportDataTableView? t = _tableFor(table);
    final String n = to.trim();
    if (t == null || n == from) {
      return false;
    }
    if (_blockedByHost()) {
      return false;
    }
    final Iterable<String> taken = <String>[
      for (final ReportDataColumnView c in t.columns)
        if (c.name.toLowerCase() != from.toLowerCase()) c.name,
    ];
    if (_rejectName(n, taken, 'column')) {
      return false;
    }
    return _editSample((ReportData d) {
      final ReportDataTable st = _schemaTable(t);
      st.column(from)?.name = n;
      final Object? at = d.get(t.name);
      if (at is List<Object?>) {
        for (int i = 0; i < at.length; i++) {
          final Object? r = at[i];
          if (r is Map<String, Object?>) {
            final String? key = _rawKey(r, from);
            if (key != null) {
              at[i] = <String, Object?>{
                for (final MapEntry<String, Object?> e in r.entries)
                  (e.key == key ? n : e.key): e.value,
              };
            }
          }
        }
      }
      _rewriteColumn(t.name, from, n);
      return true;
    });
  }

  /// Sets the type of column [name] of [table] (default: [dataTable]) and
  /// converts its stored values. Undoable.
  bool setDataColumnType(String name, ReportDataType type, {String? table}) {
    final ReportDataTableView? t = _tableFor(table);
    if (t == null) {
      return false;
    }
    return _editStructure((ReportData? d) {
      final ReportDataColumn? c = _schemaTable(t).column(name);
      if (c == null || c.type == type) {
        return false;
      }
      c.type = type;
      if (d != null && !c.isCalculated) {
        for (final Map<String, Object?> r in d.rows(t.name)) {
          final String? key = _rawKey(r, name);
          if (key != null) {
            r[key] = type.coerce(r[key]);
          }
        }
      }
      return true;
    });
