    if (e != null) {
      return _decorate(_elementProps(e), element: true);
    }
    final ReportBand? band = _selectedBand == null
        ? null
        : _template.band(_selectedBand!);
    if (band != null) {
      return _decorate(_bandProps(band), element: false);
    }
    return _decorate(_reportProps(), element: false);
  }

