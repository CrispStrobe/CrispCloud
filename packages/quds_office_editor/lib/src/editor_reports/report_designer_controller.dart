  /// Whether [id] is selected.
  bool isSelected(String id) => _selection.contains(id);

  /// Selects [id] (null clears). [additive] toggles it in the selection.
  void select(String? id, {bool additive = false}) {
    _endEdits();
    if (id == null) {
      if (!additive) {
        _selection.clear();
        _selectedBand = null;
      }
      notifyListeners();
      return;
    }
    if (additive) {
      if (!_selection.remove(id)) {
        _selection.add(id);
      }
    } else if (!(_selection.length > 1 && _selection.contains(id))) {
      _selection
        ..clear()
        ..add(id);
    }
    _selectedBand = _template.findElement(id)?.$1.kind ?? _selectedBand;
    notifyListeners();
  }

  /// Replaces the selection with [ids].
  void selectIds(Iterable<String> ids, {bool additive = false}) {
    _endEdits();
    if (!additive) {
      _selection.clear();
    }
    for (final String id in ids) {
      if (!_selection.contains(id)) {
        _selection.add(id);
      }
    }
    notifyListeners();
  }

  /// Selects a band (clears element selection).
  void selectBand(ReportBandKind? kind) {
    _endEdits();
    _selection.clear();
    _selectedBand = kind;
    notifyListeners();
  }

  /// Selects every element of the selected band, or of the whole report.
  void selectAll() {
    _endEdits();
    _selection.clear();
    final ReportBand? band = _selectedBand == null
        ? null
        : _template.band(_selectedBand!);
    for (final (ReportBand b, ReportElement e) in _template.allElements) {
      if (band == null || identical(b, band)) {
        _selection.add(e.id);
      }
    }
    notifyListeners();
  }

  // ------------------------------------------------------------ geometry

  /// Element box in physical page points; y is relative to its band.
  ReportRect physicalRect(ReportElement e) =>
      ReportRect(_template.elementLeft(e.x, e.width), e.y, e.width, e.height);

  void _setPhysical(ReportElement e, ReportRect r) {
    final double w = r.width < 0 ? 0 : r.width;
    final double h = r.height < 0 ? 0 : r.height;
    e
      ..width = _round(w)
      ..height = _round(h)
      ..x = _round(_template.elementX(r.left, w))
      ..y = _round(r.top < 0 ? 0 : r.top);
  }

  static double _round(double v) => (v * 100).roundToDouble() / 100;

  /// Starts a pointer gesture; edits until [endGesture] form one undo step.
  void beginGesture() {
    _endEdits();
    _gestureBase = _snapshot();
    _gestureChanged = false;
  }

  /// Moves or resizes elements during a gesture (physical, band-relative).
  void gestureSetRects(Map<String, ReportRect> rects) {
    for (final MapEntry<String, ReportRect> entry in rects.entries) {
      final ReportElement? e = _template.findElement(entry.key)?.$2;
      if (e != null) {
        _setPhysical(e, entry.value);
      }
    }
    _gestureChanged = true;
    _changed();
  }

  /// Resizes a band during a gesture.
  void gestureSetBandHeight(ReportBandKind kind, double height) {
    final ReportBand? band = _template.band(kind);
    if (band == null) {
      return;
    }
    band.height = _round(height < 0 ? 0 : height);
    _gestureChanged = true;
    _changed();
  }

  /// Moves element [id] into band [target] at band-relative [top].
  void gestureMoveToBand(String id, ReportBandKind target, double top) {
    final (ReportBand, ReportElement)? found = _template.findElement(id);
    final ReportBand? to = _template.band(target);
    if (found == null || to == null || identical(found.$1, to)) {
      return;
    }
    found.$1.elements.remove(found.$2);
    to.elements.add(found.$2);
    found.$2.y = _round(top < 0 ? 0 : top);
    if (to.height < found.$2.y + found.$2.height) {
      to.height = _round(found.$2.y + found.$2.height);
    }
    _selectedBand = target;
    _gestureChanged = true;
    _changed();
  }

  /// Ends the gesture started by [beginGesture].
  void endGesture() {
    final _Snapshot? base = _gestureBase;
    _gestureBase = null;
    if (base != null && _gestureChanged) {
      _push(base);
    }
    _gestureChanged = false;
    notifyListeners();
  }

  /// Moves the selection by ([dx], [dy]) physical points.
  void nudge(double dx, double dy) {
    final List<ReportElement> sel = selectedElements;
    if (sel.isEmpty) {
      return;
    }
    _mutate(() {
      for (final ReportElement e in sel) {
        final ReportRect r = physicalRect(e);
        _setPhysical(e, ReportRect(r.left + dx, r.top + dy, r.width, r.height));
      }
      return true;
    });
  }

  /// Applies [action] to the selection. With one element, aligns to the
  /// band (vertical) and the printable area (horizontal).
  void align(ReportAlignAction action) {
    final List<ReportElement> sel = selectedElements;
    if (sel.isEmpty) {
      return;
    }
    final List<ReportRect> rects = <ReportRect>[
      for (final ReportElement e in sel) physicalRect(e),
    ];
    double left;
    double top;
    double right;
    double bottom;
    if (sel.length == 1) {
      final ReportBand band = _template.findElement(sel.first.id)!.$1;
      left = _template.margins.left;
      right = _template.pageWidth - _template.margins.right;
      top = 0;
      bottom = band.designHeight;
    } else {
      left = rects.map((ReportRect r) => r.left).reduce(_min);
      top = rects.map((ReportRect r) => r.top).reduce(_min);
      right = rects.map((ReportRect r) => r.right).reduce(_max);
      bottom = rects.map((ReportRect r) => r.bottom).reduce(_max);
    }
    final ReportRect lead = rects.first;
    _mutate(() {
      switch (action) {
        case ReportAlignAction.distributeX:
        case ReportAlignAction.distributeY:
          return _distribute(
            sel,
            rects,
            action == ReportAlignAction.distributeX,
          );
        default:
          break;
      }
      for (int i = 0; i < sel.length; i++) {
        final ReportRect r = rects[i];
        final ReportRect next = switch (action) {
          ReportAlignAction.left => ReportRect(left, r.top, r.width, r.height),
          ReportAlignAction.right => ReportRect(
            right - r.width,
            r.top,
            r.width,
            r.height,
          ),
          ReportAlignAction.centerX => ReportRect(
            (left + right - r.width) / 2,
            r.top,
            r.width,
            r.height,
          ),
          ReportAlignAction.top => ReportRect(r.left, top, r.width, r.height),
          ReportAlignAction.bottom => ReportRect(
            r.left,
            bottom - r.height,
            r.width,
            r.height,
          ),
          ReportAlignAction.middle => ReportRect(
            r.left,
            (top + bottom - r.height) / 2,
            r.width,
            r.height,
          ),
          ReportAlignAction.sameWidth => ReportRect(
            r.left,
            r.top,
            lead.width,
            r.height,
          ),
          ReportAlignAction.sameHeight => ReportRect(
            r.left,
            r.top,
            r.width,
            lead.height,
          ),
          ReportAlignAction.distributeX || ReportAlignAction.distributeY => r,
        };
        _setPhysical(sel[i], next);
      }
      return true;
    });
  }

  bool _distribute(
    List<ReportElement> sel,
    List<ReportRect> rects,
    bool horizontal,
  ) {
    if (sel.length < 3) {
      return false;
    }
    final List<int> order = List<int>.generate(sel.length, (int i) => i)
      ..sort(
        (int a, int b) => horizontal
            ? rects[a].left.compareTo(rects[b].left)
            : rects[a].top.compareTo(rects[b].top),
      );
    final ReportRect first = rects[order.first];
    final ReportRect last = rects[order.last];
    var occupied = 0.0;
    for (final ReportRect r in rects) {
      occupied += horizontal ? r.width : r.height;
    }
    final double span = horizontal
        ? last.right - first.left
        : last.bottom - first.top;
    final double gap = (span - occupied) / (sel.length - 1);
    var cursor = horizontal ? first.left : first.top;
    for (final int i in order) {
      final ReportRect r = rects[i];
      _setPhysical(
        sel[i],
        horizontal
            ? ReportRect(cursor, r.top, r.width, r.height)
            : ReportRect(r.left, cursor, r.width, r.height),
      );
      cursor += (horizontal ? r.width : r.height) + gap;
    }
    return true;
  }

  static double _min(double a, double b) => a < b ? a : b;

  static double _max(double a, double b) => a > b ? a : b;

