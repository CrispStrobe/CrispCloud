    if (_mode == ReportDesignMode.data &&
        _inspectorPage == ReportInspectorPage.properties) {
      return _decorate(_dataProps(), element: false);
    }
    switch (_inspectorPage) {
      case ReportInspectorPage.variables:
        return _decorate(_variableProps(_template), element: false);
      case ReportInspectorPage.images:
        return _decorate(_imageProps(), element: false);
      case ReportInspectorPage.fonts:
        return _fontProps();
      case ReportInspectorPage.properties:
        break;
