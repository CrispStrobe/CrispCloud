  bool _applyChart(ReportChartElement e, String key, String v) {
    final List<String> dot = key.split('.');
    if (dot.length == 2 &&
        (dot[0] == 'title' || dot[0] == 'labels' || dot[0] == 'legend')) {
      final ReportTextStyle style = switch (dot[0]) {
        'title' => e.titleStyle,
        'labels' => e.labelStyle,
        _ => e.legendStyle,
      };
      switch (dot[1]) {
        case 'fontFamily':
          style.fontFamily = _opt(v);
        case 'fontSize':
          if (v.trim().isEmpty) {
            style.fontSize = null;
            return true;
          }
          final double? n = _parseNum(v);
          if (n == null || n <= 0) {
            return false;
          }
          style.fontSize = n;
        case 'bold':
          style.bold = _parseBool(v);
        case 'italic':
          style.italic = _parseBool(v);
        case 'color':
          style.color = _opt(v);
        default:
          return false;
      }
      return true;
    }
    final List<String> parts = key.split('.');
    if (parts.length == 3) {
      final int? i = int.tryParse(parts[1]);
      if (i == null || i < 0) {
        return false;
      }
      if (parts[0] == 'series' && i < e.series.length) {
        final ReportChartSeries s = e.series[i];
        switch (parts[2]) {
          case 'name':
            s.name = v;
          case 'value':
            if (v.trim().isEmpty) {
              return false;
            }
            s.value = v.trim();
          case 'color':
            s.color = _opt(v);
          case 'x':
            s.x = _opt(v);
          case 'size':
            s.size = _opt(v);
          case 'style':
            final ReportSeriesStyle? style = reportEnumByName(
              ReportSeriesStyle.values,
              v,
            );
            if (style == null) {
              return false;
            }
            s.style = style;
          case 'secondary':
            s.secondary = _parseBool(v);
          default:
            return false;
        }
        return true;
      }
      if (parts[0] == 'point' && i < e.points.length) {
        final ReportChartPoint p = e.points[i];
        switch (parts[2]) {
          case 'label':
            p.label = v;
          case 'value':
            if (v.trim().isEmpty) {
              return false;
            }
            p.value = v.trim();
          case 'color':
            p.color = _opt(v);
          case 'x':
            p.x = _opt(v);
          case 'size':
