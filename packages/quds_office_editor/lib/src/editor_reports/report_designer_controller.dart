  /// Imports a data file: CSV rows replace the rows of the selected table
  /// (a new table named after the file while the fields are shown); a JSON
  /// object replaces the sample data and a JSON array of objects the rows
  /// of the table. Returns whether it imported; [notice] explains a
  /// failure. Undoable.
  bool importDataText(String fileName, String text) {
    if (_blockedByHost()) {
      return false;
    }
    final String lower = fileName.toLowerCase();
    final ReportDataTableView view = dataTable;
    String target() {
      if (!view.isFields) {
        return view.name;
      }
      var stem = fileName.split(RegExp(r'[\\/]')).last;
      final int dot = stem.lastIndexOf('.');
      if (dot > 0) {
        stem = stem.substring(0, dot);
      }
      stem = stem.replaceAll(RegExp('[^$_identChar]+'), '_');
      if (stem.isEmpty || RegExp('^[0-9_]').hasMatch(stem)) {
        stem = 'table$stem';
      }
      final Iterable<String> taken = dataTables.map(
        (ReportDataTableView t) => t.name,
      );
      return taken.any((String t) => t.toLowerCase() == stem.toLowerCase())
          ? _freeName(taken, stem)
          : stem;
    }

    try {
      if (lower.endsWith('.csv') ||
          lower.endsWith('.tsv') ||
          lower.endsWith('.txt')) {
        return _importRows(
          target(),
          ReportCsv.rows(text, delimiter: lower.endsWith('.tsv') ? '\t' : null),
        );
      }
      final Object? decoded = ReportData.fromJsonValue(
        jsonDecode(text.startsWith('\uFEFF') ? text.substring(1) : text),
      );
      if (decoded is Map<String, Object?>) {
        setSampleData(decoded);
        _dataTable = null;
        _dataRow = -1;
        _dataColumn = -1;
        notifyListeners();
        return true;
      }
      if (decoded is List<Object?> &&
          decoded.every((Object? x) => x is Map<String, Object?>)) {
        return _importRows(target(), <Map<String, Object?>>[
          for (final Object? x in decoded)
            if (x is Map<String, Object?>) x,
        ]);
      }
      _notice = 'JSON data must be an object or an array of objects';
    } on ReportDataException catch (e) {
      _notice = e.message;
    } on FormatException catch (e) {
      _notice = 'Invalid JSON: ${e.message}';
    }
    notifyListeners();
    return false;
  }

  bool _importRows(String table, List<Map<String, Object?>> rows) {
    final bool done = _editSample((ReportData d) {
      d.setTable(table, <Map<String, Object?>>[
        for (final Map<String, Object?> r in rows) _revive(r),
      ]);
      return true;
    });
    if (done) {
      _dataTable = table;
      _dataRow = -1;
      _dataColumn = -1;
      _notice =
          'Imported ${rows.length} row${rows.length == 1 ? '' : 's'} '
          'into $table';
      notifyListeners();
    }
    return done;
  }

  /// Asks [dataPicker] for a file and imports it ([importDataText]).
  Future<bool> importDataFile() async {
    final ReportDataPicker? picker = dataPicker;
    if (picker == null) {
      return false;
    }
    final ({String name, String text})? file = await picker();
    if (file == null || _disposed) {
      return false;
    }
    return importDataText(file.name, file.text);
  }

  void _rewriteElement(ReportElement e, String Function(String) f) {
    final String? when = e.visibleWhen;
    if (when != null) {
      e.visibleWhen = f(when);
    }
    String? opt(String? s) => s == null ? null : f(s);
    switch (e) {
      case ReportTextElement():
        e.text = f(e.text);
      case ReportImageElement():
        e.source = f(e.source);
      case ReportBarcodeElement():
        e.data = f(e.data);
      case ReportShapeElement():
        break;
      case ReportTableElement():
        for (final ReportTableColumn c in e.columns) {
          c.header = f(c.header);
        }
        for (final ReportTableCell c in <ReportTableCell>[
          ...e.cells,
          ...e.footerCells,
        ]) {
          c
            ..field = opt(c.field)
            ..text = opt(c.text);
        }
      case ReportChartElement():
        e
          ..title = f(e.title)
          ..category = opt(e.category);
        for (final ReportChartSeries s in e.series) {
          s
            ..name = f(s.name)
            ..value = f(s.value);
        }
        for (final ReportChartPoint p in e.points) {
          p
            ..label = f(p.label)
            ..value = f(p.value);
        }
      case ReportCrosstabElement():
        e
          ..rowField = f(e.rowField)
          ..columnField = f(e.columnField)
          ..valueField = f(e.valueField)
          ..dataSet = opt(e.dataSet);
      case ReportSubreportElement():
        e.dataSet = opt(e.dataSet);
    }
  }

  void _rewriteColumn(String table, String from, String to) {
    const String before = '(?<![$_identChar.])';
    const String after = '(?![$_identChar])';
    final String t = RegExp.escape(table);
    final String c = RegExp.escape(from);
    final RegExp member = RegExp(
      '$before((?:Data\\.)?$t)\\.$c$after',
      caseSensitive: false,
    );
    final RegExp rowRef = RegExp(
      '$before(item|row|record)\\.$c$after',
      caseSensitive: false,
    );
    String all(String s) =>
        s.replaceAllMapped(member, (Match m) => '${m.group(1)}.$to');
    String rows(String s) =>
        all(s).replaceAllMapped(rowRef, (Match m) => '${m.group(1)}.$to');
    final String key = table.toLowerCase();
    final String detail = ReportData.normalizePath(
      _template.detail?.dataSet ?? '',
    ).toLowerCase();
    for (final ReportBand band in _template.bands) {
      final String Function(String) bandFn = detail == key ? rows : all;
      String? opt(String? s) => s == null ? null : bandFn(s);
      band
        ..groupBy = opt(band.groupBy)
        ..sortBy = opt(band.sortBy)
        ..filter = opt(band.filter)
        ..visibleWhen = opt(band.visibleWhen);
      for (final ReportElement e in band.elements) {
        final String? own = switch (e) {
          ReportTableElement(:final String? dataSet) => dataSet,
          ReportChartElement(:final String? dataSet) => dataSet,
          _ => null,
        };
        final String scope = own != null && own.trim().isNotEmpty
            ? ReportData.normalizePath(own).toLowerCase()
            : detail;
        _rewriteElement(e, scope == key ? rows : all);
      }
    }
    final RegExp bare = RegExp('$before$c$after(?!\\s*\\()');
    for (final ReportDataColumn col
        in _template.dataSchema.table(table)?.columns ?? <ReportDataColumn>[]) {
      final String? x = col.expression;
      if (x != null) {
        col.expression = rows(x).replaceAll(bare, to);
      }
    }
  }

  void _rewriteField(String from, String to) {
    const String before = '(?<![$_identChar.])';
    const String after = '(?![$_identChar])';
    final RegExp re = RegExp(
      '$before(Data\\.)?${RegExp.escape(from)}$after(?!\\s*\\()',
      caseSensitive: false,
    );
    String f(String s) =>
        s.replaceAllMapped(re, (Match m) => '${m.group(1) ?? ''}$to');
    for (final ReportBand band in _template.bands) {
      String? opt(String? s) => s == null ? null : f(s);
      band
        ..groupBy = opt(band.groupBy)
        ..sortBy = opt(band.sortBy)
        ..filter = opt(band.filter)
        ..visibleWhen = opt(band.visibleWhen);
      for (final ReportElement e in band.elements) {
        _rewriteElement(e, f);
      }
    }
  }

