  /// Lists [deviceFonts] once; later calls reuse the list.
  Future<void> loadDeviceFamilies() async {
    final ReportDeviceFonts? source = _deviceFonts;
    if (source == null || _deviceFamilies != null || _deviceLoading) {
      return;
    }
    _deviceLoading = true;
    _deviceError = null;
    List<String>? list;
    Object? error;
    try {
      list = await source.families();
      if (source is ReportDeviceFontScripts) {
        _deviceScripts = await (source as ReportDeviceFontScripts).scripts();
      }
    } on Object catch (e) {
      error = e;
    }
    if (_disposed || !identical(source, _deviceFonts)) {
      return;
    }
    _deviceLoading = false;
    _deviceFamilies = list == null ? null : List<String>.unmodifiable(list);
    _deviceError = error;
    notifyListeners();
  }

  void _loadDeviceFamilies() => unawaited(loadDeviceFamilies());

  /// Embeds the TrueType face [bytes] under the family it declares, in its
  /// regular or bold slot (replacing a face already there), and returns the
  /// family. Undoable.
  ///
  /// Throws [ReportFontException] for files reports cannot use: collections,
  /// CFF outlines (`.otf`), italic faces, and fonts whose license forbids
  /// embedding.
  String addFont(Uint8List bytes) {
    final ReportFontFileInfo info = _uprightFace(bytes);
    _mutate(() {
      _putFace(info, bytes);
      return true;
    });
    return info.family;
  }

  /// Embeds [files] as [family], replacing any embedded faces of that
  /// family. Undoable. Throws [ReportFontException] like [addFont], or when
  /// [family] cannot name a package folder.
  void embedFont(String family, ReportFontFiles files) {
    if (!ReportPackage.isValidFontFamily(family)) {
      throw ReportFontException('"$family" cannot be used as a family name');
    }
    for (final Uint8List? face in <Uint8List?>[files.regular, files.bold]) {
      if (face != null) {
        _uprightFace(face);
      }
    }
    _mutate(() {
      embeddedFonts[family] = files;
      _fontsRevision++;
      return true;
    });
  }

  /// Removes embedded family [family]; text that uses it falls back to the
  /// host fonts. Returns whether it existed. Undoable.
  bool removeFont(String family) {
    if (!embeddedFonts.containsKey(family)) {
      return false;
    }
    _mutate(() {
      _fontsRevision++;
      return embeddedFonts.remove(family) != null;
    });
    return true;
  }

  /// Asks [fontPicker] for files and embeds them ([addFont]) as one undo
  /// step; returns the families added. Unusable files are skipped and
  /// reported in [notice].
  Future<List<String>> importFonts() async {
    final ReportFontPicker? picker = fontPicker;
    if (picker == null) {
      return const <String>[];
    }
    final List<({String name, Uint8List bytes})>? files = await picker();
    if (files == null || files.isEmpty || _disposed) {
      return const <String>[];
    }
    final List<(ReportFontFileInfo, Uint8List)> faces =
        <(ReportFontFileInfo, Uint8List)>[];
    final List<String> errors = <String>[];
    for (final ({String name, Uint8List bytes}) file in files) {
      try {
        faces.add((_uprightFace(file.bytes), file.bytes));
      } on ReportFontException catch (e) {
        errors.add('${file.name}: ${e.message}');
      }
    }
    final List<String> added = <String>[
      ...<String>{
        for (final (ReportFontFileInfo info, _) in faces) info.family,
      },
    ];
    if (faces.isNotEmpty) {
      _mutate(() {
        for (final (ReportFontFileInfo info, Uint8List bytes) in faces) {
          _putFace(info, bytes);
        }
        return true;
      });
    }
    _notice = <String>[
      if (added.isNotEmpty) 'Embedded ${added.join(', ')}',
      ...errors,
    ].join('  ·  ');
    notifyListeners();
    return added;
  }

  /// Loads [family] from [deviceFonts] and embeds it ([embedFont]); returns
  /// whether it was embedded. The outcome is reported in [notice].
  Future<bool> embedDeviceFont(String family) async {
    final ReportDeviceFonts? source = _deviceFonts;
    if (source == null || !_embedding.add(family)) {
      return false;
    }
    notifyListeners();
    String message;
    var ok = false;
    try {
      final ReportFontFiles? files = await source.load(family);
      if (_disposed) {
        return false;
      }
      if (files == null) {
        message = '$family has no regular or bold TrueType face';
      } else {
        embedFont(family, files);
        ok = true;
        message =
            'Embedded $family (${_faceNames(files)}, '
            '${_byteSize(files.byteLength)})';
      }
    } on Object catch (e) {
      if (_disposed) {
        return false;
      }
      message =
          'Could not embed $family: '
          '${e is ReportFontException ? e.message : e}';
    }
    _embedding.remove(family);
    _notice = message;
    notifyListeners();
    return ok;
  }

  /// Embeds [family] from the device when a font field names an installed
  /// family that neither the host nor the report has.
  Future<void> _embedIfInstalled(String family) async {
    if (_deviceFonts == null ||
        family.isEmpty ||
        embeddedFonts.containsKey(family) ||
        fonts.has(family)) {
      return;
    }
    await loadDeviceFamilies();
    if (!_disposed && (_deviceFamilies?.contains(family) ?? false)) {
      await embedDeviceFont(family);
    }
  }

  ReportFontFileInfo _uprightFace(Uint8List bytes) {
    final ReportFontFileInfo info = ReportFontFile.inspect(bytes);
    if (!ReportPackage.isValidFontFamily(info.family)) {
      throw ReportFontException(
        '"${info.family}" cannot be used as a family name',
      );
    }
    return info;
  }

  void _putFace(ReportFontFileInfo info, Uint8List bytes) {
    final ReportFontFiles? old = embeddedFonts[info.family];
    embeddedFonts[info.family] = old == null
        ? ReportFontFiles(
            regular: !info.bold && !info.italic ? bytes : null,
            bold: info.bold && !info.italic ? bytes : null,
            italic: !info.bold && info.italic ? bytes : null,
            boldItalic: info.bold && info.italic ? bytes : null,
          )
        : old.withFace(bytes, bold: info.bold, italic: info.italic);
    _fontsRevision++;
  }

  static String _faceNames(ReportFontFiles f) => <String>[
    if (f.regular != null) 'Regular',
    if (f.bold != null) 'Bold',
    if (f.italic != null) 'Italic',
    if (f.boldItalic != null) 'Bold Italic',
  ].join(' + ');

  static String _byteSize(int bytes) {
    if (bytes < 1024) {
      return '$bytes B';
    }
    if (bytes < 1024 * 1024) {
      return '${(bytes / 1024).toStringAsFixed(bytes < 10240 ? 1 : 0)} KB';
    }
    return '${(bytes / (1024 * 1024)).toStringAsFixed(1)} MB';
  }

  int _fontUses(String family) {
    var n = 0;
    for (final (ReportBand _, ReportElement e) in _template.allElements) {
      final String? f = switch (e) {
        ReportTextElement(:final ReportTextStyle style) => style.fontFamily,
        ReportChartElement(:final String? fontFamily) => fontFamily,
        _ => null,
      };
      if (f?.trim() == family) {
        n++;
      }
    }
    return n;
  }

