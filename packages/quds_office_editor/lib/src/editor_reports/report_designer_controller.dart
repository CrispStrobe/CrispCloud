  bool _rename(ReportElement e, String requested) {
    if (selectedElements.length > 1) {
      _notice = 'Select a single element to rename it';
      return false;
    }
    final String name = requested.isEmpty
        ? _template.uniqueElementName(e.namePrefix, except: e)
        : requested;
    if (name == e.name) {
      return false;
    }
    if (!ReportTemplate.isValidElementName(name)) {
      _notice =
          '"$name" is not a valid name: start with a letter or _, then use '
          'letters, digits or _';
      return false;
    }
    final (ReportBand, ReportElement)? other = _template.elementNamed(name);
    if (other != null && !identical(other.$2, e)) {
      _notice = 'Another element is already named "${other.$2.name}"';
      return false;
    }
    e.name = name;
    return true;
  }

