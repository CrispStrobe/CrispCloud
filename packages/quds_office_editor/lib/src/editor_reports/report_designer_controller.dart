  /// Handles the data explorer keys of [setProperty]; returns whether [key]
  /// was one.
  bool _setDataProperty(String key, String value) {
    final RegExpMatch? cell = _cellKey.firstMatch(key);
    if (cell != null) {
      setDataCell(int.parse(cell.group(1)!), int.parse(cell.group(2)!), value);
      notifyListeners();
