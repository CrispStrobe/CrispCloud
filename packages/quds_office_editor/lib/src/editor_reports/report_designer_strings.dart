  static const ReportDesignerStrings fr = ReportDesignerStrings._("fr", _fr);
  static const ReportDesignerStrings es = ReportDesignerStrings._("es", _es);
  static const ReportDesignerStrings pt = ReportDesignerStrings._("pt", _pt);
  static const ReportDesignerStrings zh = ReportDesignerStrings._("zh", _zh);
  static const ReportDesignerStrings ja = ReportDesignerStrings._("ja", _ja);
  static const ReportDesignerStrings ko = ReportDesignerStrings._("ko", _ko);

  /// Languages with a translation.
  static const List<ReportDesignerStrings> all = <ReportDesignerStrings>[
    english,
    arabic,
    de,
    fr,
    es,
    pt,
    zh,
    ja,
    ko,
  ];

  /// Strings for [locale]; English when the language has no translation.
  static ReportDesignerStrings forLocale(Locale? locale) {
    for (final ReportDesignerStrings s in all) {
      if (s.languageCode == locale?.languageCode) {
        return s;
      }
    }
    return english;
  }

  /// ISO 639-1 language code.
  final String languageCode;

  final Map<String, String> _table;

  /// Locale of this language.
  Locale get locale => Locale(languageCode);

  /// Whether the interface reads right to left.
  bool get isRtl => languageCode == 'ar';

  /// Reading direction of the interface.
  TextDirection get direction => isRtl ? TextDirection.rtl : TextDirection.ltr;

  /// English source labels explicitly covered by this language.
  Iterable<String> get translatedKeys => _table.keys;

  /// Translation of the English label [english].
  String t(String english) => _table[english] ?? english;

  static final RegExp _sourceTail = RegExp(r'^(.*?) in "(.*)"(?: at (\d+))?$');

  /// Translates known diagnostics, preserving names, values and source text.
  /// Unknown provider or parser messages remain unchanged.
  String diagnostic(String summary) {
    if (languageCode == 'en') return summary;
    // Remove only known engine wrappers; unknown errors keep their full text.
    var message = summary;
    var assetError = false;
    for (final prefix in const [
      'ReportFormatException: ',
      'ReportExpressionException: ',
      'ReportPackageException: ',
      'ReportFontException: ',
      'ReportShapeException: ',
    ]) {
      if (message.startsWith(prefix)) {
        message = message.substring(prefix.length);
        assetError =
            prefix == 'ReportPackageException: ' ||
            prefix == 'ReportFontException: ' ||
            prefix == 'ReportShapeException: ';
        break;
      }
    }
    final whole =
        (assetError
            ? localizeReportAssetMessage(languageCode, message)
            : null) ??
        _table[message] ??
        _dynamicDiagnostic(message);
    if (whole != null) return whole;

    final source = _sourceTail.firstMatch(message);
    final head = source?.group(1) ?? message;
    final translated = _table[head] ?? _dynamicDiagnostic(head);
    if (translated == null) return summary;
    if (source == null) return translated;
    final at = source.group(3);
    return '$translated ${t('in')} "${source.group(2)}"'
        '${at == null ? '' : ' ${t('at character')} $at'}';
  }

  /// Localizes recognized import and embedding notices, preserving names.
  String assetNotice(String message) {
    if (languageCode == 'en') return message;
    return localizeReportAssetMessage(languageCode, message) ??
        diagnostic(message);
  }

  String? _dynamicDiagnostic(String message) {
    for (final (pattern, template) in _dynamicPatterns) {
      final match = pattern.firstMatch(message);
      if (match == null) continue;
      return t(template).replaceAllMapped(RegExp(r'\{(\d+)\}'), (placeholder) {
        final index = int.parse(placeholder.group(1)!);
        return index < match.groupCount
            ? (match.group(index + 1) ?? '')
            : placeholder.group(0)!;
      });
    }
    return null;
  }

