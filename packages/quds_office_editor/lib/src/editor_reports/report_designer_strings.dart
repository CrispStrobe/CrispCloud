  /// Formats a translated template without treating inserted text as a template.
  String format(String template, Map<String, Object?> values) => t(template)
      .replaceAllMapped(RegExp(r'\{([A-Za-z][A-Za-z0-9_]*)\}'), (match) {
        final name = match.group(1)!;
        return values.containsKey(name) ? '${values[name]}' : match.group(0)!;
      });

  /// Localizes generated inspector headings while preserving user names.
  String inspectorTitle(String raw, {required bool objectSelected}) {
    if (objectSelected) return raw;
    final many = RegExp(r'^(\d+) elements$').firstMatch(raw);
    if (many != null) return count(int.parse(many[1]!), 'element');
    final colon = raw.indexOf(': ');
    if (colon <= 0) return t(raw);
    final head = raw.substring(0, colon);
    var tail = raw.substring(colon + 2);
    if (head == 'Band') {
      final spaced = tail.replaceAllMapped(
        RegExp(r'([a-z])([A-Z])'),
        (match) => '${match[1]} ${match[2]!.toLowerCase()}',
      );
      tail = spaced.isEmpty
          ? spaced
          : spaced[0].toUpperCase() + spaced.substring(1);
      tail = t(tail);
    }
    return '${t(head)}: $tail';
  }

  /// `3 elements`: [n] with the plural of [noun], an English singular noun
  /// with a known plural in this table (`element`, `variable`, …).
  String count(int n, String noun) {
    final _Plural? p = _plurals[noun];
    if (p == null) {
      return '$n $noun';
    }
    if (!isRtl) {
      final forms = _localizedCounts[languageCode]?[noun];
      if (forms == null) return '$n ${n == 1 ? noun : p.english}';
      final singular =
          n == 1 || ((languageCode == 'fr' || languageCode == 'pt') && n == 0);
      final word = singular ? forms.$1 : forms.$2;
      final separator = languageCode == 'zh' || languageCode == 'ja' ? '' : ' ';
      return '$n$separator$word';
    }
    if (n == 0) {
      return '0 ${p.many}';
    }
    if (n == 1) {
      return '${p.one} ${p.oneSuffix}'.trim();
    }
    if (n == 2) {
      return p.two;
    }
    if (n <= 10) {
      return '$n ${p.few}';
    }
    return '$n ${p.many}';
  }

  /// Label of an enum option or keyword (`contain`, `rtl`, `qr`).
  String option(String option) {
    if (option.isEmpty) {
      return t('None');
    }
    final String? direct = _table[option];
    if (direct != null) {
      return direct;
    }
    switch (option) {
      case 'rtl' || 'ltr' || 'qr' || 'pt' || 'mm' || 'cm' || 'px':
        return t(option.toUpperCase());
      case 'inch':
        return t('IN');
    }
    final String spaced = option.replaceAllMapped(
      RegExp('([a-z])([A-Z0-9])'),
      (Match m) => '${m[1]} ${m[2]!.toLowerCase()}',
    );
    return t(spaced[0].toUpperCase() + spaced.substring(1));
  }

