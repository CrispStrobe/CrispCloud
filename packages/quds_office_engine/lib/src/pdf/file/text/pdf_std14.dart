  /// WinAnsi byte for [codePoint], or null if it is outside the encoding.
  ///
  /// Unassigned WinAnsi slots (decoded as U+0020) are not used as a reverse map.
  static int? winAnsiByte(int codePoint) {
    if (codePoint >= 0x20 && codePoint <= 0x7E) {
      return codePoint;
    }
    return _winAnsiReverse[codePoint];
  }

  static final Map<int, int> _winAnsiReverse = <int, int>{
    for (int i = 0; i < _winAnsi.length; i++)
      if (_winAnsi[i] != 0x20) _winAnsi[i]: 0x80 + i,
  };

  /// Unicode for a simple-font byte under [encoding] (`WinAnsiEncoding`, …).
  static int unicode(int byte, String encoding) {
    final int b = byte & 0xFF;
    if (b < 128) {
      return b;
    }
    final List<int> table = switch (encoding) {
      'MacRomanEncoding' => _macRoman,
      'PDFDocEncoding' => _pdfDoc,
      _ => _winAnsi,
    };
    final int i = b - 128;
    return i < table.length ? table[i] : b;
  }

  /// Width in thousandths of an em for [code] (byte or Unicode ASCII).
  static int width(String baseFont, int code) {
    final String n = _canon(baseFont);
    if (n.startsWith('courier')) {
      return 600;
    }
    final List<int> row = switch (n) {
      'helvetica-bold' || 'helvetica-boldoblique' => _helvBold,
      'times-bold' || 'times-bolditalic' => _timesBold,
      'times-roman' || 'times-italic' || 'times' => _times,
      'symbol' => _symbol,
      'zapfdingbats' => _zapf,
      _ => _helv,
    };
    if (code >= 32 && code < 32 + row.length) {
      final int w = row[code - 32];
      return w == 0 ? 500 : w;
    }
    return 500;
  }

  static String _canon(String name) {
    var n = name.toLowerCase();
    if (n.contains('+')) {
      n = n.substring(n.lastIndexOf('+') + 1);
    }
    return n.replaceAll(' ', '');
  }

