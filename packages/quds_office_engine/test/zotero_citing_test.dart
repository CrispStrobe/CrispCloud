          _command('Field.setText', [_doc, 'f1', 'Must not dispatch', true]),
          _command('Document.activate', [_doc]),
          _complete(),
        ];
        await expectLater(() async {
          await _run(
            (request) async {
              requests.add(request);
              return replies.removeAt(0);
            },
            handler: (name, args) {
              handled.add(name);
              switch (name) {
                case 'Document.getFields':
                  return [_field('f1')];
                case 'Field.setText':
                  stagedText = args[2] as String;
                  return null;
                case 'Document.displayAlert':
                  return answer;
                default:
                  fail('A command was dispatched after the desktop error.');
              }
            },
          );
          committed = true;
        }, throwsA(_failure(ZoteroCitingErrorKind.document)));
        expect(stagedText, 'Partial update');
        expect(committed, isFalse);
        expect(handled, [
          'Document.getFields',
          'Field.setText',
          'Document.displayAlert',
        ]);
        expect(replies, isEmpty);
        expect(requests.length, 6);
        expect(requests[3].body, '$answer');
        final abort = jsonDecode(requests[4].body!) as Map;
        expect(abort['error'], 'Alert');
        expect(requests[5].body, 'null');
        expect(
