      'desktop error buttons=$buttons answer=$answer discards partial work after complete',
      () async {
        final requests = <ZoteroHttpRequest>[];
        final handled = <String>[];
        var stagedText = 'Original';
        var committed = false;
        final replies = [
          _command('Document.getFields', [_doc, 'Http']),
          _command('Field.setText', [_doc, 'f1', 'Partial update', true]),
          _command('Document.displayAlert', [
            _doc,
            'Zotero processing failed',
