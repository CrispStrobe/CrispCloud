#!/usr/bin/env python3
"""Precompute Camel Morph analyses for the Arabic grammar-rule checks.

Development tool only (the app never runs Python). Two modes:

  analyze: read words (one per line), analyze each with the camel_tools
  reference analyzer over a Camel Morph MSA database (the `noprob` variant)
  and merge compact feature maps into a JSON file (word -> analyses):

    python3 export_arabic_morph_analyses.py analyze DB WORDS JSON

  dart: write the analyses of a JSON file as a Dart test fixture:

    python3 export_arabic_morph_analyses.py dart JSON OUT.dart

Only features the rules read are kept; duplicate analyses are dropped.
Analyses are data derived from Camel Morph MSA v1.0 (c) 2024 New York
University Abu Dhabi, CC BY 4.0. Corpus text and corpus analyses are
evaluation data and stay outside the repository; only analyses of our own
test sentences may be committed as a fixture.
"""
import json
import os
import sys

KEYS = ['lex', 'pos', 'gen', 'num', 'cas', 'stt', 'mod', 'asp', 'per',
        'form_gen', 'form_num', 'prc0', 'prc1', 'prc2', 'prc3', 'enc0']


def analyze(db_path, words_path, json_path):
    from camel_tools.morphology.analyzer import Analyzer
    from camel_tools.morphology.database import MorphologyDB
    analyzer = Analyzer(MorphologyDB(db_path))
    data = {}
    if os.path.exists(json_path):
        with open(json_path, encoding='utf-8') as f:
            data = json.load(f)
    with open(words_path, encoding='utf-8') as f:
        words = [w for w in f.read().split('\n') if w]
    count = 0
    for word in words:
        if word in data:
            continue
        out, seen = [], set()
        for a in analyzer.analyze(word):
            d = {k: a[k] for k in KEYS if a.get(k) not in (None, '0', 'na', '')}
            key = json.dumps(d, sort_keys=True, ensure_ascii=False)
            if key not in seen:
                seen.add(key)
                out.append(d)
        data[word] = out
        count += 1
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, separators=(',', ':'),
                  sort_keys=True)
    print('analyzed', count, 'total', len(data))


def _dart_string(value):
    return value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')


def dart(json_path, out_path):
    with open(json_path, encoding='utf-8') as f:
        data = json.load(f)
    lines = [
        '// GENERATED by tool/proofing/export_arabic_morph_analyses.py; do not',
        '// edit. Analyses of the words of our own test sentences, produced by',
        '// the camel_tools analyzer over Camel Morph MSA v1.0 (noprob).',
        '// Camel Morph MSA v1.0 (c) 2024 New York University Abu Dhabi,',
        '// licensed under CC BY 4.0.',
        '//',
        '// Each analysis is one string of `|`-separated values in the order of',
        '// [arabicGrammarFixtureKeys]; an empty value is an absent feature.',
        '',
        'const List<String> arabicGrammarFixtureKeys = <String>[',
        *[f"  '{k}'," for k in KEYS],
        '];',
        '',
        'const Map<String, List<String>> arabicGrammarFixture =',
        '    <String, List<String>>{',
    ]
    for word in sorted(data):
        lines.append(f"      '{_dart_string(word)}': <String>[")
        for a in data[word]:
            row = '|'.join(str(a.get(k, '')) for k in KEYS)
            lines.append(f"        '{_dart_string(row)}',")
        lines.append('      ],')
    lines.append('    };')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    if len(sys.argv) == 5 and sys.argv[1] == 'analyze':
        analyze(*sys.argv[2:])
    elif len(sys.argv) == 4 and sys.argv[1] == 'dart':
        dart(*sys.argv[2:])
    else:
        sys.exit(__doc__)
