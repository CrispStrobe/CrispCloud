#!/usr/bin/env python3
"""Reproduce the English Dart patterns and original notices, without network I/O."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
PINNED = {
    'en-US': ('f4ffcd96c5cbc886bdad23f95dcae8edc3cd3620eae62f7946eceda97c4e68f8', 4938, 14),
    'en-GB': ('e95bb4ab350f620c41c231c4785d7bdb4f91949d3e631b30e08b3ead3c340a52', 8527, 8),
}
NOTICES = {
    'en-US': 'ENGLISH_US_LICENSE',
    'en-GB': 'ENGLISH_GB_LICENSE',
}


def pinned_source(entry):
    raw = (ROOT / 'third_party/hyphenation' / entry['source']).read_bytes()
    digest = PINNED[entry['language']][0]
    if hashlib.sha256(raw).hexdigest() != digest or entry['source_sha256'] != digest:
        raise ValueError('Unreviewed source; inspect the original license and provenance first')
    return raw


def original_notice(entry):
    # Keep every byte before the pattern section, including original TeX
    # comments, copyright, permission, provenance and word-list restrictions.
    # Hosts can bundle these small files without shipping the pattern sources.
    preface, marker, _ = pinned_source(entry).partition(b'\\patterns{')
    if not marker or not preface:
        raise ValueError('Missing original source preface')
    return preface


def generate(entry):
    raw = pinned_source(entry)
    _, pattern_count, exception_count = PINNED[entry['language']]
    source = raw.decode('utf-8')
    clean = re.sub(r'%[^\n]*', '', source)
    pattern_blocks = re.findall(r'\\patterns\{([^}]*)\}', clean)
    exception_blocks = re.findall(r'\\hyphenation\{([^}]*)\}', clean)
    if len(pattern_blocks) != 1 or len(exception_blocks) != 1:
        raise ValueError('Unexpected TeX pattern or exception structure')
    patterns = pattern_blocks[0].split()
    exceptions = exception_blocks[0].split()
    if len(patterns) != pattern_count or len(exceptions) != exception_count:
        raise ValueError('Unexpected pattern or exception count')
    if any(re.fullmatch(r'[a-z0-9.]+', item) is None for item in patterns):
        raise ValueError('Unsupported pattern syntax')
    if any(re.fullmatch(r'[a-z]+(?:-[a-z]+)*', item) is None for item in exceptions):
        raise ValueError('Unsupported exception syntax')
    if len({re.sub(r'\d', '', item) for item in patterns}) != len(patterns):
        raise ValueError('Duplicate pattern keys require an explicit review')
    if len({item.replace('-', '') for item in exceptions}) != len(exceptions):
        raise ValueError('Duplicate exceptions')
    if (entry['patterns'], entry['exceptions'], entry['left_min'], entry['right_min']) != (
        pattern_count, exception_count, 2, 3
    ):
        raise ValueError('Manifest counts or fragment minima do not match the pinned input')
    # Retain the complete source preface, including all original license notices.
    preface = source.split('\\patterns{', 1)[0]
    header = '\n'.join(
        ('// ' + line.removeprefix('%').strip()).rstrip()
        for line in preface.split('\n')
    )
    stem = 'englishUs' if entry['language'] == 'en-US' else 'englishGb'
    output = header + '\n// Generated by tool/proofing/generate_english_hyphenation.py; do not edit.\n'
    output += "const " + stem + "HyphenationPatterns = r'''\n" + '\n'.join(patterns) + "\n''';\n\n"
    output += "const " + stem + "HyphenationExceptions = r'''\n" + '\n'.join(exceptions) + "\n''';\n"
    generated = output.encode('utf-8')
    if hashlib.sha256(generated).hexdigest() != entry['generated_sha256']:
        raise ValueError('Generated output differs from the reviewed manifest')
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify checked-in output without writing')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'third_party/hyphenation/english-manifest.json').read_text())
    if manifest['upstream_commit'] != '5684c0f51c0b81133db2efbe60a408b4155a3ff5':
        raise ValueError('Unreviewed upstream revision')
    if {entry['language'] for entry in manifest['inputs']} != set(PINNED) or len(manifest['inputs']) != 2:
        raise ValueError('Unexpected language inventory')
    receipt = []
    for entry in manifest['inputs']:
        output = generate(entry)
        path = ROOT / entry['generated']
        notice = original_notice(entry)
        notice_path = ROOT / 'third_party/hyphenation' / NOTICES[entry['language']]
        for artifact, expected in [(path, output), (notice_path, notice)]:
            if args.check:
                if not artifact.is_file() or artifact.read_bytes() != expected:
                    raise ValueError(f'Stale generated file: {artifact}')
            else:
                artifact.write_bytes(expected)
        receipt.append({
            'language': entry['language'],
            'patterns': entry['patterns'],
            'exceptions': entry['exceptions'],
            'source_sha256': entry['source_sha256'],
            'generated_sha256': hashlib.sha256(output).hexdigest(),
            'notice': str(notice_path.relative_to(ROOT)),
            'notice_sha256': hashlib.sha256(notice).hexdigest(),
        })
    print(json.dumps({'mode': 'check' if args.check else 'write', 'inputs': receipt}, indent=2))


if __name__ == '__main__':
    main()
