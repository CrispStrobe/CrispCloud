#!/usr/bin/env python3
"""Generate the pinned MIT German lexicon; no dictionary packages are consumed.

Usage (from any directory):
  python generate_german_lexicon.py --source /path/to/wortliste [--check]
  python generate_german_lexicon.py --download [--check]

Reformed (2006) orthography is selected using the database's documented field
layout. Reading every key would incorrectly admit obsolete forms such as Fluß.
The exact mirror is pinned because the canonical host currently has access
restrictions. We do not silently replace this input with its latest revision.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path
import urllib.request
import zlib

REVISION = '4330a0b1254e88615cb4c83e4b3dc2f0810c76d9'
SOURCE_URL = f'https://raw.githubusercontent.com/hyphenation/languages-german/{REVISION}/wortliste'
SOURCE_SHA256 = '55b457fac8e322146853f45bbda59046a55496a3e3deb32d3a88feb908eca243'
PACKAGE = Path(__file__).resolve().parents[2]
DATA = PACKAGE / 'lib/src/proofing/data'
THIRD_PARTY = PACKAGE / 'third_party/proofing'


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def variants(data: bytes) -> tuple[set[str], set[str]]:
    standard: set[str] = set()
    swiss: set[str] = set()
    for line in data.decode('utf-8').splitlines():
        fields = line.split('#', 1)[0].strip().split(';')
        if len(fields) < 2:
            continue
        word = fields[0]
        # Column 2 is shared; otherwise column 4 is modern DE/AT.
        if len(fields) == 2 or len(fields) > 3 and not fields[3].startswith('-'):
            standard.add(word)
        # Column 7 is modern no-sharp-s; column 5 is its shared fallback.
        if (len(fields) == 2 or
            len(fields) > 6 and not fields[6].startswith('-') or
            len(fields) == 5 and not fields[4].startswith('-')):
            swiss.add(word.replace('ß', 'ss').replace('ẞ', 'SS'))
    swiss.update(word.replace('ß', 'ss').replace('ẞ', 'SS') for word in standard)
    swiss = {word for word in swiss if 'ß' not in word and 'ẞ' not in word}
    return standard, swiss


def encode(words: list[str]) -> str:
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    source = ('\n'.join(words) + '\n').encode()
    return base64.b64encode(compressor.compress(source) + compressor.flush()).decode()


def generate(data: bytes) -> dict[Path, bytes]:
    if digest(data) != SOURCE_SHA256:
        raise ValueError('Source hash does not match the pinned MIT word list')
    base, swiss = variants(data)
    supplement_path = PACKAGE / 'tool/proofing/german_common_words.txt'
    supplement = supplement_path.read_bytes()
    common = set(' '.join(line.split('#', 1)[0] for line in supplement.decode().splitlines()).split())
    standard = base | common
    swiss.update(word.replace('ß', 'ss').replace('ẞ', 'SS') for word in common)
    additions = swiss - standard
    assert 'daß' not in standard and 'Fluß' not in standard
    assert 'dass' in standard and 'Fluss' in standard
    assert 'Strasse' not in standard and 'Strasse' in additions
    generated: dict[Path, bytes] = {}
    imports: list[str] = []
    names: dict[str, list[str]] = {'standard': [], 'swiss': [], 'common': []}
    header = ('// GENERATED by tool/proofing/generate_german_lexicon.py.\n'
              '// Pinned MIT data; see third_party/proofing/manifest.json and licenses.\n'
              '// Raw DEFLATE chunks contain sorted UTF-8 word forms. Do not edit.\n')
    # Keep pinned upstream shards unchanged when host-authored supplements grow.
    for kind, word_set in [('standard', base), ('swiss', additions), ('common', common - base)]:
        words = sorted(word_set)
        for shard_start in range(0, len(words), 32768):
            number = shard_start // 32768
            stem = f'german_{kind}_{number:02}'
            name = f'german{kind.title()}Chunks{number}'
            imports.append(f"import '{stem}.dart';")
            names[kind].append(name)
            lines = [header, f'const List<String> {name} = <String>[']
            for chunk_start in range(shard_start, min(shard_start + 32768, len(words)), 4096):
                encoded = encode(words[chunk_start:chunk_start + 4096])
                # Adjacent Dart string literals form one chunk with reviewable lines.
                lines.extend("  '" + encoded[i:i + 100] + "'" for i in range(0, len(encoded), 100))
                lines[-1] += ','
            lines.append('];\n')
            generated[DATA / (stem + '.dart')] = '\n'.join(lines).encode()
    index = [header, *sorted(imports), '', 'const List<String> germanLexiconChunks = <String>[']
    index.extend(f'  ...{name},' for name in names['standard'] + names['common'])
    index.extend(['];', '', 'const List<String> germanSwissLexiconChunks = <String>['])
    index.extend(f'  ...{name},' for name in names['swiss'])
    index.extend(['];', ''])
    generated[DATA / 'german_lexicon_data.dart'] = '\n'.join(index).encode()
    manifest = {
        'schema_version': 1,
        'upstream': {
            'name': "DANTE / Werners Wortliste (hyphenation mirror)",
            'repository': 'https://github.com/hyphenation/languages-german',
            'canonical_repository': 'https://repo.or.cz/wortliste.git',
            'revision': REVISION,
            'source_url': SOURCE_URL,
            'source_sha256': SOURCE_SHA256,
            'license': 'MIT',
            'license_url': f'https://github.com/hyphenation/languages-german/blob/{REVISION}/LICENSE',
            'license_sha256': digest((THIRD_PARTY / 'WORTLISTE_LICENSE').read_bytes()),
            'format_reference': f'https://github.com/hyphenation/languages-german/blob/{REVISION}/skripte/python/edit_tools/wortliste.py',
            'snapshot_date': '2016-05-01',
            'modern_source_forms': len(base),
        },
        'supplement': {
            'path': 'tool/proofing/german_common_words.txt',
            'license': 'MIT',
            'authorship': 'Independently authored Quds Office basic-word supplement, 2026',
            'sha256': digest(supplement),
            'forms': len(common),
            'additional_forms': len(common - base),
        },
        'selection': {
            'standard': 'Shared field 2, otherwise reformed field 4; excludes absent -N- placeholders.',
            'swiss': 'Reformed no-sharp-s field 7 with shared field 5 fallback, plus standard forms with sharp-s replaced by ss; sharp-s forms rejected in de-CH.',
            'scope': 'Finite word forms; no unrestricted compound decomposition or complete morphology. DE and AT share this source vocabulary. The old source snapshot has no claim to contemporary completeness.',
        },
        'data': {
            'standard_count': len(standard),
            'swiss_additions_count': len(additions),
            'standard_sha256': digest(('\n'.join(sorted(standard)) + '\n').encode()),
            'swiss_additions_sha256': digest(('\n'.join(sorted(additions)) + '\n').encode()),
        },
        'encoding': {'format': 'base64 raw DEFLATE of newline-separated UTF-8, <=4096 words/chunk', 'zlib_version': zlib.ZLIB_VERSION},
        'generated_files': {str(path.relative_to(PACKAGE)): digest(value) for path, value in sorted(generated.items())},
    }
    generated[THIRD_PARTY / 'manifest.json'] = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    return generated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument('--source', type=Path)
    inputs.add_argument('--download', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = args.source.read_bytes() if args.source else urllib.request.urlopen(SOURCE_URL, timeout=60).read()
    files = generate(data)
    for path, value in files.items():
        if args.check:
            if not path.exists() or path.read_bytes() != value:
                raise SystemExit(f'Generated output differs: {path.relative_to(PACKAGE)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(value)
    print(f'{"Verified" if args.check else "Wrote"} {len(files)} pinned generated files; source SHA-256 {SOURCE_SHA256}')


if __name__ == '__main__':
    main()
