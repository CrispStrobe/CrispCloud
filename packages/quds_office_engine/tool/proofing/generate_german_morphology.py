#!/usr/bin/env python3
"""Generate a pinned Unicode-3.0 German noun morphology resource.

Use --source-directory DIR for the two actual Git LFS contents and LICENSE,
or --download. --check verifies every generated byte without writing. The
existing modern spelling vocabulary selects lemmas and gates suggestions;
it is never broadened by this generator. Inflections remain analysis data.
"""
from __future__ import annotations

import argparse
import base64
from collections import Counter, defaultdict
import hashlib
import json
import os
from pathlib import Path
import re
import urllib.request
import xml.etree.ElementTree as ET
import zlib

REVISION = '346cf8916249eddc3d5918cfbc27d2b24826ca37'
UPSTREAM = 'https://github.com/unicode-org/inflection'
RESOURCE_PATH = 'resources/org/unicode/inflection/dictionary'
INPUTS = {
    'dictionary_de.lst': ('71570363fc58cab09da0cdf440e3e37083600115467954038ac9b1ff38b062d6', 55993784),
    'inflectional_de.xml': ('0d3df7cbaaad6ef0f7036a961e00273892673df0070c43508fb29bf664fb442d', 1857558),
    'LICENSE': ('b2d3b5d59972767d52997d9f47e67cd30661bcfc3eeb6e3e1ada1ee06634be52', 2033),
}
PACKAGE = Path(__file__).resolve().parents[2]
DATA = PACKAGE / 'lib/src/proofing/data'
NOTICE = PACKAGE / 'third_party/proofing'
CASES = ('nominative', 'accusative', 'dative', 'genitive')
GENDERS = ('masculine', 'feminine', 'neuter')


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_url(name: str) -> str:
    if name == 'LICENSE':
        return f'https://raw.githubusercontent.com/unicode-org/inflection/{REVISION}/LICENSE'
    return f'https://media.githubusercontent.com/media/unicode-org/inflection/{REVISION}/{RESOURCE_PATH}/{name}'


def verify_source(name: str, data: bytes) -> None:
    expected, size = INPUTS[name]
    if data.startswith(b'version https://git-lfs.github.com/spec/'):
        raise ValueError(f'{name} is an LFS pointer; actual source bytes are required')
    if len(data) != size or digest(data) != expected:
        raise ValueError(f'{name}: source size/hash differs from pinned Unicode data')


def decode_chunks(path: Path) -> list[str]:
    # Only the generator's adjacent base64 literals are accepted; no Dart eval.
    blocks = re.findall(r"((?:\s*'[A-Za-z0-9+/=]+'\s*)+),", path.read_text())
    result = []
    for block in blocks:
        encoded = ''.join(re.findall(r"'([^']+)'", block))
        result.extend(zlib.decompress(base64.b64decode(encoded, validate=True), -15).decode().splitlines())
    return result


def spelling_vocabulary() -> tuple[set[str], set[str], dict[str, str]]:
    manifest = json.loads((NOTICE / 'manifest.json').read_text())
    inputs = {}
    standard: set[str] = set()
    additions: set[str] = set()
    for name, expected in manifest['generated_files'].items():
        path = PACKAGE / name
        if digest(path.read_bytes()) != expected:
            raise ValueError(f'Spelling input changed: {name}')
        inputs[name] = expected
        if path.name.startswith(('german_standard_', 'german_common_')):
            standard.update(decode_chunks(path))
        elif path.name.startswith('german_swiss_'):
            additions.update(decode_chunks(path))
    canonical = ('\n'.join(sorted(standard)) + '\n').encode()
    if digest(canonical) != manifest['data']['standard_sha256']:
        raise ValueError('Decoded modern spelling vocabulary hash mismatch')
    swiss = {w.replace('ß', 'ss').replace('ẞ', 'SS') for w in standard} | additions
    return standard, swiss, inputs


def plain_word(word: str) -> bool:
    # Multiword names, digits, symbols and punctuation are outside the token
    # grammar. Keep single ordinary capitalized words (including diacritics).
    return len(word) > 1 and word[0].isupper() and all(c.isalpha() for c in word)


def noun_readings(dictionary: bytes, patterns_xml: bytes, modern: set[str]):
    patterns = {}
    unsafe_patterns = set()
    excluded = Counter()
    for pattern in ET.fromstring(patterns_xml):
        if [p.text for p in pattern.findall('pos')] != ['noun']:
            continue
        # Nominalized adjectives need determiner-dependent declension. Never
        # flatten them into fixed noun paradigms.
        if any(set(i.attrib) - {'case', 'number', 'gender'} or
               i.get('number') == 'singular' and i.get('gender') not in GENDERS
               for i in pattern.findall('./inflections/inflection')):
            excluded['context_dependent_patterns'] += 1
            unsafe_patterns.add(pattern.attrib['name'])
            continue
        suffix = pattern.findtext('suffix') or ''
        inflections = []
        for inflection in pattern.findall('./inflections/inflection'):
            case = inflection.get('case')
            number = inflection.get('number')
            gender = inflection.get('gender')
            t = inflection.find('t')
            if (case not in CASES or number not in ('singular', 'plural') or
                    gender not in (*GENDERS, None) or t is None or
                    len(t) != 1 or t[0].tag != 'stem' or t[0].attrib or
                    t[0].text or (t.text or '')):
                continue
            inflections.append((case, number, gender, t[0].tail or ''))
        if inflections:
            patterns[pattern.attrib['name']] = (suffix, inflections)
    # Dictionary tags aggregate multiple analyses. Corroborate generated
    # forms against the actual source rows instead of treating every unioned
    # nominative tag as permission to seed a new paradigm (Funken -> Funkenn).
    source_tags = {}
    for line in dictionary.decode().splitlines():
        if ': ' in line:
            word, tags = line.rsplit(': ', 1)
            if plain_word(word):
                source_tags[word] = tags
    readings: dict[tuple[str, str, int], list[set[str]]] = {}
    selected = set()
    unresolved = set()
    for word, attributes in source_tags.items():
        tags = set(attributes.split())
        if 'noun' in tags and unsafe_patterns.intersection(t[11:] for t in tags if t.startswith('inflection=')):
            unresolved.add(word)
    for line in dictionary.decode().splitlines():
        if ': ' not in line:
            continue
        lemma, attributes = line.rsplit(': ', 1)
        tags = set(attributes.split())
        plural_only = 'plural' in tags and 'singular' not in tags
        base_number = 'plural' if plural_only else 'singular'
        if (lemma not in modern or not plain_word(lemma) or
                not {'noun', base_number, 'nominative'} <= tags or
                tags & {'proper-noun', 'adjective', 'abbreviation', 'diminutive', 'numeral', 'weak', 'strong', 'mixed'}):
            continue
        references = sorted(t[11:] for t in tags if t.startswith('inflection='))
        if unsafe_patterns.intersection(references):
            excluded['ambiguous_lemma'] += 1
            continue
        for reference in references:
            if reference not in patterns:
                continue
            suffix, inflections = patterns[reference]
            if not lemma.endswith(suffix):
                excluded['suffix_mismatch'] += 1
                continue
            stem = lemma[:-len(suffix)] if suffix else lemma
            # A dictionary row can aggregate several parts of speech/forms.
            # Require the exact candidate lemma to be this pattern's singular
            # nominative; a plural surface must not seed another paradigm.
            base_genders = {g for c, n, g, tail in inflections
                            if c == 'nominative' and n == base_number and stem + tail == lemma
                            and (plural_only or g in tags)}
            if not base_genders:
                excluded['not_pattern_lemma'] += 1
                continue
            groups = defaultdict(lambda: [set() for _ in CASES])
            for case, number, gender, tail in inflections:
                if (plural_only and number != 'plural' or
                        not plural_only and gender not in base_genders):
                    continue
                form = stem + tail
                if not plain_word(form):
                    continue
                corroboration = set(source_tags.get(form, '').split())
                if not {'noun', case, number, 'inflection=' + reference} <= corroboration:
                    excluded['unattested_generated_form'] += 1
                    continue
                genders = [3] if number == 'plural' else [GENDERS.index(gender)]
                for index in genders:
                    groups[index][CASES.index(case)].add(form)
            for gender, forms in groups.items():
                # A partial paradigm cannot establish that a source form is
                # wrong in an unrepresented case. Omit the entire reading.
                if any(not case for case in forms):
                    excluded['incomplete_readings'] += 1
                    continue
                key = (lemma, reference, gender)
                previous = readings.setdefault(key, [set() for _ in CASES])
                for old, new in zip(previous, forms):
                    old.update(new)
                selected.add(lemma)
    # Independently reviewed ordinary-language facts, not imported checker
    # rule tables. Do not generate literary dative-e from spelling alone:
    # even a modern plural ending in e does not establish that case form.
    # The phrase analyzer may abstain in ambiguous literary constructions.
    additions = []
    # Herz has two modern dative singular forms. The pinned upstream only
    # lists Herz. Keep both valid; never force a stylistic choice.
    for (lemma, reference, gender), forms in list(readings.items()):
        if lemma == 'Herz' and gender == 2 and 'Herzen' in modern:
            forms[2].add('Herzen')
            additions.append(('Herz', 'optional-dative', 'Herzen'))
        if lemma == 'Nachbar' and gender == 0:
            forms[1].update({'Nachbar', 'Nachbarn'})
            forms[2].update({'Nachbar', 'Nachbarn'})
            forms[3].update({'Nachbars', 'Nachbarn'})
            additions.append(('Nachbar', 'strong-and-weak-variants', 'Nachbar|Nachbarn|Nachbars'))
        if lemma in ('Assistent', 'Architekt') and gender == 0:
            weak_form = lemma + 'en'
            forms[1] = {weak_form}
            forms[2] = {weak_form}
            forms[3] = {weak_form}
            additions.append((lemma, 'corrected-weak-declension', weak_form))
        extra_gender = 2 if lemma in ('Teil', 'Stift') and gender == 0 else 0 if lemma == 'Bonbon' and gender == 2 else None
        if extra_gender is not None:
            readings[(lemma, reference + '-reviewed-gender', extra_gender)] = [set(case) for case in forms]
            additions.append((lemma, 'alternative-gender', GENDERS[extra_gender]))
    return readings, selected, excluded, additions, unresolved


def encode(lines: list[str]) -> str:
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    return base64.b64encode(compressor.compress(('\n'.join(lines) + '\n').encode()) + compressor.flush()).decode()


def surface_bucket(key: str) -> int:
    """Same bounded UTF-16 rolling hash as Dart, including non-BMP input."""
    encoded = key.encode('utf-16-le')
    value = 0
    for i in range(0, len(encoded), 2):
        value = (value * 31 + encoded[i] + (encoded[i + 1] << 8)) & 255
    return value


def dart_buckets(buckets: list[list[str]], header: str):
    files = {}
    symbols = []
    for offset in range(0, 256, 16):
        number = offset // 16
        stem = f'german_morphology_surfaces_{number:02}'
        symbol = 'germanMorphologySurfaceChunks' + str(number)
        symbols.append((stem, symbol))
        text = [header, f'const List<String> {symbol} = <String>[']
        for lines in buckets[offset:offset + 16]:
            encoded = encode(sorted(lines))
            text.extend("  '" + encoded[i:i + 100] + "'" for i in range(0, len(encoded), 100))
            text[-1] += ','
        text.append('];\n')
        files[DATA / (stem + '.dart')] = '\n'.join(text).encode()
    return files, symbols


def generate(sources: dict[str, bytes]) -> dict[Path, bytes]:
    for name, data in sources.items():
        verify_source(name, data)
    standard, swiss, spelling_inputs = spelling_vocabulary()
    readings, lemmas, excluded, additions, unresolved = noun_readings(sources['dictionary_de.lst'], sources['inflectional_de.xml'], standard)
    templates = {}
    rows = []
    buckets = [[] for _ in range(256)]
    all_forms = set()
    seen_readings = set()
    for (lemma, reference, gender), forms in sorted(readings.items()):
        identity = (lemma, gender, tuple(tuple(sorted(case)) for case in forms))
        if identity in seen_readings:
            continue
        seen_readings.add(identity)
        flattened = sorted(set.union(*forms))
        stem = os.path.commonprefix(flattened)
        endings = tuple('|'.join(sorted(form[len(stem):] for form in case)) for case in forms)
        template = '\t'.join([str(gender), *endings])
        if template not in templates:
            templates[template] = len(templates)
        all_endings = sorted({form[len(stem):] for form in flattened})
        if len(all_endings) > 30:
            raise ValueError('Spelling mask exceeds portable 30-bit budget')
        standard_mask = sum(1 << i for i, tail in enumerate(all_endings) if stem + tail in standard)
        swiss_mask = sum(1 << i for i, tail in enumerate(all_endings) if (stem + tail).replace('ß', 'ss').replace('ẞ', 'SS') in swiss)
        descriptor = '\t'.join([str(len(rows)), lemma, stem, str(templates[template]), str(standard_mask), str(swiss_mask)])
        rows.append(descriptor)
        keys = {f.lower() for f in flattened}
        keys.update(k.replace('ß', 'ss') for k in list(keys))
        for key in sorted(keys):
            buckets[surface_bucket(key)].append(key + '\t' + descriptor)
        all_forms.update(flattened)
    safe_standard = sorted(all_forms & standard)
    safe_swiss = sorted({f.replace('ß', 'ss').replace('ẞ', 'SS') for f in all_forms} & swiss)
    indexed_keys = {f.lower() for f in all_forms}
    indexed_keys.update(k.replace('ß', 'ss') for k in list(indexed_keys))
    unresolved_keys = {w.lower() for w in unresolved if w in standard or w.lower() in indexed_keys}
    unresolved_keys.update(k.replace('ß', 'ss') for k in list(unresolved_keys))
    for key in sorted(unresolved_keys):
        buckets[surface_bucket(key)].append(key + '\t-1\t\t\t\t\t')
    # The complete license accompanies each generated file, so redistribution
    # cannot accidentally strip it by excluding the development directory.
    attribution = ('Derived from Unicode Inflection, revision ' + REVISION + '.\n'
                   'Copyright 2016-2024 Apple Inc. All rights reserved.\n'
                   'Copyright 2024 Unicode, Inc.\n' + sources['LICENSE'].decode())
    header = ('// GENERATED by tool/proofing/generate_german_morphology.py.\n'
              '// Analysis only; does not expand accepted spellings.\n' +
              '\n'.join('// ' + line if line else '//' for line in attribution.splitlines()) + '\n')
    files, symbols = dart_buckets(buckets, header)
    index = [header, *(f"import '{stem}.dart';" for stem, _ in symbols), '', 'const List<String> germanMorphologySurfaceChunks = <String>[']
    index.extend(f'  ...{symbol},' for _, symbol in symbols)
    index.extend(['];', ''])
    index.append('const List<String> germanMorphologyPatterns = <String>[')
    index.extend("  '" + t.replace('\\', '\\\\').replace("'", "\\'").replace('\t', '\\t').replace('$', '\\$') + "'," for t in templates)
    index.extend(['];', '', f'const int germanMorphologyLemmaCount = {len(lemmas)};', f'const int germanMorphologyReadingCount = {len(rows)};', ''])
    files[DATA / 'german_morphology_data.dart'] = '\n'.join(index).encode()
    files[NOTICE / 'UNICODE_INFLECTION_LICENSE'] = sources['LICENSE']
    files[NOTICE / 'UNICODE_INFLECTION_NOTICE'] = attribution.encode()
    manifest = {
        'schema_version': 1,
        'upstream': {'name': 'Unicode Inflection', 'repository': UPSTREAM, 'revision': REVISION,
                     'license': 'Unicode-3.0', 'sources': {name: {'url': source_url(name), 'sha256': sha, 'bytes': size} for name, (sha, size) in INPUTS.items()}},
        'selection': {'lemma': 'Modern spelling allowlist; single capitalized alphabetic singular nominative or plural-only nominative noun; exact pattern nominative and gender match. Proper names, abbreviations and nominalized adjectives excluded.',
                      'analyses': 'Complete fixed noun paradigms only; all explicit genders, numbers and alternative case forms retained. Distinct source patterns remain distinct, including plural senses. Generated forms must be corroborated by matching source case/number/pattern tags. Lemmas with unknown gender or context-dependent declension are omitted.',
                      'corrections': 'Separate standard/Swiss modern spelling intersection gates suggested noun forms. Upstream forms never enlarge spelling acceptance.',
                      'scope': 'Finite lexical morphology, not dependency parsing or a full grammar checker.'},
        'statistics': {'lemmas': len(lemmas), 'readings': len(rows), 'patterns': len(templates), 'surface_forms': len(all_forms), 'unresolved_surface_keys': len(unresolved_keys),
                       'suggestion_safe_standard': len(safe_standard), 'suggestion_safe_swiss': len(safe_swiss), 'excluded': dict(excluded)},
        'validity_additions': [{'lemma': l, 'reason': reason, 'form': f} for l, reason, f in sorted(additions)],
        'review_references': {
            'Herz': 'https://grammis.ids-mannheim.de/fragen/6979',
            'Nachbar': 'https://www.duden.de/deklination/substantive/Nachbar',
            'Assistent': 'https://www.duden.de/deklination/substantive/Assistent',
            'Architekt': 'https://www.duden.de/deklination/substantive/Architekt',
            'Teil': 'https://www.duden.de/rechtschreibung/Teil',
            'Stift': 'https://www.duden.de/rechtschreibung/Stift_Koerperschaft',
            'Bonbon': 'https://www.duden.de/rechtschreibung/Bonbon',
            'literary_dative_limits': 'https://grammis.ids-mannheim.de/fragen/25',
        },
        'spelling_inputs_sha256': spelling_inputs,
        'logical_sha256': digest(('\n'.join(rows) + '\n').encode()),
        'encoding': {'format': 'base64 raw DEFLATE UTF-8 TSV; surface/read-id/lemma/stem/pattern/standard-mask/swiss-mask',
                     'unresolved_reading': 'read-id -1, five empty remaining fields; known unmodeled analyses veto corrections and first-party fallbacks',
                     'buckets': 256, 'hash': 'UTF-16 code units: h=(h*31+unit)&255, h0=0',
                     'mask_order': 'Sorted distinct pattern suffixes; one bit per suffix, max 30 bits',
                     'zlib_version': zlib.ZLIB_VERSION,
                     'max_bucket_rows': max(map(len, buckets)),
                     'max_bucket_utf8_bytes': max(len(('\n'.join(sorted(b)) + '\n').encode()) for b in buckets)},
        'generated_files': {str(p.relative_to(PACKAGE)): digest(b) for p, b in sorted(files.items())},
    }
    files[NOTICE / 'morphology_manifest.json'] = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--source-directory', type=Path)
    source.add_argument('--download', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = {name: (args.source_directory / name).read_bytes() if args.source_directory else urllib.request.urlopen(source_url(name), timeout=120).read() for name in INPUTS}
    files = generate(sources)
    expected = {p.name for p in files if p.parent == DATA}
    unexpected = {p.name for p in DATA.glob('german_morphology_*.dart')} - expected
    if unexpected:
        if args.check:
            raise ValueError(f'Stale generated morphology files: {sorted(unexpected)}')
        for name in sorted(unexpected):
            (DATA / name).unlink()
    for path, data in files.items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Generated output differs: {path.relative_to(PACKAGE)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    manifest = json.loads(files[NOTICE / 'morphology_manifest.json'])
    print(json.dumps({'status': 'verified' if args.check else 'generated', 'files': len(files), **manifest['statistics']}, indent=2))


if __name__ == '__main__':
    main()
