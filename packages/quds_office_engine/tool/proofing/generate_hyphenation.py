#!/usr/bin/env python3
"""Embed reviewed MIT TeX patterns; no network or unreviewed conversion data."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'third_party/hyphenation/hyph-de-1996.tex'
EXPECTED = '374ad1ce3263f8a2791ec070ef9b516c532dae64456f3fb656e617e8ae53a9d3'
raw = SOURCE.read_bytes()
assert hashlib.sha256(raw).hexdigest() == EXPECTED, 'Unreviewed input; inspect license and provenance first'
source = re.sub(r'%[^\n]*', '', raw.decode('utf-8'))
match = re.search(r'\\patterns\{([^}]*)\}', source)
assert match
patterns = match.group(1).split()
assert len(patterns) == 36709
assert all(re.fullmatch(r'[.\wÀ-ž]+', p) for p in patterns)
notice = raw.decode('utf-8').split('% source:')[0]
header = '\n'.join('// ' + line.removeprefix('%').strip() for line in notice.splitlines())
output = header + '\n// Generated by tool/proofing/generate_hyphenation.py; do not edit.\n'
output += "const germanHyphenationPatterns = r'''\n" + '\n'.join(patterns) + "\n''';\n"
path = ROOT / 'lib/src/bidi/german_hyphenation_data.dart'
path.write_text(output, encoding='utf-8')
print(json.dumps({'patterns': len(patterns), 'source_sha256': EXPECTED,
                  'generated_sha256': hashlib.sha256(output.encode()).hexdigest()}, indent=2))
