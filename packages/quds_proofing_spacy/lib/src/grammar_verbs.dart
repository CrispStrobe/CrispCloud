/// Every engine-reviewed or supplementary paradigm containing [surface].
/// Duplicate infinitives are merged (the engine entry wins).
List<GermanReviewedPresentParadigm> spacyPresentParadigms(String surface) {
  final result = <String, GermanReviewedPresentParadigm>{};
  for (final paradigm in GermanPhraseFacts.reviewedPresentParadigms(surface)) {
    result[paradigm.infinitive] = paradigm;
  }
  for (final row in _supplementaryParadigms) {
    if (result.containsKey(row[0])) continue;
    if (row
        .skip(1)
        .any(
          (form) => GermanPhraseFacts.sameForm(form, surface.toLowerCase()),
        )) {
      result[row[0]] = GermanReviewedPresentParadigm(
        infinitive: row[0],
        ich: row[1],
        du: row[2],
        thirdSingular: row[3],
        wir: row[4],
        ihr: row[5],
      );
    }
  }
  return List<GermanReviewedPresentParadigm>.unmodifiable(result.values);
}
