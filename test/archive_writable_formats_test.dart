final _originalTime = DateTime.utc(2025, 2, 3, 4, 5, 6);
final _changedTime = DateTime.utc(2026, 11, 12, 9, 15, 31);

class _WritableCase {
  const _WritableCase(
    this.suffix,
    this.format,
    this.writer, {
    this.compression,
    this.comic = false,
  });

  final String suffix;
  final ArchiveEndpointFormat format;
  final koni.ArchiveWriteFormat writer;
  final ArchiveCompressionKind? compression;
  final bool comic;
}

Future<Uint8List> _fixture(_WritableCase kind) async {
  final sink = koni.BytesBuilderSink();
  final writer = koni.Archive.create(sink, format: kind.writer);
  final files = {
    // Deliberately nonalphabetical: comic page order must survive a rename.
    'folder/original.txt': utf8.encode('original'),
    'keep.txt': [9, 8, 7],
    'remove.txt': [0],
    if (const ['jar', 'war', 'ear'].contains(kind.suffix))
      'META-INF/MANIFEST.MF': utf8.encode('Manifest-Version: 1.0\r\n\r\n'),
    if (kind.suffix == 'kmz')
      'doc.kml': utf8.encode(
        '<kml xmlns="http://www.opengis.net/kml/2.2"><Document/></kml>',
      ),
  };
  for (final entry in files.entries) {
    await writer.addBytes(
      koni.ArchiveEntrySpec(
        path: entry.key,
        modified: _originalTime,
        posixMode: 0x1a0,
      ),
      Uint8List.fromList(entry.value),
    );
  }
  await writer.addEntry(
    koni.ArchiveEntrySpec(
      path: 'empty',
      type: koni.ArchiveEntryType.directory,
      modified: _originalTime,
      posixMode: 0x1e8,
    ),
  );
  await writer.close();
  await sink.close();
  final bytes = sink.takeBytes();
  return kind.compression == null
      ? bytes
      : encodeArchiveCompression(bytes, kind.compression!);
}

class _WorkspaceFixture {
  _WorkspaceFixture(this.client, this.workspace, this.path);
  final ArchiveWorkflowClient client;
  final ArchiveWorkspace workspace;
  final String path;
  Uint8List get saved => client.files[path]!;

  static Future<_WorkspaceFixture> open(String name, Uint8List bytes) async {
    final path = '/$name';
    final client = ArchiveWorkflowClient()..put(path, bytes);
    final backend = ArchiveWorkflowBackend(client, isCurrent: () => true);
    final workspace = await ArchiveWorkspace.open(
      backend,
      (await backend.stat(path))!,
    );
    addTearDown(workspace.close);
    return _WorkspaceFixture(client, workspace, path);
  }

  Future<ViewerArchive> reopen() async {
    final archive = await openViewerArchive(saved, name: workspace.file.name);
    addTearDown(archive.close);
    return archive;
  }

  Future<void> verifyPublished({ArchiveWorkspaceReview? reviewed}) async {
    final receipt = await workspace.save(reviewed: reviewed);
    expect(receipt, isNotNull);
    expect(receipt!.record.phase, ArchivePublicationPhase.complete);
    expect(workspace.dirty, isFalse);
    expect(workspace.canUpdate, isTrue, reason: workspace.updateSupport);
    expect(client.files.keys, [path]);
    expect(workspace.file.path, path);
  }
}

String _name(ViewerArchiveMember member) =>
    member.name.replaceFirst(RegExp(r'/+$'), '');

ViewerArchiveMember _member(ViewerArchive archive, String name) =>
    archive.members.singleWhere((member) => _name(member) == name);

Uint8List _supportedXarFixture() {
  // The historical reader fixture has 20 unrelated trailing bytes. The exact
  // TOC/heap slice is independently generated by libarchive and rewriteable;
  // the complete historical fixture is separately checked as read-only below.
  final bytes = referenceXar();
  return bytes.sublist(0, bytes.length - 20);
}

void main() {
  final cases = [
    const _WritableCase(
      'cbz',
      ArchiveEndpointFormat.zip,
      koni.ZipWriteFormat(),
      comic: true,
    ),
    const _WritableCase(
      'cb7',
      ArchiveEndpointFormat.sevenZip,
      koni.SevenZWriteFormat(),
      comic: true,
    ),
    const _WritableCase(
      'cbt',
      ArchiveEndpointFormat.tar,
      koni.TarWriteFormat(),
      comic: true,
    ),
    const _WritableCase(
      'jar',
      ArchiveEndpointFormat.zip,
      koni.ZipWriteFormat(),
    ),
    const _WritableCase(
      'war',
      ArchiveEndpointFormat.zip,
      koni.ZipWriteFormat(),
    ),
    const _WritableCase(
      'ear',
      ArchiveEndpointFormat.zip,
      koni.ZipWriteFormat(),
    ),
    const _WritableCase(
      'kmz',
      ArchiveEndpointFormat.zip,
      koni.ZipWriteFormat(),
    ),
    for (final suffix in ['tar.gz', 'tgz'])
      _WritableCase(
        suffix,
        ArchiveEndpointFormat.tarGzip,
        const koni.TarWriteFormat(),
        compression: ArchiveCompressionKind.gzip,
      ),
    for (final suffix in ['tar.bz2', 'tar.bzip2', 'tbz2', 'tbz'])
      _WritableCase(
        suffix,
        ArchiveEndpointFormat.tarBzip2,
        const koni.TarWriteFormat(),
        compression: ArchiveCompressionKind.bzip2,
      ),
    for (final suffix in ['tar.xz', 'txz'])
      _WritableCase(
        suffix,
        ArchiveEndpointFormat.tarXz,
        const koni.TarWriteFormat(),
        compression: ArchiveCompressionKind.xz,
      ),
    for (final suffix in ['tar.zst', 'tar.zstd', 'tzst'])
      _WritableCase(
        suffix,
        ArchiveEndpointFormat.tarZstd,
        const koni.TarWriteFormat(),
        compression: ArchiveCompressionKind.zstd,
      ),
  ];

  for (final kind in cases) {
    test(
      '${kind.suffix} stages edits and preserves its format across two saves',
      () async {
        final original = await _fixture(kind);
        final fixture = await _WorkspaceFixture.open(
          'work.${kind.suffix}',
          original,
        );
        final workspace = fixture.workspace;
        expect(workspace.canUpdate, isTrue, reason: workspace.updateSupport);
        expect(workspace.endpointCapabilities.format, kind.format);
        final before = await fixture.reopen();
        final initialOrder = before.members
            .where((m) => m.isFile)
            .map(_name)
            .toList();
        final originalFile = _member(before, 'folder/original.txt');
        final kept = _member(before, 'keep.txt');

        workspace.rename('/folder', 'renamed');
        workspace.replace(
          '/renamed/original.txt',
          Uint8List.fromList([3, 2, 1]),
        );
        workspace.remove(['/remove.txt']);
        workspace.replace(
          '/added.txt',
          Uint8List.fromList(utf8.encode('added')),
          modified: _changedTime,
          mode: 0x180,
        );
        workspace.createDirectory(
          '/new-empty',
          modified: _changedTime,
          mode: 0x1c0,
        );
        expect(workspace.dirty, isTrue);
        expect(fixture.client.writes, isEmpty);
        expect(fixture.saved, original);

        final review = await workspace.review();
        expect(review.changes.map((change) => change.kind).toSet(), {
          ArchiveWorkspaceChangeKind.rename,
          ArchiveWorkspaceChangeKind.replace,
          ArchiveWorkspaceChangeKind.remove,
          ArchiveWorkspaceChangeKind.add,
          ArchiveWorkspaceChangeKind.createDirectory,
        });
        expect(fixture.client.writes, isEmpty);
        await fixture.verifyPublished(reviewed: review);
        expect(archiveCompressionForBytes(fixture.saved), kind.compression);
        final saved = await fixture.reopen();
        expect(saved.formatName, before.formatName);
        final expectedOrder = [
          for (final name in initialOrder)
            if (name != 'remove.txt')
              name == 'folder/original.txt' ? 'renamed/original.txt' : name,
          'added.txt',
        ];
        expect(
          saved.members.where((m) => m.isFile).map(_name).toSet(),
          expectedOrder.toSet(),
        );
        if (kind.comic) {
          expect(
            saved.members.where((m) => m.isFile).map(_name),
            expectedOrder,
            reason: 'Editing a comic must preserve the retained page order.',
          );
        }
        final edited = _member(saved, 'renamed/original.txt');
        expect(await saved.readMember(edited), [3, 2, 1]);
        expect(edited.modified, originalFile.modified);
        expect(edited.posixMode, originalFile.posixMode);
        expect(await saved.readMember(_member(saved, 'keep.txt')), [9, 8, 7]);
        expect(_member(saved, 'keep.txt').modified, kept.modified);
        expect(_member(saved, 'keep.txt').posixMode, kept.posixMode);
        expect(_member(saved, 'empty').isFile, isFalse);
        expect(_member(saved, 'new-empty').isFile, isFalse);
        expect(_member(saved, 'new-empty').posixMode! & 0xfff, 0x1c0);
        expect(_member(saved, 'added.txt').modified, _changedTime);
        expect(_member(saved, 'added.txt').posixMode! & 0xfff, 0x180);
        for (final name in initialOrder.where(
          (name) => name.startsWith('META-INF/') || name.endsWith('.kml'),
        )) {
          expect(
            await saved.readMember(_member(saved, name)),
            await before.readMember(_member(before, name)),
          );
        }

        // A successful save refreshes the inspection and member handles used by
        // the next rewrite, rather than retaining offsets into the old image.
        workspace.replace('/added.txt', Uint8List.fromList([6, 5, 4]));
        await fixture.verifyPublished();
        expect(await workspace.read('/added.txt'), [6, 5, 4]);
        expect(archiveCompressionForBytes(fixture.saved), kind.compression);
      },
    );
  }

  for (final kind in [
    ('gz', ArchiveEndpointFormat.gzip, ArchiveCompressionKind.gzip),
    ('gzip', ArchiveEndpointFormat.gzip, ArchiveCompressionKind.gzip),
    ('bz2', ArchiveEndpointFormat.bzip2, ArchiveCompressionKind.bzip2),
    ('bzip2', ArchiveEndpointFormat.bzip2, ArchiveCompressionKind.bzip2),
    ('xz', ArchiveEndpointFormat.xz, ArchiveCompressionKind.xz),
    ('zst', ArchiveEndpointFormat.zstd, ArchiveCompressionKind.zstd),
    ('zstd', ArchiveEndpointFormat.zstd, ArchiveCompressionKind.zstd),
  ]) {
    test(
      '${kind.$1} replaces exactly one payload without changing its wrapper',
      () async {
        final original = encodeArchiveCompression(
          Uint8List.fromList(utf8.encode('single original payload')),
          kind.$3,
        );
        final fixture = await _WorkspaceFixture.open(
          'payload.txt.${kind.$1}',
          original,
        );
        final workspace = fixture.workspace;
        expect(workspace.canUpdate, isTrue, reason: workspace.updateSupport);
        expect(workspace.endpointCapabilities.format, kind.$2);
        expect(workspace.endpointCapabilities.supportsPermissions, isFalse);
        final name = (await fixture.reopen()).members.single.name;
        final revision = workspace.revision;
        for (final action in <void Function()>[
          () => workspace.rename(name, 'different.txt'),
          () => workspace.remove([name]),
          () => workspace.createDirectory('folder'),
          () => workspace.replace('second.txt', Uint8List.fromList([1])),
          () => workspace.replace(name, Uint8List.fromList([1]), mode: 0x180),
        ]) {
          expect(action, throwsA(isA<ArchiveViewException>()));
          expect(workspace.revision, revision);
          expect(workspace.dirty, isFalse);
          expect(fixture.saved, original);
        }
        workspace.replace(name, Uint8List.fromList([0, 255, 4, 5]));
        await fixture.verifyPublished();
        final saved = await fixture.reopen();
        expect(saved.members.single.name, name);
        expect(await saved.readMember(saved.members.single), [0, 255, 4, 5]);
        expect(archiveCompressionForBytes(fixture.saved), kind.$3);
        if (kind.$3 == ArchiveCompressionKind.gzip) {
          expect(archiveGzipHeader(fixture.saved), archiveGzipHeader(original));
        }
        if (kind.$3 == ArchiveCompressionKind.xz) {
          expect(fixture.saved[7], original[7]);
        }
        workspace.replace(name, Uint8List(0));
        await fixture.verifyPublished();
        expect(await workspace.read(name), isEmpty);
        expect(archiveCompressionForBytes(fixture.saved), kind.$3);
      },
    );
  }

  for (final kind in [
    ('ar', ArchiveEndpointFormat.ar, referenceGnuAr, 'short'),
    ('cpio', ArchiveEndpointFormat.cpio, referenceNewc, 'docs/hello.txt'),
    ('xar', ArchiveEndpointFormat.xar, _supportedXarFixture, 'docs/hello.txt'),
  ]) {
    test(
      '${kind.$1} rewrites an independent package fixture and refreshes metadata',
      () async {
        final fixture = await _WorkspaceFixture.open(
          'work.${kind.$1}',
          kind.$3(),
        );
        final workspace = fixture.workspace;
        expect(workspace.canUpdate, isTrue, reason: workspace.updateSupport);
        expect(workspace.endpointCapabilities.format, kind.$2);
        final original = await fixture.reopen();
        final originalMember = _member(original, kind.$4);
        workspace.rename(kind.$4, 'renamed-日本語.txt');
        workspace.replace('renamed-日本語.txt', Uint8List.fromList([11, 22, 33]));
        workspace.replace(
          'added.bin',
          Uint8List.fromList([44]),
          modified: _changedTime,
          mode: 0x1a0,
        );
        if (kind.$2 != ArchiveEndpointFormat.ar) {
          workspace.createDirectory(
            'empty',
            modified: _changedTime,
            mode: 0x1c0,
          );
        } else {
          final revision = workspace.revision;
          expect(
            () => workspace.createDirectory('empty'),
            throwsA(isA<ArchiveViewException>()),
          );
          expect(
            () => workspace.replace('nested/file', Uint8List(0)),
            throwsA(isA<ArchiveViewException>()),
          );
          expect(workspace.revision, revision);
        }
        await fixture.verifyPublished();
        final saved = await fixture.reopen();
        expect(saved.formatName, original.formatName);
        final renamed = _member(saved, 'renamed-日本語.txt');
        expect(await saved.readMember(renamed), [11, 22, 33]);
        expect(renamed.modified, originalMember.modified);
        expect(renamed.posixMode, originalMember.posixMode);
        expect(_member(saved, 'added.bin').modified, _changedTime);
        expect(_member(saved, 'added.bin').posixMode! & 0xfff, 0x1a0);
        final policy = await ArchiveEndpointPolicy.inspect(
          fixture.saved,
          workspace.file.name,
          saved,
          null,
        );
        expect(policy.reason, isNull);
        expect(policy.inspection!.supported, isTrue);
        workspace.remove(['added.bin']);
        workspace.replace('renamed-日本語.txt', Uint8List.fromList([99]));
        await fixture.verifyPublished();
        expect(await workspace.read('renamed-日本語.txt'), [99]);
        final again = await fixture.reopen();
        expect(again.members.any((m) => _name(m) == 'added.bin'), isFalse);
      },
    );
  }

  for (final kind in [
    ('a', referenceGnuAr, 'symbol index'),
    ('xar', referenceXar, 'trailing data'),
  ]) {
    test('${kind.$1} keeps unpreservable package metadata read-only', () async {
      final original = kind.$2();
      final fixture = await _WorkspaceFixture.open(
        'protected.${kind.$1}',
        original,
      );
      expect(fixture.workspace.canUpdate, isFalse);
      expect(fixture.workspace.updateSupport, contains(kind.$3));
      expect(
        fixture.workspace.endpointCapabilities.supportsMemberWrites,
        isFalse,
      );
      expect(
        () => fixture.workspace.replace('new.txt', Uint8List.fromList([1])),
          throwsUnsupportedError,
      );
      expect(fixture.workspace.dirty, isFalse);
      expect(fixture.client.writes, isEmpty);
      expect(fixture.saved, original);
    });
  }

  test(
    'ISO workspace preserves volume and POSIX metadata through repeated edits',
    () async {
      final iso = IsoFixture(rockRidgeName: 'original-日本語.txt');
      const labelOffset = 16 * IsoFixture.sectorSize + 40;
      iso.bytes.setRange(
        labelOffset,
        labelOffset + 32,
        ascii.encode('KEEP_VOLUME_LABEL'.padRight(32)),
      );
      final fixture = await _WorkspaceFixture.open('data.iso', iso.bytes);
      final workspace = fixture.workspace;
      expect(workspace.canUpdate, isTrue, reason: workspace.updateSupport);
      expect(workspace.endpointCapabilities.format, ArchiveEndpointFormat.iso);
      final original = await fixture.reopen();
      final originalMember = _member(original, 'original-日本語.txt');
      final originalInfo = await inspectIsoRewrite(iso.bytes, original);
      workspace.rename('original-日本語.txt', 'renamed-🌍.txt');
      workspace.replace('renamed-🌍.txt', Uint8List.fromList([1, 2, 3]));
      workspace.remove(['DOCS/NOTE.TXT']);
      workspace.replace(
        'DOCS/added-日本語.txt',
        Uint8List.fromList([7, 8]),
        modified: _changedTime,
        mode: 0x180,
      );
      workspace.createDirectory(
        'new-empty',
        modified: _changedTime,
        mode: 0x1c0,
      );
      await fixture.verifyPublished();
      final saved = await fixture.reopen();
      expect(
        ascii.decode(fixture.saved.sublist(labelOffset, labelOffset + 32)),
        'KEEP_VOLUME_LABEL'.padRight(32),
      );
      final renamed = _member(saved, 'renamed-🌍.txt');
      expect(await saved.readMember(renamed), [1, 2, 3]);
      expect(renamed.modified, originalMember.modified);
      expect(renamed.posixMode, originalMember.posixMode);
      expect(saved.members.any((m) => m.name == 'DOCS/NOTE.TXT'), isFalse);
      expect(_member(saved, 'DOCS/added-日本語.txt').modified, _changedTime);
      expect(_member(saved, 'DOCS/added-日本語.txt').posixMode, 0x8180);
      expect(_member(saved, 'new-empty').posixMode, 0x41c0);
      expect(_member(saved, 'EMPTY').isFile, isFalse);
      final info = await inspectIsoRewrite(fixture.saved, saved);
      expect(info.reason, isNull);
      for (final field in ['iso.uid', 'iso.gid', 'iso.serial']) {
        expect(
          info.attributes[renamed.name]![field],
          originalInfo.attributes[originalMember.name]![field],
        );
      }
      workspace.rename('DOCS', 'renamed-dir');
      workspace.replace('renamed-🌍.txt', Uint8List.fromList([5, 4]));
      await fixture.verifyPublished();
      expect(await workspace.read('renamed-dir/added-日本語.txt'), [7, 8]);
      expect(await workspace.read('renamed-🌍.txt'), [5, 4]);
      expect(
        ascii.decode(fixture.saved.sublist(labelOffset, labelOffset + 32)),
        'KEEP_VOLUME_LABEL'.padRight(32),
      );
    },
  );
}
