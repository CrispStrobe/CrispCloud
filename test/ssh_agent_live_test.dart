/// Real SSHSocket connections and production host-key/authentication handling
/// against disposable OpenSSH servers. Only the local agent socket is replaced
/// by an explicitly in-memory, framed agent-protocol fixture. Its private key
/// is generated by the runner for this invocation and deleted afterward.
///
/// This proves SSH interoperability and authority lifetime, not system-agent,
/// hardware-token or forwarded Unix-socket acceptance. A separate opt-in case
/// below uses an actual disposable ssh-agent when the host permits Unix sockets.
void main() {
  final environment = Platform.environment;
  final keyPath = environment['CRISPCLOUD_LIVE_SSH_KEY'];
  final rsaKeyPath = environment['CRISPCLOUD_LIVE_SSH_RSA_KEY'];
  final jumpPort = int.tryParse(
    environment['CRISPCLOUD_LIVE_SSH_JUMP_PORT'] ?? '',
  );
  final targetPort = int.tryParse(
    environment['CRISPCLOUD_LIVE_SSH_TARGET_PORT'] ?? '',
  );
  final username = environment['CRISPCLOUD_LIVE_SSH_USER'];
  final enabled =
      keyPath != null &&
      rsaKeyPath != null &&
      jumpPort != null &&
      targetPort != null &&
      username != null;

  group(
    'real OpenSSH with an in-memory local-agent protocol fixture',
    () {
      Future<_LiveAgentHarness> harness({bool rsa = false}) async {
        final key = SSHKeyPair.fromPem(
          await File(rsa ? rsaKeyPath! : keyPath!).readAsString(),
        ).single;
        final value = _LiveAgentHarness(key);
        addTearDown(value.service.dispose);
        return value;
      }

      List<SshJumpHost> jumps() => [
        SshJumpHost(
          host: '127.0.0.1',
          port: jumpPort!,
          username: username!,
          authentication: SshTerminalAuthentication.agent,
        ),
      ];

      Future<SshSession> connect(
        _LiveAgentHarness value, {
        bool jump = false,
        bool Function()? isCurrent,
      }) => value.service
          .connectWithAgent(
            '127.0.0.1',
            targetPort!,
            username!,
            jumpHosts: jump ? jumps() : const [],
            isCurrent: isCurrent,
          )
          .timeout(const Duration(seconds: 20));

      void noPasswordFallback(_LiveAgentHarness value) {
        expect(value.suppliedPasswords, everyElement(isNull));
        for (final client in value.clients) {
          expect(client.onPasswordRequest, isNull);
          expect(client.onUserInfoRequest, isNull);
        }
      }

      for (final rsa in [false, true]) {
        final algorithm = rsa ? 'RSA SHA-2' : 'Ed25519';
        final flag = rsa ? SSHAgentProtocol.rsaSha2_512 : 0;

        test(
          '$algorithm waits for host approval before direct signing',
          () async {
            final value = await harness(rsa: rsa);
            final prompted = Completer<void>();
            final approval = Completer<bool>();
            value.prompt = (_, _) {
              prompted.complete();
              return approval.future;
            };
            addTearDown(() {
              if (!approval.isCompleted) approval.complete(false);
            });
            final pending = connect(value);
            await prompted.future.timeout(const Duration(seconds: 10));
            expect(value.signatureRequests, isEmpty);
            expect(value.fixture.requests.map((request) => request.first), [
              11,
            ]);
            approval.complete(true);
            final session = await pending;

            expect(value.events, [
              'list',
              'approve:127.0.0.1:$targetPort',
              'sign:$flag',
            ]);
            expect(value.signatureFlags, [flag]);
            expect(value.clients, hasLength(1));
            noPasswordFallback(value);
            expect(
              await value.service.execute(session.id, "printf 'agent-✓-日本語'"),
              'agent-✓-日本語',
            );
            await value.service.disconnect(session.id);
            expect(value.agents.single.isClosed, isTrue);
            expect(value.fixture.transports.every((t) => t.destroyed), isTrue);
          },
        );

        test(
          '$algorithm signs independently after each verified jump hop',
          () async {
            final value = await harness(rsa: rsa);
            final session = await connect(value, jump: true);
            expect(value.events, [
              'list',
              'approve:127.0.0.1:$jumpPort',
              'sign:$flag',
              'approve:127.0.0.1:$targetPort',
              'sign:$flag',
            ]);
            expect(value.signatureFlags, [flag, flag]);
            expect(value.clients, hasLength(2));
            noPasswordFallback(value);
            expect(
              value.clients.every((client) => client.agentHandler == null),
              isTrue,
            );
            final known = jsonDecode(
              (await value.storage.read('ssh_known_hosts_v1'))!,
            ) as Map;
            expect(known, hasLength(2));
            expect(known.values.toSet(), hasLength(2));
            expect(
              await value.service.execute(session.id, "printf 'agent-jump-✓'"),
              'agent-jump-✓',
            );
          },
        );
      }

      test('session output drains across a live OpenSSH rekey', () async {
        final value = await harness();
        final session = await connect(value, jump: true);
        final client = value.clients.last;
        final channel = await client.execute('cat');
        addTearDown(channel.close);
        final output = channel.stdout.fold<BytesBuilder>(
          BytesBuilder(copy: false),
          (bytes, chunk) => bytes..add(chunk),
        );
        final errors = channel.stderr.fold<BytesBuilder>(
          BytesBuilder(copy: false),
          (bytes, chunk) => bytes..add(chunk),
        );
        final payload = Uint8List.fromList([
          ...utf8.encode('agent-authenticated-rekey-✓-日本語\n'),
          ...List<int>.generate(512 * 1024, (index) => index % 256),
        ]);
        // Initiate the actual key exchange before queuing session input. The
        // session owns its channel's input stream; its normal write/flush path
        // must preserve exact output across rekey. The unit cohort separately
        // holds NEWKEYS and receive windows to prove bounded agent writes wait.
        final rekey = client.rekey();
        channel.write(payload);
        final flushed = channel.flush();
        await Future.wait([rekey, flushed])
            .timeout(const Duration(seconds: 15));
        await channel.stdin.close();
        expect(
          (await output.timeout(const Duration(seconds: 15))).takeBytes(),
          payload,
        );
        expect((await errors).takeBytes(), isEmpty);
        expect(
          await channel.waitForExit(timeout: const Duration(seconds: 5)),
          0,
        );
        expect(value.signatureFlags, [0, 0]);
        expect(value.prompts, ['127.0.0.1:$jumpPort', '127.0.0.1:$targetPort']);
        expect(
          await value.service.execute(session.id, 'printf rekeyed'),
          'rekeyed',
        );
      });

      test('rejecting a real host key never asks the agent to sign', () async {
        final value = await harness();
        value.prompt = (_, _) async => false;
        await expectLater(
          connect(value),
          throwsA(isA<TerminalMountException>()),
        );
        expect(value.prompts, ['127.0.0.1:$targetPort']);
        expect(value.signatureRequests, isEmpty);
        expect(value.agents.single.isClosed, isTrue);
        expect(value.service.getActiveSessions(), isEmpty);
        noPasswordFallback(value);
      });

      test('a changed direct host key fails before any signature', () async {
        final value = await harness();
        final known = {'127.0.0.1:$targetPort': 'SHA256:${'A' * 43}'};
        await value.storage.write('ssh_known_hosts_v1', jsonEncode(known));
        await expectLater(
          connect(value),
          throwsA(isA<TerminalMountException>()),
        );
        expect(value.prompts, isEmpty);
        expect(value.signatureRequests, isEmpty);
        expect(value.agents.single.isClosed, isTrue);
        expect(value.service.getActiveSessions(), isEmpty);
        expect(
          jsonDecode((await value.storage.read('ssh_known_hosts_v1'))!),
          known,
        );
      });

      test(
        'a changed final key signs only for the independently trusted jump',
        () async {
          final value = await harness();
          final rejected = 'SHA256:${'A' * 43}';
          await value.storage.write(
            'ssh_known_hosts_v1',
            jsonEncode({'127.0.0.1:$targetPort': rejected}),
          );
          await expectLater(
            connect(value, jump: true),
            throwsA(isA<TerminalMountException>()),
          );
          expect(value.prompts, ['127.0.0.1:$jumpPort']);
          expect(value.signatureRequests, hasLength(1));
          expect(value.agents.single.isClosed, isTrue);
          expect(value.clients.every((client) => client.isClosed), isTrue);
          expect(value.service.getActiveSessions(), isEmpty);
          expect(
            jsonDecode(
              (await value.storage.read('ssh_known_hosts_v1'))!,
            )['127.0.0.1:$targetPort'],
            rejected,
          );
          noPasswordFallback(value);
        },
      );

      test(
        'a refused agent signature has no password or interactive fallback',
        () async {
          final value = await harness();
          value.refuseSignatures = true;
          await expectLater(
            connect(value),
            throwsA(
              anyOf(isA<TerminalMountException>(), isA<SshAgentException>()),
            ),
          );
          expect(value.signatureRequests, isNotEmpty);
          expect(value.clients, hasLength(1));
          noPasswordFallback(value);
          expect(value.agents.single.isClosed, isTrue);
          expect(value.service.getActiveSessions(), isEmpty);
        },
      );

      test(
        'disconnect revokes a pending local-agent signature on a live route',
        () async {
          final value = await harness();
          final session = await connect(value, jump: true);
          expect(
            await value.service.execute(session.id, 'printf connected'),
            'connected',
          );
          final agent = value.agents.single;
          final retained = (await agent.loadIdentities()).single;
          final signatureStarted = Completer<void>();
          final lateReply = Completer<Uint8List>();
          value.pendingSignature = lateReply;
          value.signatureStarted = signatureStarted;
          final pending = Future<SSHSignature>.sync(
            () => retained.sign(Uint8List.fromList([1, 2, 3, 4])),
          );
          final rejected = expectLater(
            pending,
            throwsA(
              isA<SshAgentException>().having(
                (error) => error.message,
                'message',
                SshAgentException.closed,
              ),
            ),
          );
          await signatureStarted.future.timeout(const Duration(seconds: 2));
          final closing = value.service.disconnect(session.id);
          expect(agent.isClosed, isTrue);
          expect(value.fixture.transports.every((t) => t.destroyed), isTrue);
          await rejected.timeout(const Duration(seconds: 2));
          // A late, otherwise valid device reply cannot regain route authority.
          lateReply.complete(
            await value.fixture.handler.handleRequest(
              value.signatureRequests.last,
            ),
          );
          await closing.timeout(const Duration(seconds: 5));
          final count = value.fixture.requests.length;
          expect(await agent.handleRequest(Uint8List.fromList([11])), [5]);
          await expectLater(
            Future<SSHSignature>.sync(
              () => retained.sign(Uint8List.fromList([5, 6, 7, 8])),
            ),
            throwsA(isA<SshAgentException>()),
          );
          expect(value.fixture.requests.length, count);
          expect(value.service.getActiveSessions(), isEmpty);
        },
      );

      test(
        'cancelling host approval closes authority before a late approval',
        () async {
          final value = await harness();
          final prompted = Completer<void>();
          final approval = Completer<bool>();
          value.prompt = (_, _) {
            prompted.complete();
            return approval.future;
          };
          addTearDown(() {
            if (!approval.isCompleted) approval.complete(false);
          });
          var current = true;
          final pending = connect(value, isCurrent: () => current);
          final rejected = expectLater(pending, throwsStateError);
          await prompted.future.timeout(const Duration(seconds: 10));
          current = false;
          await value.service.disconnectAll();
          expect(value.agents.single.isClosed, isTrue);
          approval.complete(true);
          await rejected;
          expect(value.signatureRequests, isEmpty);
          expect(value.service.getActiveSessions(), isEmpty);
        },
      );
    },
    skip: !enabled
        ? 'Run tool/run_terminal_live_smoke.py for disposable OpenSSH fixtures.'
        : false,
  );

  test(
    'actual disposable Unix ssh-agent authenticates and forwards to ssh-add',
    () async {
      final service = SshTerminalService(
        secureStorage: InMemorySecureStorage(),
        confirmHostKey: (_, _) async => true,
      );
      addTearDown(service.dispose);
      final session = await service
          .connectWithAgent(
            '127.0.0.1',
            targetPort!,
            username!,
            forwardAgent: true,
          )
          .timeout(const Duration(seconds: 20));
      final expected = (await File(
        '$keyPath.pub',
      ).readAsString()).trim().split(RegExp(r'\s+')).take(2).join(' ');
      final forwarded = await service.execute(session.id, 'ssh-add -L');
      expect(forwarded, contains(expected));
      await service.disconnect(session.id);
      expect(service.getActiveSessions(), isEmpty);
    },
    skip: !enabled || environment['CRISPCLOUD_LIVE_UNIX_AGENT'] != '1'
        ? environment['CRISPCLOUD_LIVE_UNIX_AGENT_REASON'] ??
              'Use --with-unix-agent on a host that permits Unix sockets.'
        : false,
  );
}

class _LiveAgentHarness {
  _LiveAgentHarness(SSHKeyPair key) {
    fixture = AgentFixture(
      handler: SSHKeyPairAgent([key], comment: 'disposable loopback agent'),
    );
    fixture.respond = (request) async {
      if (request.first == SSHAgentProtocol.requestIdentities) {
        events.add('list');
      }
      if (request.first == SSHAgentProtocol.signRequest) {
        events.add(
          'sign:${ByteData.sublistView(request).getUint32(request.length - 4)}',
        );
        if (refuseSignatures) return Uint8List.fromList([5]);
        if (pendingSignature case final pending?) {
          if (signatureStarted case final started?) {
            if (!started.isCompleted) started.complete();
          }
          return pending.future;
        }
      }
      return fixture.handler.handleRequest(request);
    };
    service = SshTerminalService(
      secureStorage: storage,
      confirmHostKey: (endpoint, fingerprint) async {
        prompts.add(endpoint);
        final accepted =
            await (prompt?.call(endpoint, fingerprint) ?? Future.value(true));
        if (accepted) events.add('approve:$endpoint');
        return accepted;
      },
      agentFactory: ({required isCurrent}) {
        final agent = fixture.connection(
          current: isCurrent,
          timeout: const Duration(seconds: 5),
        );
        agents.add(agent);
        return agent;
      },
      // Observe credentials/callbacks, retaining the actual production trust
      // implementation and the real SSH socket. No fake SSHClient is used.
      verifiedClientOpener:
          (
            SSHSocket socket, {
            required String username,
            String? password,
            List<SSHIdentity>? identities,
            SSHAgentHandler? agentHandler,
            required FutureOr<bool> Function(String, Uint8List) verify,
            void Function(SSHClient)? onCreated,
          }) {
            suppliedPasswords.add(password);
            return openVerifiedSsh(
              socket,
              username: username,
              password: password,
              identities: identities,
              agentHandler: agentHandler,
              verify: verify,
              onCreated: (client) {
                clients.add(client);
                onCreated?.call(client);
              },
            );
          },
    );
  }

  final storage = InMemorySecureStorage();
  late final AgentFixture fixture;
  late final SshTerminalService service;
  final agents = <SshAgentConnection>[];
  final clients = <SSHClient>[];
  final suppliedPasswords = <String?>[];
  final prompts = <String>[];
  final events = <String>[];
  Future<bool> Function(String endpoint, String fingerprint)? prompt;
  bool refuseSignatures = false;
  Completer<Uint8List>? pendingSignature;
  Completer<void>? signatureStarted;

  List<Uint8List> get signatureRequests => fixture.requests
      .where((request) => request.first == SSHAgentProtocol.signRequest)
      .toList();
  List<int> get signatureFlags => signatureRequests
      .map(
        (request) =>
            ByteData.sublistView(request).getUint32(request.length - 4),
      )
      .toList();
}
