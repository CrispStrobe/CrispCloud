import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import struct
import zipfile


class ForwardOnly(io.BytesIO):
    def seekable(self):
        return False

    def seek(self, *args):
        raise io.UnsupportedOperation("Fixture requires data descriptors")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build(entries, *, descriptors=False, force_zip64=False):
    output = ForwardOnly() if descriptors else io.BytesIO()
    with zipfile.ZipFile(output, "w") as archive:
        for name, data, method in entries:
            entry = zipfile.ZipInfo(name, (2000, 1, 1, 0, 0, 0))
            entry.compress_type = method
            entry.external_attr = 0o100644 << 16
            if force_zip64:
                with archive.open(entry, "w", force_zip64=True) as member:
                    member.write(data)
            else:
                archive.writestr(entry, data)
    return output.getvalue()


def strip_directory(data):
    end = data.rfind(b"PK\x05\x06")
    if end < 0:
        raise ValueError("Missing generated EOCD")
    return data[: struct.unpack_from("<I", data, end + 16)[0]]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stored = b"Stored independent recovery bytes\n"
    deflated = (b"Deflate recovery with PK\x03\x04 inside its actual content.\n" * 128) + bytes(range(256))
    unicode = "Recovered caf\u00e9 and \u96ea\n".encode()
    payloads = {"stored.txt": stored, "deflated.bin": deflated, "caf\u00e9-\u96ea.txt": unicode}
    known = [(name, data, zipfile.ZIP_STORED if name == "stored.txt" else zipfile.ZIP_DEFLATED) for name, data in payloads.items()]
    complete = build(known)
    local = strip_directory(complete)
    descriptor_zip = build([("deflated.bin", deflated, zipfile.ZIP_DEFLATED)], descriptors=True)
    descriptor = strip_directory(descriptor_zip)
    descriptor_at = descriptor.rfind(b"PK\x07\x08")
    assert descriptor_at > 30
    unsigned = descriptor[:descriptor_at] + descriptor[descriptor_at + 4 :]
    stored_descriptor = strip_directory(build([("stored.txt", stored, zipfile.ZIP_STORED)], descriptors=True))
    prefix = strip_directory(build([("stored.txt", stored, zipfile.ZIP_STORED)]))
    damaged = bytearray(strip_directory(build([("deflated.bin", deflated, zipfile.ZIP_DEFLATED)])))
    damaged[14] ^= 0x80  # Known local-header CRC, not arbitrary payload damage.
    duplicate = strip_directory(build([("same.txt", b"first", zipfile.ZIP_STORED), ("same.txt", b"second", zipfile.ZIP_STORED)]))
    unsafe = strip_directory(build([("../outside.txt", b"unsafe", zipfile.ZIP_STORED), ("safe.txt", b"safe", zipfile.ZIP_STORED)]))
    zip64 = strip_directory(build([("stored.txt", stored, zipfile.ZIP_STORED)], force_zip64=True))
    rollover = b"".join(hashlib.sha256(struct.pack("<I", i)).digest() for i in range(900))[:26003]
    rollover_record = strip_directory(build([("rollover.bin", rollover, zipfile.ZIP_DEFLATED)], descriptors=True))
    assert len(rollover_record) > 3 * 8192
    cases = {
        "complete": (complete, list(payloads)),
        "missing-directory": (local, list(payloads)),
        "deflate-signed-descriptor": (descriptor, ["deflated.bin"]),
        "deflate-unsigned-descriptor": (unsigned, ["deflated.bin"]),
        "stored-descriptor-unsupported": (stored_descriptor, []),
        "truncated-final-member": (prefix + local[len(prefix) : -7], ["stored.txt", "deflated.bin"]),
        "bad-crc-after-good": (prefix + damaged, ["stored.txt"]),
        "duplicate-names": (duplicate, []),
        "unsafe-then-safe": (unsafe, ["safe.txt"]),
        "zip64-unsupported": (zip64, []),
        "descriptor-size-mismatch": (descriptor[:-1] + bytes([descriptor[-1] ^ 1]), []),
        "deflate-input-rollover": (rollover_record + prefix, ["rollover.bin", "stored.txt"]),
    }
    manifest = {
        "schema": 1,
        "generator": "Python standard library zipfile; ZIP_STORED and ZIP_DEFLATED, fixed metadata. No library code bundled.",
        "payloads": {name: {"bytes": len(data), "sha256": sha(data)} for name, data in {**payloads, "safe.txt": b"safe", "rollover.bin": rollover}.items()},
        "cases": {name: {"bytes": len(data), "sha256": sha(data), "expected_recoverable_names": expected} for name, (data, expected) in cases.items()},
    }
    dart = ["// Generated by generate_zip_recovery_reference.py; original fixture data.", "// SPDX-License-Identifier: MIT", "import 'dart:convert';", "import 'dart:typed_data';", "", "const zipRecoveryReferenceData = <String, String>{"]
    for name, (data, _) in cases.items():
        encoded = base64.b64encode(data).decode()
        dart.append("  '" + name + "':")
        for pos in range(0, len(encoded), 100):
            dart.append("      '" + encoded[pos : pos + 100] + "'")
        dart[-1] += ","
    dart += ["};", "", "Uint8List zipRecoveryReferenceBytes(String name) =>", "    base64Decode(zipRecoveryReferenceData[name]!);", "", "const zipRecoveryReferenceExpected = <String, List<String>>{"]
    for name, (_, expected) in cases.items():
        dart.append("  '" + name + "': " + json.dumps(expected, ensure_ascii=False) + ",")
    dart += ["};", "", "const zipRecoveryReferencePayloadHashes = <String, String>{"]
    for name, data in {**payloads, "safe.txt": b"safe", "rollover.bin": rollover}.items():
        dart.append("  " + json.dumps(name, ensure_ascii=False) + ":")
        dart.append("      '" + sha(data) + "',")
    dart += ["};", ""]
    outputs = {"archive_zip_recovery_reference_data.dart": "\n".join(dart).encode(), "zip-recovery-reference-manifest.json": (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode()}
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, data in outputs.items():
        target = args.output_dir / name
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                raise SystemExit("Reference reproduction differs: " + name)
        else:
            target.write_bytes(data)
    print(json.dumps({"cases": len(cases), "payloads": len(manifest["payloads"]), "reproduction_check": args.check}))


if __name__ == "__main__":
    main()
