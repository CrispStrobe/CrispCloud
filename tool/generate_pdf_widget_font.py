#!/usr/bin/env python3
"""Embed a real Unicode TTF subset for native and Chrome widget tests.

Requires fontTools 4.61.1. Pass the original upstream editor asset with --source.
The generated Dart file avoids asset platform messages in fake-time tests.
"""

import argparse
import base64
import hashlib
import io
import textwrap
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    args = parser.parse_args()
    source_bytes = args.source.read_bytes()
    font = TTFont(io.BytesIO(source_bytes), recalcTimestamp=False)
    options = subset.Options()
    options.recalc_timestamp = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.name_legacy = True
    options.name_languages = ["*"]
    subsetter = subset.Subsetter(options=options)
    text = "".join(chr(i) for i in range(32, 127)) + (
        "ÄÖÜäöüßéèëÅñŽųŁ€–ЖукМоскваΑθήναשלום")
    subsetter.populate(text=text)
    subsetter.subset(font)
    for record in font["name"].names:
        if record.nameID in (1, 3, 4, 6):
            name = ("CrispWidgetTestSans" if record.nameID == 6
                    else "Crisp Widget Test Sans")
            record.string = name.encode(record.getEncoding())
    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    source_hash = hashlib.sha256(source_bytes).hexdigest()
    fixture_hash = hashlib.sha256(data).hexdigest()
    license_file = ROOT / (
        "packages/pdf_operations/test/fonts/"
        "DejaVuSans-font-metadata-LICENSE.txt")
    notice = "\n".join(
        line.rstrip() for line in license_file.read_text().splitlines()).rstrip()
    chunks = "\n".join(
        f"    '{line}'" for line in textwrap.wrap(
            base64.b64encode(data).decode("ascii"), width=64))
    dart = f"""// Generated by tool/generate_pdf_widget_font.py using fontTools 4.61.1.
// Real DejaVu Sans outlines, renamed and subset for widget tests only.
// Production asset loading and worker serialization are covered separately.
// Source SHA-256: {source_hash}
// Fixture SHA-256: {fixture_hash}
// Original font copyright/license metadata is retained inside the TTF.
/*
{notice}
*/

import 'dart:convert';
import 'dart:typed_data';

ByteData pdfOperationsFontFixture() =>
    ByteData.sublistView(base64Decode(_fontBase64));

const _fontBase64 =
{chunks};
"""
    destination = ROOT / "test/support/pdf_operations_font_fixture.dart"
    destination.write_text(dart)
    print(f"Font bytes: {len(data)}; source SHA-256: {source_hash}")
    print(f"Fixture SHA-256: {fixture_hash}")
    print(destination.relative_to(ROOT))


if __name__ == "__main__":
    main()
